-- Staff invited to set their own password (audit R8 X1-14;
-- docs/architecture/authentication.md#staff-invitations). A manager names the
-- person, their address, where they work and their role; the address is sent
-- a link that works once, for INVITE_DAYS (src/lib/staff-accounts.ts), and
-- only a keyed hash of it is kept, as a password reset's is. Accepting it
-- makes the account with the password the invitee chose, so nobody else ever
-- knows it, and no account exists (or can sign in) before then.
--
-- `admin_id` is set when the invitation is a new address for an account that
-- already exists: accepting moves the account to it, with a password chosen
-- there. Kept after acceptance or withdrawal, with who sent it, for the record.
CREATE TABLE IF NOT EXISTS staff_invitations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id INTEGER REFERENCES admins(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  venue_id INTEGER REFERENCES venues(id) ON DELETE CASCADE,
  business_id INTEGER REFERENCES businesses(id) ON DELETE CASCADE,
  role TEXT NOT NULL DEFAULT 'manager' CHECK (role IN ('manager', 'desk')),
  locale TEXT,
  invited_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  token_hash TEXT NOT NULL UNIQUE,
  expires_at TEXT NOT NULL,
  sent_at TEXT NOT NULL DEFAULT datetime('now'),
  accepted_at TEXT,
  withdrawn_at TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  CHECK (venue_id IS NULL OR business_id IS NULL)
);
CREATE INDEX IF NOT EXISTS idx_staff_invitations_open ON staff_invitations (venue_id, business_id) WHERE accepted_at IS NULL AND withdrawn_at IS NULL;
