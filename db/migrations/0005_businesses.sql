-- A business that owns one or more venues: its branches.
--
-- On a marketplace a staff account used to belong to one venue, so a chain
-- with three branches had three logins, no view across them, and credit a
-- customer bought at one branch that would not spend at the next. Now a staff
-- account belongs to either one branch (venue_id) or a whole business
-- (business_id), and the platform owner to neither.
CREATE TABLE IF NOT EXISTS businesses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);

ALTER TABLE venues ADD COLUMN IF NOT EXISTS business_id INTEGER REFERENCES businesses(id);
CREATE INDEX IF NOT EXISTS idx_venues_business ON venues(business_id);

ALTER TABLE admins ADD COLUMN IF NOT EXISTS business_id INTEGER REFERENCES businesses(id);
ALTER TABLE admins ADD CONSTRAINT admins_one_scope CHECK (venue_id IS NULL OR business_id IS NULL);

-- A new branch asked for by a business already on the platform. Its manager
-- already has an account, so there is no password to keep.
ALTER TABLE venue_applications ADD COLUMN IF NOT EXISTS business_id INTEGER REFERENCES businesses(id);
ALTER TABLE venue_applications ALTER COLUMN password_hash DROP NOT NULL;
