-- Waivers (lib/waivers.ts): a venue's words a customer agrees to before
-- playing. New words are a new version, agreed to afresh.
CREATE TABLE IF NOT EXISTS venue_waivers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  text TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  retired_at TEXT
);
CREATE INDEX IF NOT EXISTS venue_waivers_venue ON venue_waivers (venue_id) WHERE retired_at IS NULL;

-- Who agreed to which version: the venue's record of consent.
CREATE TABLE IF NOT EXISTS waiver_signatures (
  waiver_id INTEGER NOT NULL REFERENCES venue_waivers(id) ON DELETE CASCADE,
  phone_key TEXT NOT NULL,
  name TEXT NOT NULL,
  booking_id INTEGER REFERENCES bookings(id) ON DELETE SET NULL,
  -- Staff who recorded one signed on paper; NULL when the customer ticked it.
  recorded_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  signed_at TEXT NOT NULL DEFAULT datetime('now'),
  PRIMARY KEY (waiver_id, phone_key)
);
