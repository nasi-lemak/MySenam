-- Ratings built from results, and rankings across events (docs/features/tournaments.md#ratings-and-rankings,
-- docs/features/matchmaking.md#earned-levels; ADR 0031; lib/rating-math.ts, lib/ratings.ts).
--
-- The source of truth is a LEDGER of rated results: one row per decided match (a tournament match, a box-league match,
-- a team-league game or a team-league fixture) that a venue marked as rated, with both sides and the outcome. A rating is
-- a pure function of the ledger's live rows in a defined order, recomputed from scratch for the whole pool whenever a
-- row is added or removed; there is no incremental update to drift. Results still enter only through recordResult and
-- the league functions: the ledger is a consumer of them (lib/ratings.ts `syncRatedEvent`), never a scoring path.
-- Ratings are per venue, per sport and per format (singles, doubles, team).

-- The published constants the maths uses, as install data (one row). Changing them raises `version`, and every pool
-- computed under an older version is recomputed from its ledger. No UI edits these: they are an operator's decision.
CREATE TABLE IF NOT EXISTS rating_rules (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  version INTEGER NOT NULL DEFAULT 1,
  rules TEXT NOT NULL,
  updated_at TEXT NOT NULL DEFAULT datetime('now')
);
INSERT INTO rating_rules (id, version, rules) VALUES (1, 1, '{}') ON CONFLICT (id) DO NOTHING;

-- Which events count: a venue's manager marks a tournament, box league or league of teams as rated, before it starts
-- (lib/ratings.ts `setEventRated`). Off by default; a casual open game is never rated.
ALTER TABLE tournaments ADD COLUMN IF NOT EXISTS rated BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE leagues ADD COLUMN IF NOT EXISTS rated BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE team_leagues ADD COLUMN IF NOT EXISTS rated BOOLEAN NOT NULL DEFAULT false;

-- A venue's choice to list its ratings beside its business's other branches on a business-wide board (default no).
CREATE TABLE IF NOT EXISTS venue_rating_settings (
  venue_id INTEGER PRIMARY KEY REFERENCES venues(id) ON DELETE CASCADE,
  business_board BOOLEAN NOT NULL DEFAULT false,
  updated_at TEXT NOT NULL DEFAULT datetime('now')
);

-- What a player chooses about their own rating (all off or 'declared' until they say otherwise, adults only):
-- * level_basis: which level the matcher uses for them: the one they declared (default), the one their rating earns, or either;
-- * rating_shared: the rating (once non-provisional) may be shown, as a number, to the hosts and players matched with them;
-- * rank_publicly / rank_name: listed on a venue's public rankings under the name they give.
-- Children's ratings (participants) have no such choice: they are for the child's guardian only.
ALTER TABLE player_profiles ADD COLUMN IF NOT EXISTS level_basis TEXT NOT NULL DEFAULT 'declared' CHECK (level_basis IN ('declared', 'earned', 'either'));
ALTER TABLE player_profiles ADD COLUMN IF NOT EXISTS rating_shared INTEGER NOT NULL DEFAULT 0;
ALTER TABLE player_profiles ADD COLUMN IF NOT EXISTS rank_publicly INTEGER NOT NULL DEFAULT 0;
ALTER TABLE player_profiles ADD COLUMN IF NOT EXISTS rank_name TEXT;

-- A pool of ratings: one venue, one sport, one format. Its row is the lock a recompute runs under.
CREATE TABLE IF NOT EXISTS rating_pools (
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  sport TEXT NOT NULL REFERENCES activities(key) ON UPDATE CASCADE,
  format TEXT NOT NULL CHECK (format IN ('singles', 'doubles', 'team')),
  rules_version INTEGER NOT NULL DEFAULT 0,
  recomputed_at TEXT,
  PRIMARY KEY (venue_id, sport, format)
);

-- The ledger: one row per decided match. The facts (who, outcome, kind, margin) are never changed: a corrected result is
-- a new row and the old one is voided (`voided_at`), so what was counted when is kept. Columns marked "derived" are the
-- replay's explanation of the row, rewritten on every recompute.
CREATE TABLE IF NOT EXISTS rated_results (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  sport TEXT NOT NULL REFERENCES activities(key) ON UPDATE CASCADE,
  format TEXT NOT NULL CHECK (format IN ('singles', 'doubles', 'team')),
  -- The result it records: a tournament match, a box-league match, a team-league fixture (unit 0 for the teams' result,
  -- the rubber's number for a game of it). `result_ref` is that result's own row.
  source_kind TEXT NOT NULL CHECK (source_kind IN ('tournament', 'league', 'team_league')),
  source_id INTEGER NOT NULL,
  source_match INTEGER NOT NULL,
  unit_no INTEGER NOT NULL DEFAULT 0,
  result_ref INTEGER,
  event_name TEXT NOT NULL,
  played_on TEXT NOT NULL,
  play_order INTEGER NOT NULL DEFAULT 0,
  -- Side a's result: 1 a win, 0.5 a draw, 0 a loss.
  outcome NUMERIC(3,2) NOT NULL CHECK (outcome IN (0, 0.5, 1)),
  kind TEXT NOT NULL DEFAULT 'played' CHECK (kind IN ('played', 'walkover', 'retired')),
  -- The winning margin in goals or points, only where the sport's scoring is a tally; NULL otherwise.
  margin INTEGER,
  -- A fingerprint of the facts and the result rows they come from: a re-read that finds the same fingerprint leaves the row alone.
  fact_hash TEXT NOT NULL,
  weight NUMERIC(4,2),
  margin_factor NUMERIC(4,2),
  side_a_rating NUMERIC(8,2),
  side_b_rating NUMERIC(8,2),
  expected_a NUMERIC(6,5),
  voided_at TEXT,
  voided_reason TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_rated_results_pool ON rated_results (venue_id, sport, format) WHERE voided_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_rated_results_source ON rated_results (source_kind, source_id);
-- One live row per result: a re-read never doubles a result, however often or from however many servers it runs.
CREATE UNIQUE INDEX IF NOT EXISTS uq_rated_results_live ON rated_results (source_kind, source_id, source_match, unit_no) WHERE voided_at IS NULL;

-- Who was on each side of a rated result. A person is an account ('user') or a participant a guardian manages
-- ('participant', a child: for the child's guardian only); a team is a persistent team ('team'). A subject erased from the
-- install becomes 'removed': its name goes, and the rating it had then (`frozen_rating`) stays, so the others' ratings do not move.
CREATE TABLE IF NOT EXISTS rated_result_subjects (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  result_id INTEGER NOT NULL REFERENCES rated_results(id) ON DELETE CASCADE,
  side TEXT NOT NULL CHECK (side IN ('a', 'b')),
  subject_kind TEXT NOT NULL CHECK (subject_kind IN ('user', 'participant', 'team', 'removed')),
  subject_id INTEGER,
  -- As the event showed them.
  label TEXT NOT NULL,
  frozen_rating NUMERIC(8,2),
  rating_before NUMERIC(8,2),
  rating_after NUMERIC(8,2),
  k NUMERIC(6,2),
  games_before INTEGER,
  CHECK ((subject_kind = 'removed') = (subject_id IS NULL))
);
CREATE INDEX IF NOT EXISTS idx_rated_result_subjects_result ON rated_result_subjects (result_id);
CREATE INDEX IF NOT EXISTS idx_rated_result_subjects_subject ON rated_result_subjects (subject_kind, subject_id) WHERE subject_id IS NOT NULL;

-- Where each subject stands in a pool now: the last replay's outcome (derived), with the record that counts.
CREATE TABLE IF NOT EXISTS rating_subjects (
  venue_id INTEGER NOT NULL,
  sport TEXT NOT NULL,
  format TEXT NOT NULL,
  subject_kind TEXT NOT NULL CHECK (subject_kind IN ('user', 'participant', 'team')),
  subject_id INTEGER NOT NULL,
  rating NUMERIC(8,2) NOT NULL,
  games INTEGER NOT NULL DEFAULT 0,
  wins INTEGER NOT NULL DEFAULT 0,
  draws INTEGER NOT NULL DEFAULT 0,
  losses INTEGER NOT NULL DEFAULT 0,
  last_played_on TEXT,
  PRIMARY KEY (venue_id, sport, format, subject_kind, subject_id),
  FOREIGN KEY (venue_id, sport, format) REFERENCES rating_pools (venue_id, sport, format) ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_rating_subjects_subject ON rating_subjects (subject_kind, subject_id);

-- Which events have been read into the ledger, and the fingerprint of their results when they were: the scheduled
-- catch-up re-reads an event only when its results differ from that.
CREATE TABLE IF NOT EXISTS rating_syncs (
  source_kind TEXT NOT NULL CHECK (source_kind IN ('tournament', 'league', 'team_league')),
  source_id INTEGER NOT NULL,
  fingerprint TEXT NOT NULL,
  synced_at TEXT NOT NULL DEFAULT datetime('now'),
  PRIMARY KEY (source_kind, source_id)
);

-- A manager leaving one result out of the ratings, with the reason; the exclusion belongs to the result, so it survives a
-- correction of it. Lifting it is logged too.
CREATE TABLE IF NOT EXISTS rating_exclusions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  source_kind TEXT NOT NULL CHECK (source_kind IN ('tournament', 'league', 'team_league')),
  source_id INTEGER NOT NULL,
  source_match INTEGER NOT NULL,
  unit_no INTEGER NOT NULL DEFAULT 0,
  reason TEXT NOT NULL,
  by_name TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  lifted_at TEXT,
  lifted_reason TEXT,
  lifted_by_name TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_rating_exclusions_active ON rating_exclusions (source_kind, source_id, source_match, unit_no) WHERE lifted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_rating_exclusions_venue ON rating_exclusions (venue_id);

-- A manager restarting a subject's rating at a venue: results up to `cutoff_key` (the order key of the subject's last
-- result then) stay in the ledger and still count for the people who played them, but the subject's own rating and record
-- start again from the starting rating after them.
CREATE TABLE IF NOT EXISTS rating_resets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  sport TEXT NOT NULL,
  format TEXT NOT NULL,
  subject_kind TEXT NOT NULL CHECK (subject_kind IN ('user', 'participant', 'team')),
  subject_id INTEGER NOT NULL,
  cutoff_key TEXT NOT NULL,
  reason TEXT NOT NULL,
  by_name TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_rating_resets_subject ON rating_resets (subject_kind, subject_id);
CREATE INDEX IF NOT EXISTS idx_rating_resets_pool ON rating_resets (venue_id, sport, format);
