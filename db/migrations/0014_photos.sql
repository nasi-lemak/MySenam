-- Venue photos (lib/photos.ts). The pictures themselves are files, in a
-- bucket or the data folder (lib/photo-store.ts); this says whose they are
-- and in what order.

CREATE TABLE IF NOT EXISTS venue_photos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  -- The stored files are `<key>-400.webp`, `-800` and `-1600`.
  key TEXT NOT NULL UNIQUE,
  -- Of the largest version, so a page can hold the space before it loads.
  width INTEGER NOT NULL,
  height INTEGER NOT NULL,
  -- Its main colour, shown while it loads.
  color TEXT NOT NULL,
  caption TEXT,
  -- 0 is the cover.
  position INTEGER NOT NULL,
  created_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_venue_photos_venue ON venue_photos(venue_id, position);
