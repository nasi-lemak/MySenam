-- Company and school accounts (lib/accounts.ts): an organisation that books
-- through the month and pays once, on an invoice. Its people book in their own
-- names; the bookings are charged to the account, and invoiced together.
CREATE TABLE IF NOT EXISTS venue_accounts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  contact TEXT,
  -- Where the invoices go.
  email TEXT NOT NULL,
  address TEXT,
  -- Its registration or tax number, for the invoice.
  tax_no TEXT,
  -- Days to pay an invoice.
  terms_days INTEGER NOT NULL DEFAULT 30 CHECK (terms_days BETWEEN 0 AND 90),
  -- The most it may owe at once, invoiced or not; NULL for no limit.
  credit_limit NUMERIC(12,2),
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  closed_at TEXT
);
CREATE INDEX IF NOT EXISTS venue_accounts_venue ON venue_accounts (venue_id);

-- Who may charge a booking to it themselves: a number the venue was given,
-- which the person proves on their own account (users.verified_phone).
CREATE TABLE IF NOT EXISTS account_bookers (
  account_id INTEGER NOT NULL REFERENCES venue_accounts(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  phone_key TEXT GENERATED ALWAYS AS (phone_key(phone)) STORED,
  PRIMARY KEY (account_id, phone_key)
);

CREATE TABLE IF NOT EXISTS account_invoices (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id INTEGER NOT NULL REFERENCES venue_accounts(id) ON DELETE CASCADE,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  -- The month it is for, YYYY-MM.
  period TEXT NOT NULL,
  issued_on TEXT NOT NULL,
  due_on TEXT NOT NULL,
  total NUMERIC(12,2) NOT NULL,
  -- Of the total, the venue's SST or GST, which its prices include.
  tax_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  -- Behind the link in the email to the account, which needs no sign-in.
  token TEXT NOT NULL UNIQUE,
  paid_on TEXT,
  paid_via TEXT CHECK (paid_via IN ('cash', 'qr', 'transfer', 'card'))
);
CREATE INDEX IF NOT EXISTS account_invoices_account ON account_invoices (account_id, period);

ALTER TABLE bookings ADD COLUMN IF NOT EXISTS account_id INTEGER REFERENCES venue_accounts(id) ON DELETE SET NULL;
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS account_invoice_id INTEGER REFERENCES account_invoices(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_bookings_account ON bookings (account_id, date) WHERE account_id IS NOT NULL;
