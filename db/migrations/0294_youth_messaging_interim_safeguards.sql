-- Youth messaging: interim safeguards prepared for legal review (docs/features/player-messages.md#interim-safeguards-pending-legal-review;
-- docs/operations/legal-review-youth-messaging.md; ADR 0052, which amends ADR 0049 and ADR 0044; lib/youth-launch.ts, lib/youth-authority.ts,
-- lib/youth-restrictions.ts, lib/youth-evidence.ts).
--
-- The owner approved an interim product and safety direction, subject to review by qualified Malaysian legal and child-safeguarding professionals
-- before live youth messaging is enabled. Nothing here settles a legal question: every status, standard and period below is operational and
-- labelled "pending legal review". No custody document, identity number or other document is collected or stored.

-- ---------------------------------------------------------------- 2. custody and authority: a recorded decision with its basis, status, restrictions

-- What an operator recorded about this guardian link. `authority_status`: `asserted` is the default and means only what the guardian or the venue declared
-- when the link was made (not a legal determination); `verified` means an authorised operator recorded a verified authority decision; `disputed` and
-- `unclear` keep youth messaging off for the child. `authority_basis` is a short fixed list (no documents, no narrative). `authority_restrictions` is what
-- the decision removes from the guardian's say: it takes effect (as `messaging_authority`, which stays the one place every rule reads) only on a verified
-- decision; an asserted one sets the link to `unclear` instead. `authority_standard` is the constant 'interim: pending legal review' next to who and when
-- (`messaging_authority_by`, `messaging_authority_at`, and the short digit-safe note `messaging_authority_note` that already existed).
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS authority_status TEXT NOT NULL DEFAULT 'asserted' CHECK (authority_status IN ('asserted', 'verified', 'disputed', 'unclear'));
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS authority_basis TEXT NOT NULL DEFAULT 'not_stated' CHECK (authority_basis IN ('parent', 'legal_guardian', 'other_authorised', 'not_stated'));
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS authority_restrictions TEXT NOT NULL DEFAULT 'none' CHECK (authority_restrictions IN ('none', 'may_object_only', 'no_messaging_say'));
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS authority_standard TEXT;

-- A restriction recorded before this migration was the venue's word and nothing more (ADR 0049): it is now an asserted restriction, which does not take
-- effect and sets the link to `unclear`, so that the child's messaging stays off until an authorised operator records a decision. (Only a legacy row matches: a row
-- this migration or a later decision already wrote has another status, so running it again changes nothing.)
UPDATE participant_guardians
   SET authority_restrictions = CASE messaging_authority WHEN 'objects_only' THEN 'may_object_only' ELSE 'no_messaging_say' END,
       authority_status = 'unclear',
       messaging_authority = 'decides'
 WHERE messaging_authority <> 'decides' AND authority_status = 'asserted' AND authority_restrictions = 'none';

-- One authority review for a child and a group at a time: opened when a link becomes `disputed` or `unclear`, or a guardian conflict stays unresolved
-- beyond YOUTH_REVIEW_DAYS (an operational period, not a legal one). For safeguarding administrators only.
CREATE TABLE IF NOT EXISTS youth_authority_reviews (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id INTEGER NOT NULL REFERENCES community_groups(id) ON DELETE CASCADE,
  minor_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  cause TEXT NOT NULL CHECK (cause IN ('disputed', 'unclear', 'conflict_unresolved')),
  opened_at TEXT NOT NULL DEFAULT datetime('now'),
  closed_at TEXT,
  outcome TEXT CHECK (outcome IS NULL OR outcome IN ('resolved', 'remains_unclear')),
  closed_by TEXT,
  close_reason TEXT,
  escalated_at TEXT,
  escalated_by TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_youth_authority_reviews_open ON youth_authority_reviews (group_id, minor_user_id) WHERE closed_at IS NULL;

-- ---------------------------------------------------------------- 3. a restriction on an adult: protective or a decision, reviewed, appealable

-- `kind`: a protective restriction is temporary and not a finding; a decision is a moderator's recorded outcome with its reason. `review_by`: a protective
-- restriction passing it unreviewed is escalated to the platform's owner and never lifted or converted by itself (YOUTH_PROTECTIVE_REVIEW_DAYS, operational,
-- not a legal period). Only a restriction a report placed (`source = 'report'`) has either; a supervisor's pause is as it was.
ALTER TABLE youth_thread_mutes ADD COLUMN IF NOT EXISTS kind TEXT NOT NULL DEFAULT 'protective' CHECK (kind IN ('protective', 'decision'));
ALTER TABLE youth_thread_mutes ADD COLUMN IF NOT EXISTS review_by TEXT;
ALTER TABLE youth_thread_mutes ADD COLUMN IF NOT EXISTS last_reviewed_at TEXT;
ALTER TABLE youth_thread_mutes ADD COLUMN IF NOT EXISTS last_reviewed_by TEXT;
ALTER TABLE youth_thread_mutes ADD COLUMN IF NOT EXISTS overdue_notified_at TEXT;
ALTER TABLE youth_thread_mutes ADD COLUMN IF NOT EXISTS decision_outcome TEXT CHECK (decision_outcome IS NULL OR decision_outcome IN ('removed_from_group', 'messaging_suspended'));
ALTER TABLE youth_thread_mutes ADD COLUMN IF NOT EXISTS decision_reason TEXT;
ALTER TABLE youth_thread_mutes ADD COLUMN IF NOT EXISTS decided_by TEXT;
ALTER TABLE youth_thread_mutes ADD COLUMN IF NOT EXISTS decided_at TEXT;

-- The restricted adult's request for a review, made from the neutral line (the same for every cause): one short text, no details of any report are shown or
-- asked. It is decided by somebody other than whoever applied the restriction; the adult is told only that it was received and, when decided, the outcome.
CREATE TABLE IF NOT EXISTS youth_restriction_appeals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mute_id INTEGER NOT NULL REFERENCES youth_thread_mutes(id) ON DELETE CASCADE,
  group_id INTEGER NOT NULL REFERENCES community_groups(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  message TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'decided')),
  outcome TEXT CHECK (outcome IS NULL OR outcome IN ('lifted', 'continues')),
  decided_by TEXT,
  decided_at TEXT,
  decision_reason TEXT,
  decision_text TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_youth_restriction_appeals_open ON youth_restriction_appeals (mute_id) WHERE status = 'open';
CREATE INDEX IF NOT EXISTS idx_youth_restriction_appeals_user ON youth_restriction_appeals (user_id, id);

-- ---------------------------------------------------------------- 4. legal holds on evidence

-- A legal hold on a child and group (every youth report of that group and its conversation), or on one case: set and released by the platform's owner only,
-- with a reason, an external reference (a short digit-safe text) and an optional review date. While one is in force retention and erasure leave the covered
-- evidence copy and the conversation alone. The record has no foreign keys on purpose: it must outlive the account or the report it protects.
CREATE TABLE IF NOT EXISTS youth_evidence_holds (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope_kind TEXT NOT NULL CHECK (scope_kind IN ('child_group', 'case')),
  group_id INTEGER NOT NULL,
  minor_user_id INTEGER,
  report_id INTEGER,
  reason TEXT NOT NULL,
  reference TEXT,
  created_by TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  review_on TEXT,
  last_reviewed_at TEXT,
  released_at TEXT,
  released_by TEXT,
  release_reason TEXT,
  CHECK ((scope_kind = 'case' AND report_id IS NOT NULL) OR (scope_kind = 'child_group' AND minor_user_id IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_youth_evidence_holds_live ON youth_evidence_holds (group_id) WHERE released_at IS NULL;

-- ---------------------------------------------------------------- audit records are append-only

-- What was done about a report, and what was done about a youth group and its people, is never edited: a row can be added, and is deleted only with its
-- case under an install's own SAFEGUARDING_EVIDENCE_RETENTION_DAYS (or with the group it belongs to).
-- (A foreign key's own SET NULL, when an account is erased, is not an edit of what was recorded and is let through.)
CREATE OR REPLACE FUNCTION youth_report_actions_no_edit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (NEW.report_id, NEW.group_id, NEW.action, NEW.actor_name, NEW.detail, NEW.created_at) IS DISTINCT FROM (OLD.report_id, OLD.group_id, OLD.action, OLD.actor_name, OLD.detail, OLD.created_at) THEN
    RAISE EXCEPTION 'A safeguarding audit record is not edited.';
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS youth_report_actions_no_edit ON youth_report_actions;
CREATE TRIGGER youth_report_actions_no_edit BEFORE UPDATE ON youth_report_actions FOR EACH ROW EXECUTE FUNCTION youth_report_actions_no_edit();

CREATE OR REPLACE FUNCTION youth_message_events_no_edit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (NEW.group_id, NEW.actor_kind, NEW.action, NEW.detail, NEW.created_at) IS DISTINCT FROM (OLD.group_id, OLD.actor_kind, OLD.action, OLD.detail, OLD.created_at) THEN
    RAISE EXCEPTION 'A safeguarding audit record is not edited.';
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS youth_message_events_no_edit ON youth_message_events;
CREATE TRIGGER youth_message_events_no_edit BEFORE UPDATE ON youth_message_events FOR EACH ROW EXECUTE FUNCTION youth_message_events_no_edit();
