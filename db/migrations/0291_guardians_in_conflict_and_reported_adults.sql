-- Guardians in conflict, and a reported adult who is not told (docs/features/player-messages.md#supervised-youth-groups; ADR 0049, which
-- amends ADR 0044; lib/youth-consent.ts, lib/youth-messages.ts, lib/youth-report-cases.ts).
--
-- The owner's decisions of 5 November 2026:
--   1. Any guardian with authority may switch a minor's group messaging off, and another guardian may not unilaterally switch it back on.
--      Authority is data per guardian link, not assumed equal; an objection holds until every guardian who decides has agreed again, or a
--      safeguarding administrator settles it, with a reason. Everything for one child and group serialises on one lock.
--   2. A report in a youth thread is not told to the reported adult by any channel. Their seat is protectively restricted at once (not a
--      finding), the report goes only to safeguarding personnel, the evidence is held, and a moderator decides what, if anything, to tell
--      them later.
-- The venue's recording of what it was shown is the venue's word, applied and recorded, never verified by the app; no documents and no
-- identity numbers are kept.

-- ---------------------------------------------------------------- decision 1: authority per guardian link

-- What this guardian may do about the child's group messaging: `decides` (may consent to it and object to it: every existing link), `objects_only`
-- (may switch it off, never counts towards restoring it), `none` (no say in messaging at all). Set by a venue's manager or the platform's owner
-- (lib/youth-safeguarding.ts), with who and when and a short free-text note, visible to managers and the owner only. As declared by the venue.
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS messaging_authority TEXT NOT NULL DEFAULT 'decides' CHECK (messaging_authority IN ('decides', 'objects_only', 'none'));
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS messaging_authority_by TEXT;
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS messaging_authority_at TEXT;
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS messaging_authority_note TEXT CHECK (messaging_authority_note IS NULL OR length(messaging_authority_note) <= 200);

-- One row per child and group, taken `FOR UPDATE` by every consent change, objection, level change and resolution, and `FOR SHARE` by a message
-- being written (before any other row it takes, so the two never wait for each other in a circle). Nothing else is kept here.
CREATE TABLE IF NOT EXISTS youth_consent_locks (
  group_id INTEGER NOT NULL REFERENCES community_groups(id) ON DELETE CASCADE,
  minor_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (group_id, minor_user_id)
);

-- A guardian's switch-off for one child in one group. While one is open no consent counts unless every guardian who decides has a live consent
-- (every consent in force when it opened was ended with it, so a live one is one given after). It closes by agreement ('agreed'), or by a
-- safeguarding administrator with a reason ('admin'). Who objected is for safeguarding administrators and the audit only.
CREATE TABLE IF NOT EXISTS youth_message_objections (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id INTEGER NOT NULL REFERENCES community_groups(id) ON DELETE CASCADE,
  minor_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  participant_id INTEGER REFERENCES participants(id) ON DELETE SET NULL,
  guardian_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  level_at_time TEXT NOT NULL CHECK (level_at_time IN ('decides', 'objects_only')),
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  closed_at TEXT,
  close_kind TEXT CHECK (close_kind IS NULL OR close_kind IN ('agreed', 'admin')),
  closed_by TEXT,
  close_reason TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_youth_message_objections_open ON youth_message_objections (group_id, minor_user_id) WHERE closed_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_youth_message_objections_group ON youth_message_objections (group_id) WHERE closed_at IS NULL;

-- ---------------------------------------------------------------- decision 2: a report is not told to the reported adult

-- A report a venue's conflicted staff could not take (the reported person is staff there) or a moderator escalated: the platform's owner sees it
-- as well. Escalating is recorded, never automatic except for that conflict.
ALTER TABLE player_message_reports ADD COLUMN IF NOT EXISTS escalated_at TEXT;
ALTER TABLE player_message_reports ADD COLUMN IF NOT EXISTS escalated_by TEXT;
ALTER TABLE player_message_reports ADD COLUMN IF NOT EXISTS escalation_reason TEXT;

-- A report dealt with by leaving the protective restriction in place is a third outcome (the first two are in migration 0280).
ALTER TABLE player_message_reports DROP CONSTRAINT IF EXISTS player_message_reports_outcome_check;
ALTER TABLE player_message_reports ADD CONSTRAINT player_message_reports_outcome_check CHECK (outcome IS NULL OR outcome IN ('no_action', 'action_taken', 'restriction_continues'));

-- What safeguarding personnel did about a report in a youth thread: read the evidence, confirmed, extended or lifted the restriction, escalated,
-- wrote a note, wrote the one notification the reported adult is ever sent, reviewed. Who, what, when and why: never the text of a message.
-- Kept apart from the staff activity log, which a reported member of staff can read. Deleted with the report, after its retention.
CREATE TABLE IF NOT EXISTS youth_report_actions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id INTEGER NOT NULL,
  group_id INTEGER NOT NULL REFERENCES community_groups(id) ON DELETE CASCADE,
  action TEXT NOT NULL,
  actor_name TEXT NOT NULL,
  detail TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_youth_report_actions_report ON youth_report_actions (report_id, id);
