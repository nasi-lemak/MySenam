-- Notices (lib/notices.ts): a venue's own — an event, a promotion — shown on
-- its own page and storefront, never on the marketplace's front page; and
-- the platform owner's one site-wide notice (venue_id NULL), for what
-- concerns everybody: a government programme, a large collaboration.

CREATE TABLE IF NOT EXISTS notices (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER REFERENCES venues(id) ON DELETE CASCADE,
  text TEXT NOT NULL CHECK (char_length(text) BETWEEN 3 AND 160),
  -- A page on this site, or nothing: never somewhere else.
  link TEXT CHECK (link IS NULL OR (link LIKE '/%' AND link NOT LIKE '//%')),
  starts_on TEXT NOT NULL,
  ends_on TEXT NOT NULL,
  created_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  CHECK (ends_on >= starts_on)
);
CREATE INDEX IF NOT EXISTS idx_notices_venue ON notices(venue_id, ends_on);
