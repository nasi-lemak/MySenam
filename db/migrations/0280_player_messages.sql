-- Messages between players, inside a context they already share (docs/features/player-messages.md; ADR 0039; lib/messages.ts).
--
-- A thread belongs to one context (an open game, a team, a community group, or a fixture a person is in) and ends with it. There
-- is no thread between two strangers and none started by an address: the only way a thread begins is a first message written in a
-- context the writer is a member of. The tables are named `player_message*` because `messages` is the outbox (lib/outbox.ts).
-- Nothing here is public, in the venue API or in the MCP tools; a venue reads a message only inside a report about it.

-- Whether somebody lets people they play with write to them. Off until the person turns it on, and never turned on by joining a
-- game; `explained_at` is the day they saw the first screen (what it is, that it shows no phone or email, how to block and report).
CREATE TABLE IF NOT EXISTS player_message_settings (
  user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  enabled INTEGER NOT NULL DEFAULT 0 CHECK (enabled IN (0, 1)),
  -- An email saying "you have a message in ..." (never the text), at most one per thread per period and a few a day.
  email_notices INTEGER NOT NULL DEFAULT 1 CHECK (email_notices IN (0, 1)),
  explained_at TEXT,
  enabled_at TEXT,
  updated_at TEXT NOT NULL DEFAULT datetime('now')
);

-- One thread per context, made by the first message. `ended_at` is when the context was first seen to be over (a game played or
-- called off, a team archived, a fixture decided): the thread is then read-only for 14 days and closed, and kept for the install's
-- retention period after that (MESSAGE_RETENTION_DAYS, 90 by default). `staff_state` is a moderator's: muted (nobody may write,
-- undone by a manager) or closed (for good).
CREATE TABLE IF NOT EXISTS player_message_threads (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  context_kind TEXT NOT NULL CHECK (context_kind IN ('game', 'team', 'group', 'tournament_match', 'league_match', 'ladder_challenge', 'team_fixture')),
  context_id INTEGER NOT NULL,
  -- The venue the context belongs to, as it was when the thread began; NULL for a group, or a team with no venue.
  venue_id INTEGER REFERENCES venues(id) ON DELETE SET NULL,
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  last_message_at TEXT,
  message_count INTEGER NOT NULL DEFAULT 0,
  ended_at TEXT,
  staff_state TEXT NOT NULL DEFAULT 'open' CHECK (staff_state IN ('open', 'muted', 'closed')),
  staff_reason TEXT,
  staff_admin_name TEXT,
  staff_at TEXT,
  UNIQUE (context_kind, context_id)
);
CREATE INDEX IF NOT EXISTS idx_player_message_threads_venue ON player_message_threads (venue_id) WHERE venue_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_player_message_threads_ended ON player_message_threads (ended_at) WHERE ended_at IS NOT NULL;

-- A message. `body` is NULL (and `removed_at` set) once its sender's account is erased: the other side's messages stay for them.
-- `sender_label` is how the sender showed in the context when they wrote: a first name, or "Guardian of Aina L." for a guardian
-- (a child's short name only, never a full name, ADR 0039), and cleared with the body.
CREATE TABLE IF NOT EXISTS player_messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id INTEGER NOT NULL REFERENCES player_message_threads(id) ON DELETE CASCADE,
  sender_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  sender_label TEXT,
  body TEXT,
  removed_at TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_player_messages_thread ON player_messages (thread_id, id);
CREATE INDEX IF NOT EXISTS idx_player_messages_sender ON player_messages (sender_id, created_at);

-- How far somebody has read a thread, for unread counts.
CREATE TABLE IF NOT EXISTS player_message_reads (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  thread_id INTEGER NOT NULL REFERENCES player_message_threads(id) ON DELETE CASCADE,
  last_read_id INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, thread_id)
);

-- A person's mute of one context: no email and no unread count; they can still read and write. Keyed by the context, so it
-- stands before any thread exists.
CREATE TABLE IF NOT EXISTS player_message_mutes (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  context_kind TEXT NOT NULL,
  context_id INTEGER NOT NULL,
  muted_at TEXT NOT NULL DEFAULT datetime('now'),
  PRIMARY KEY (user_id, context_kind, context_id)
);

-- The emails sent, so a thread is told at most once per period and a person at most a few times a day. No text of a message here.
CREATE TABLE IF NOT EXISTS player_message_notices (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  thread_id INTEGER NOT NULL REFERENCES player_message_threads(id) ON DELETE CASCADE,
  sent_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_player_message_notices_user ON player_message_notices (user_id, sent_at);
CREATE INDEX IF NOT EXISTS idx_player_message_notices_thread ON player_message_notices (user_id, thread_id, sent_at);

-- A report of one message. It freezes a copy of the thread's last messages as the reporter saw them (`player_message_report_lines`),
-- so staff read what was reported even if the thread is later muted, closed or removed by retention. The reporter, the reported
-- person and the thread may all be gone later (account erased, retention): the report stays until it has been dealt with and
-- MESSAGE_REPORT_RETENTION_DAYS have passed. `venue_id` is the context's venue: its staff see the report; NULL, the platform owner.
CREATE TABLE IF NOT EXISTS player_message_reports (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id INTEGER REFERENCES player_message_threads(id) ON DELETE SET NULL,
  message_id INTEGER,
  context_kind TEXT NOT NULL,
  context_id INTEGER NOT NULL,
  venue_id INTEGER REFERENCES venues(id) ON DELETE SET NULL,
  reporter_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  reported_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  reporter_label TEXT,
  reported_label TEXT,
  reason TEXT NOT NULL CHECK (reason IN ('abuse', 'spam', 'contact', 'safety', 'other')),
  note TEXT,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'reviewed')),
  -- How it was dealt with: nothing needed, or something done (a thread muted or closed, a person's messaging suspended).
  outcome TEXT CHECK (outcome IS NULL OR outcome IN ('no_action', 'action_taken')),
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  reviewed_at TEXT,
  reviewed_by_name TEXT
);
CREATE INDEX IF NOT EXISTS idx_player_message_reports_venue ON player_message_reports (venue_id, status);
CREATE INDEX IF NOT EXISTS idx_player_message_reports_reported ON player_message_reports (reported_id, created_at) WHERE reported_id IS NOT NULL;
-- One open report of the same message by the same person is enough.
CREATE UNIQUE INDEX IF NOT EXISTS uq_player_message_report_once ON player_message_reports (reporter_id, message_id) WHERE reporter_id IS NOT NULL AND message_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS player_message_report_lines (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id INTEGER NOT NULL REFERENCES player_message_reports(id) ON DELETE CASCADE,
  message_id INTEGER NOT NULL,
  sender_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  sender_label TEXT,
  body TEXT,
  sent_at TEXT NOT NULL,
  flagged INTEGER NOT NULL DEFAULT 0 CHECK (flagged IN (0, 1))
);
CREATE INDEX IF NOT EXISTS idx_player_message_report_lines_report ON player_message_report_lines (report_id, id);
CREATE INDEX IF NOT EXISTS idx_player_message_report_lines_sender ON player_message_report_lines (sender_id) WHERE sender_id IS NOT NULL;

-- Somebody's messaging stopped: by staff (a venue's for its own contexts, `venue_id` set; the platform owner's for everywhere,
-- NULL), or automatically when enough different people have reported them (ADR 0039), pending the platform owner's review. At
-- most one in force for a person and scope; lifting one keeps who lifted it and why.
CREATE TABLE IF NOT EXISTS player_message_suspensions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  source TEXT NOT NULL CHECK (source IN ('staff', 'automatic')),
  venue_id INTEGER REFERENCES venues(id) ON DELETE CASCADE,
  reason TEXT NOT NULL,
  admin_name TEXT,
  report_id INTEGER REFERENCES player_message_reports(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  lifted_at TEXT,
  lifted_by_name TEXT,
  lift_reason TEXT
);
CREATE INDEX IF NOT EXISTS idx_player_message_suspensions_user ON player_message_suspensions (user_id) WHERE lifted_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_player_message_suspension_global ON player_message_suspensions (user_id) WHERE lifted_at IS NULL AND venue_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_player_message_suspension_venue ON player_message_suspensions (user_id, venue_id) WHERE lifted_at IS NULL AND venue_id IS NOT NULL;
