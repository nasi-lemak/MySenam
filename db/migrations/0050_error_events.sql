-- Errors, grouped: one row for each kind of failure (its fingerprint), with
-- how often it has happened, where last, and its last stack trace. Server
-- errors from requests and errors reported by customers' browsers.
-- resolved_at: marked fixed; it reopens if it happens again.
CREATE TABLE IF NOT EXISTS error_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fingerprint TEXT NOT NULL UNIQUE,
  source TEXT NOT NULL CHECK (source IN ('server', 'browser')),
  name TEXT NOT NULL,
  message TEXT NOT NULL,
  stack TEXT,
  path TEXT,
  method TEXT,
  digest TEXT,
  count INTEGER NOT NULL DEFAULT 1,
  first_at TEXT NOT NULL DEFAULT datetime('now'),
  last_at TEXT NOT NULL DEFAULT datetime('now'),
  resolved_at TEXT
);
CREATE INDEX IF NOT EXISTS error_events_last ON error_events (last_at);
