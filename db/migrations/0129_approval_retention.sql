-- Purpose-based retention for applications to be approved for an activity
-- (lib/approval-retention.ts; docs/architecture/privacy.md#applications-to-be-approved-for-an-activity;
-- ADR 0021).
--
-- The eligibility an approval gives lives in the sign-off or certification it
-- wrote (sign_offs), which the booking rules check; the application is the
-- history of how it was decided. Each is kept for its own purpose: the
-- documents only while a decision, review or appeal needs them; the answers
-- and history a set time after the application closed; the sign-off as long
-- as it is valid. A hold placed by somebody entitled to, for a stated legal,
-- safety or dispute reason, keeps an application past its time until the
-- hold's review date.

-- Why the venue needs the document it asks for (shown to applicants). A venue
-- that asks for a document must say why before it can take one.
ALTER TABLE approval_requirements ADD COLUMN IF NOT EXISTS document_purpose TEXT;
-- An activity's own, shorter periods; NULL: the install's defaults. The
-- maxima are the documented ones (lib/privacy.ts RETENTION): longer only by a hold.
ALTER TABLE approval_requirements ADD COLUMN IF NOT EXISTS review_days INTEGER;
ALTER TABLE approval_requirements ADD COLUMN IF NOT EXISTS document_days INTEGER;
ALTER TABLE approval_requirements ADD COLUMN IF NOT EXISTS record_days INTEGER;
ALTER TABLE approval_requirements DROP CONSTRAINT IF EXISTS approval_requirements_retention;
ALTER TABLE approval_requirements ADD CONSTRAINT approval_requirements_retention CHECK (
  (review_days IS NULL OR review_days BETWEEN 1 AND 90)
  AND (document_days IS NULL OR document_days BETWEEN 1 AND 90)
  AND (record_days IS NULL OR record_days BETWEEN 30 AND 365)
);

-- When the application stopped being needed for what it was for: decided
-- other than approved, or the approval it gave ended (lapsed, taken back or
-- replaced). Kept once known, so a sign-off deleted later does not move it.
ALTER TABLE approval_requests ADD COLUMN IF NOT EXISTS closed_at TIMESTAMPTZ;
-- An approved application whose answers, declarations and history detail
-- have gone, its approval still standing.
ALTER TABLE approval_requests ADD COLUMN IF NOT EXISTS minimised_at TIMESTAMPTZ;
CREATE INDEX IF NOT EXISTS idx_approval_requests_decided ON approval_requests (decided_at) WHERE decided_at IS NOT NULL;

-- Keeping an application past its time, for an actual legal, safety or
-- dispute reason: who placed it, in what role, why, and until when it is to
-- be reviewed. A hold ends on its review date unless renewed by a new one.
CREATE TABLE IF NOT EXISTS approval_holds (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id INTEGER NOT NULL REFERENCES approval_requests(id) ON DELETE CASCADE,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  basis TEXT NOT NULL CHECK (basis IN ('legal', 'safety', 'dispute', 'incident')),
  reason TEXT NOT NULL CHECK (length(reason) BETWEEN 10 AND 1000),
  placed_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  placed_by_name TEXT NOT NULL,
  placed_by_role TEXT NOT NULL CHECK (placed_by_role IN ('owner', 'manager')),
  placed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- The day it is to be looked at again; it stops protecting anything after it.
  review_by TEXT NOT NULL,
  released_at TIMESTAMPTZ,
  released_by_name TEXT,
  release_reason TEXT,
  -- A manager's hold is short; the platform owner's at most a year at a time.
  CHECK (review_by::date <= (placed_at AT TIME ZONE 'UTC')::date + CASE WHEN placed_by_role = 'owner' THEN 366 ELSE 91 END)
);
CREATE INDEX IF NOT EXISTS idx_approval_holds_request ON approval_holds (request_id);
CREATE INDEX IF NOT EXISTS idx_approval_holds_venue ON approval_holds (venue_id, id);

-- What is left of an application once its record is deleted: that it
-- existed, how it ended, when, and who decided it. No answers, declarations,
-- documents, name or number; the account it was from only while that exists.
CREATE TABLE IF NOT EXISTS approval_audit (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id INTEGER NOT NULL,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  sport TEXT NOT NULL,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  outcome TEXT NOT NULL,
  applied_at TIMESTAMPTZ NOT NULL,
  decided_at TIMESTAMPTZ,
  decided_by TEXT,
  decided_by_kind TEXT,
  closed_at TIMESTAMPTZ,
  removed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  removed_why TEXT NOT NULL CHECK (removed_why IN ('retention', 'erasure'))
);
CREATE INDEX IF NOT EXISTS idx_approval_audit_user ON approval_audit (user_id) WHERE user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_approval_audit_removed ON approval_audit (removed_at);
