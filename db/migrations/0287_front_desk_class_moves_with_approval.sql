-- Front-desk class moves, with a manager's approval for the consequential or exceptional ones
-- (lib/class-move-requests.ts; ADR 0045; docs/features/programmes.md#front-desk-moves-and-approval).
--
-- 1. Per-venue settings, all advanced and all with a default that needs no setting up. `desk_may_move_classes` is on: front desk may move
--    a class at its own venue (a manager may turn it off, which is the earlier rule, a manager's alone). A desk's move needs a manager's approval when it
--    is more than `class_move_max_days` days from where the session was, moves more than `class_move_max_series` sessions, starts or would start within
--    `class_move_within_hours` hours, bumps a waiting list, is a second move of a session, prices differently (`class_move_price_check`), or, where
--    `class_move_paid_people` is set (null: not asked), puts more than that many paying people through a move; and a term with paid enrolments always.
ALTER TABLE venues ADD COLUMN IF NOT EXISTS desk_may_move_classes BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE venues ADD COLUMN IF NOT EXISTS class_move_max_days INTEGER NOT NULL DEFAULT 14;
ALTER TABLE venues ADD COLUMN IF NOT EXISTS class_move_max_series INTEGER NOT NULL DEFAULT 4;
ALTER TABLE venues ADD COLUMN IF NOT EXISTS class_move_within_hours INTEGER NOT NULL DEFAULT 24;
ALTER TABLE venues ADD COLUMN IF NOT EXISTS class_move_paid_people INTEGER;
ALTER TABLE venues ADD COLUMN IF NOT EXISTS class_move_price_check BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE venues ADD COLUMN IF NOT EXISTS class_move_request_days INTEGER NOT NULL DEFAULT 7;
ALTER TABLE venues DROP CONSTRAINT IF EXISTS venues_class_move_rules_check;
ALTER TABLE venues ADD CONSTRAINT venues_class_move_rules_check CHECK (
  class_move_max_days BETWEEN 0 AND 365 AND class_move_max_series BETWEEN 0 AND 52 AND class_move_within_hours BETWEEN 0 AND 720
  AND (class_move_paid_people IS NULL OR class_move_paid_people BETWEEN 0 AND 1000) AND class_move_request_days BETWEEN 1 AND 60
);

-- 2. A request to move a class that needs approval: who asked and what for, why it needs approval (`reasons`, JSON, as computed when it was asked),
--    the preview as the desk saw it (`snapshot`, JSON: sessions from and to, and counts, never a person's name) and a fingerprint of what it was
--    computed from, so an approval refuses if the class, who is enrolled or who is waiting changed since. It changes nothing and tells nobody until a
--    manager approves, which makes the move through `moveClasses` in the same transaction that marks it approved.
CREATE TABLE IF NOT EXISTS class_move_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  class_id INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
  scope TEXT NOT NULL CHECK (scope IN ('one', 'following', 'term')),
  to_date TEXT NOT NULL,
  to_start_min INTEGER NOT NULL,
  to_court_id INTEGER,
  requested_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  requested_by_name TEXT NOT NULL,
  note TEXT,
  reasons TEXT NOT NULL,
  snapshot TEXT NOT NULL,
  fingerprint TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'approved', 'declined', 'expired', 'closed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at TIMESTAMPTZ NOT NULL,
  decided_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  decided_by_name TEXT,
  decided_at TIMESTAMPTZ,
  decision_note TEXT,
  -- Why it closed without a decision: 'expired' is a status of its own; here 'started', 'cancelled' or 'changed'.
  closed_reason TEXT,
  move_id INTEGER REFERENCES class_moves(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_class_move_requests_venue ON class_move_requests (venue_id, status, id);
CREATE INDEX IF NOT EXISTS idx_class_move_requests_class ON class_move_requests (class_id);
-- One request waits for a manager for a class at a time.
CREATE UNIQUE INDEX IF NOT EXISTS uq_class_move_request_open ON class_move_requests (class_id) WHERE status = 'open';
