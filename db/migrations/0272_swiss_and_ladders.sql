-- ---------------------------------------------------------------- Swiss

-- A tournament may be of format 'swiss'. The list is extended from what it holds now (not rewritten), so a format
-- another migration added stays.
DO $$
DECLARE c RECORD;
BEGIN
  FOR c IN SELECT t.relname AS tbl, k.conname, pg_get_constraintdef(k.oid) AS def
             FROM pg_constraint k JOIN pg_class t ON t.oid = k.conrelid
            WHERE k.contype = 'c' AND t.relname IN ('tournaments', 'competition_templates')
              AND pg_get_constraintdef(k.oid) LIKE '%round_robin%' AND pg_get_constraintdef(k.oid) NOT LIKE '%swiss%'
  LOOP
    EXECUTE format('ALTER TABLE %I DROP CONSTRAINT %I', c.tbl, c.conname);
    EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I %s', c.tbl, c.conname, replace(c.def, '''performance''::text', '''performance''::text, ''swiss''::text'));
  END LOOP;
END $$;

-- Each entry's place in the initial order (seeds first, then the drawn order): what every pairing and tie-break reads.
ALTER TABLE tournament_entries ADD COLUMN IF NOT EXISTS swiss_rank INTEGER;

-- One row per Swiss event, made at its draw: the rounds it will play (the organiser can end it early), the seed of the
-- draw's randomness (recorded so the draw can be reproduced), and the tie-break order the standings use.
CREATE TABLE IF NOT EXISTS swiss_events (
  tournament_id INTEGER PRIMARY KEY REFERENCES tournaments(id) ON DELETE CASCADE,
  rounds INTEGER NOT NULL CHECK (rounds BETWEEN 1 AND 127),
  planned_rounds INTEGER NOT NULL CHECK (planned_rounds BETWEEN 1 AND 127),
  seed BIGINT NOT NULL,
  tiebreaks TEXT NOT NULL,
  bye_points INTEGER NOT NULL CHECK (bye_points BETWEEN 0 AND 10),
  -- Why the next round could not be paired, when it could not (no legal pairing, no court time); cleared when it is.
  blocked TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);

-- A paired round and why each pairing was made (JSON: who, against whom, from which score group, floats, the bye).
CREATE TABLE IF NOT EXISTS swiss_rounds (
  tournament_id INTEGER NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
  round INTEGER NOT NULL CHECK (round >= 1),
  paired_at TEXT NOT NULL DEFAULT datetime('now'),
  notes TEXT NOT NULL,
  PRIMARY KEY (tournament_id, round)
);

-- ---------------------------------------------------------------- Ladders

CREATE TABLE IF NOT EXISTS ladders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id),
  name TEXT NOT NULL,
  sport TEXT NOT NULL,
  -- Singles (1) or pairs (2, named by the player who joins).
  team_size INTEGER NOT NULL DEFAULT 1 CHECK (team_size IN (1, 2)),
  who TEXT NOT NULL DEFAULT 'anyone' CHECK (who IN ('anyone', 'women', 'men')),
  -- Adults take the account holder who declares they are 18 or over; juniors only participants a guardian enters.
  audience TEXT NOT NULL DEFAULT 'adults' CHECK (audience IN ('adults', 'juniors')),
  level TEXT,
  description TEXT,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
  -- How its matches are scored (lib/tournament-rules.ts), as a box league's are.
  rules TEXT,
  template TEXT,
  rated BOOLEAN NOT NULL DEFAULT false,
  -- Settings: challenge up to `reach` places above; the challenged answers within `respond_days` or forfeits; a
  -- played match is reported within `play_days` of acceptance or lapses; the same pair wait `cooldown_days`; a player
  -- idle `inactive_days` drops `inactive_drop` places (0 days: never); a freeze is at most `freeze_max_days`;
  -- declining is free or counts as a forfeit.
  reach INTEGER NOT NULL DEFAULT 3 CHECK (reach BETWEEN 1 AND 10),
  respond_days INTEGER NOT NULL DEFAULT 3 CHECK (respond_days BETWEEN 1 AND 14),
  play_days INTEGER NOT NULL DEFAULT 14 CHECK (play_days BETWEEN 3 AND 60),
  cooldown_days INTEGER NOT NULL DEFAULT 14 CHECK (cooldown_days BETWEEN 0 AND 90),
  inactive_days INTEGER NOT NULL DEFAULT 30 CHECK (inactive_days BETWEEN 0 AND 365),
  inactive_drop INTEGER NOT NULL DEFAULT 1 CHECK (inactive_drop BETWEEN 1 AND 10),
  freeze_max_days INTEGER NOT NULL DEFAULT 60 CHECK (freeze_max_days BETWEEN 1 AND 180),
  decline_is TEXT NOT NULL DEFAULT 'free' CHECK (decline_is IN ('free', 'forfeit')),
  created_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_ladders_venue ON ladders (venue_id);

-- A season: its events are its own; ending it archives the final order.
CREATE TABLE IF NOT EXISTS ladder_seasons (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ladder_id INTEGER NOT NULL REFERENCES ladders(id) ON DELETE CASCADE,
  number INTEGER NOT NULL,
  started_on TEXT NOT NULL,
  ended_on TEXT,
  -- JSON: [{rank, playerId, name}] as the season ended, names as shown publicly.
  final_ranks TEXT,
  UNIQUE (ladder_id, number)
);

CREATE TABLE IF NOT EXISTS ladder_players (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ladder_id INTEGER NOT NULL REFERENCES ladders(id) ON DELETE CASCADE,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  -- As shown on the ladder: a player's name, or "Lim / Tan" for a pair.
  name TEXT NOT NULL,
  partner_name TEXT,
  partner_gender TEXT CHECK (partner_gender IN ('woman', 'man')),
  participant_id INTEGER REFERENCES participants(id) ON DELETE SET NULL,
  entrant_gender TEXT CHECK (entrant_gender IN ('woman', 'man')),
  contact_phone TEXT,
  entered_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  entered_by_name TEXT,
  -- An adult declared they are 18 or over (the entrant's word, never verified).
  declared_adult_at TEXT,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'left')),
  joined_at TEXT NOT NULL DEFAULT datetime('now'),
  left_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_ladder_players_ladder ON ladder_players (ladder_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_ladder_player_user ON ladder_players (ladder_id, user_id)
  WHERE user_id IS NOT NULL AND participant_id IS NULL AND status = 'active';
CREATE UNIQUE INDEX IF NOT EXISTS uq_ladder_player_participant ON ladder_players (ladder_id, participant_id)
  WHERE participant_id IS NOT NULL AND status = 'active';

-- A challenge, from the challenger's first message to its end.
CREATE TABLE IF NOT EXISTS ladder_challenges (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ladder_id INTEGER NOT NULL REFERENCES ladders(id) ON DELETE CASCADE,
  season_id INTEGER NOT NULL REFERENCES ladder_seasons(id) ON DELETE CASCADE,
  challenger INTEGER NOT NULL REFERENCES ladder_players(id),
  challenged INTEGER NOT NULL REFERENCES ladder_players(id),
  -- Their ranks when it was made, for the history.
  challenger_rank INTEGER NOT NULL,
  challenged_rank INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'accepted', 'reported', 'disputed', 'confirmed', 'walkover', 'declined', 'cancelled', 'lapsed', 'void')),
  -- Pending: whose answer it waits for (the challenged first; the challenger after a proposed time).
  awaiting TEXT NOT NULL DEFAULT 'challenged' CHECK (awaiting IN ('challenged', 'challenger')),
  proposed_on TEXT,
  proposed_min INTEGER,
  proposed_by INTEGER REFERENCES ladder_players(id),
  agreed_on TEXT,
  agreed_min INTEGER,
  created_on TEXT NOT NULL,
  respond_by TEXT,
  play_by TEXT,
  winner INTEGER REFERENCES ladder_players(id),
  score TEXT,
  forfeit BOOLEAN NOT NULL DEFAULT false,
  reported_by INTEGER REFERENCES ladder_players(id),
  reported_at TEXT,
  dispute_note TEXT,
  decided_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  resolved_on TEXT,
  version INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  updated_at TEXT NOT NULL DEFAULT datetime('now'),
  CHECK (challenger <> challenged)
);
CREATE INDEX IF NOT EXISTS idx_ladder_challenges_ladder ON ladder_challenges (ladder_id, season_id);
CREATE INDEX IF NOT EXISTS idx_ladder_challenges_open ON ladder_challenges (ladder_id) WHERE status IN ('pending', 'accepted', 'reported', 'disputed');

-- The ledger: what happened on a ladder, in order. A season's ranks are the pure replay of its live events by `ord`.
-- A correction voids the event and writes its replacement with the same `ord`, so it keeps its place in the order.
CREATE TABLE IF NOT EXISTS ladder_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ladder_id INTEGER NOT NULL REFERENCES ladders(id) ON DELETE CASCADE,
  season_id INTEGER NOT NULL REFERENCES ladder_seasons(id) ON DELETE CASCADE,
  ord INTEGER NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('join', 'carry', 'leave', 'result', 'drop', 'freeze', 'thaw', 'move', 'remove')),
  -- The subject; for a result the challenger, and `other_id` the challenged.
  player_id INTEGER NOT NULL REFERENCES ladder_players(id),
  other_id INTEGER REFERENCES ladder_players(id),
  challenge_id INTEGER REFERENCES ladder_challenges(id) ON DELETE SET NULL,
  -- The day it counts from, in the venue's time.
  on_date TEXT NOT NULL,
  -- JSON: { challengerWon, forfeit, places, until, toRank, reason, by }.
  data TEXT NOT NULL DEFAULT '{}',
  replaces INTEGER REFERENCES ladder_events(id),
  voided_at TEXT,
  voided_reason TEXT,
  voided_by TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_ladder_events_live ON ladder_events (season_id, ord) WHERE voided_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_ladder_events_season ON ladder_events (season_id);

-- The ranks as the replay of the ledger gave them at the last change: a cache, rewritten whole from the replay after
-- every change under the ladder's row lock, never updated from itself.
CREATE TABLE IF NOT EXISTS ladder_ranks (
  season_id INTEGER NOT NULL REFERENCES ladder_seasons(id) ON DELETE CASCADE,
  player_id INTEGER NOT NULL REFERENCES ladder_players(id),
  rank INTEGER NOT NULL,
  -- A freeze's last day, while frozen.
  frozen_until TEXT,
  -- Their last activity (the day inactivity is counted from).
  active_on TEXT NOT NULL,
  PRIMARY KEY (season_id, player_id)
);

