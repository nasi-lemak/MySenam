-- The install's own retention periods for applications to be approved for an
-- activity, and the record of who reviewed them (lib/retention-policy.ts;
-- docs/architecture/privacy.md#applications-to-be-approved-for-an-activity;
-- ADR 0024).
--
-- The defaults (90 days for documents after the decision, 30 for the review
-- window, 365 for a closed application's record) are the product owner's
-- provisional choice, not legal requirements, and are subject to professional
-- legal review in each country an install serves. The platform owner may set
-- the install's own; an activity may keep less than the install, never more.
-- Until somebody records a review (who reviewed it, on what day, on what
-- basis), the dashboard and the privacy notice say the periods are
-- provisional. Changing a period lapses the review.

CREATE TABLE IF NOT EXISTS retention_policy (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  approval_document_days INTEGER NOT NULL DEFAULT 90 CHECK (approval_document_days BETWEEN 7 AND 365),
  approval_review_days INTEGER NOT NULL DEFAULT 30 CHECK (approval_review_days BETWEEN 1 AND 365),
  approval_record_days INTEGER NOT NULL DEFAULT 365 CHECK (approval_record_days BETWEEN 30 AND 2190),
  -- A document refused by the malware scan, or one that could not be scanned:
  -- what is left of it (the fact; for a failed scan, the quarantined bytes).
  scan_quarantine_days INTEGER NOT NULL DEFAULT 7 CHECK (scan_quarantine_days BETWEEN 1 AND 30),
  changed_at TIMESTAMPTZ,
  changed_by_name TEXT,
  -- The professional review of these periods, absent until somebody records one.
  reviewed_on TEXT,
  reviewed_by TEXT,
  review_basis TEXT,
  review_recorded_by_name TEXT,
  review_recorded_at TIMESTAMPTZ,
  CHECK (approval_review_days <= approval_document_days),
  CHECK ((reviewed_on IS NULL) = (reviewed_by IS NULL) AND (reviewed_on IS NULL) = (review_basis IS NULL))
);
INSERT INTO retention_policy (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

-- Every change and every recorded review, with who and when; never pruned.
CREATE TABLE IF NOT EXISTS retention_policy_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at TIMESTAMPTZ NOT NULL DEFAULT now(),
  kind TEXT NOT NULL CHECK (kind IN ('changed', 'reviewed')),
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  by_name TEXT NOT NULL,
  detail TEXT NOT NULL
);

-- An activity's own periods may be anything up to the install's (checked in
-- the code against the install's policy); the database keeps the outer bounds.
ALTER TABLE approval_requirements DROP CONSTRAINT IF EXISTS approval_requirements_retention;
ALTER TABLE approval_requirements ADD CONSTRAINT approval_requirements_retention CHECK (
  (review_days IS NULL OR review_days BETWEEN 1 AND 365)
  AND (document_days IS NULL OR document_days BETWEEN 1 AND 365)
  AND (record_days IS NULL OR record_days BETWEEN 30 AND 2190)
);
