-- Teams that persist across events, and leagues of teams with fixture lists
-- (docs/features/tournaments.md#teams, #team-leagues; lib/teams.ts, lib/team-leagues.ts, lib/fixtures.ts).
--
-- A team is an entity of its own: a name, a sport, a captain, and members who joined with their own accounts (or, for a
-- child, through the guardian's account with the guardian's agreement, ADR 0022/0023). It holds no court and no money.
-- Tournament entries and team-league entries can name a team; the entry then carries a roster picked from the team's
-- members, checked per member against the event's rules (declared, never verified).

CREATE TABLE IF NOT EXISTS teams (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  sport TEXT NOT NULL REFERENCES activities(key) ON UPDATE CASCADE,
  -- Optional: the venue it plays from, and the community group it grew out of (a label; neither adds members).
  venue_id INTEGER REFERENCES venues(id) ON DELETE SET NULL,
  group_id INTEGER REFERENCES community_groups(id) ON DELETE SET NULL,
  captain_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  description TEXT,
  -- Shown by name (and sport) to anybody only if the captain publishes it; members see it always.
  published BOOLEAN NOT NULL DEFAULT false,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'archived')),
  archived_at TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_teams_captain ON teams(captain_user_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_team_captain_name ON teams (captain_user_id, lower(name)) WHERE status = 'active' AND captain_user_id IS NOT NULL;

-- Who is on a team: an account (its own holder), or a participant a guardian manages (`acting_user_id` is the guardian's
-- account, who agreed). Invited people have no row until they accept (team_invitations). `birth_date` and `gender` are
-- declared by the member, or the guardian for a child, only so an event's age range and category can be checked: the
-- member's word, never verified, and shown to nobody but them and their guardian.
CREATE TABLE IF NOT EXISTS team_members (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
  participant_id INTEGER REFERENCES participants(id) ON DELETE CASCADE,
  acting_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  role TEXT NOT NULL DEFAULT 'member' CHECK (role IN ('captain', 'member')),
  status TEXT NOT NULL DEFAULT 'member' CHECK (status IN ('member', 'left', 'removed')),
  birth_date TEXT,
  gender TEXT CHECK (gender IN ('woman', 'man')),
  -- A child joins only with the acting guardian's agreement, as declared when they accepted.
  agreed_at TEXT,
  invited_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  joined_at TEXT NOT NULL DEFAULT datetime('now'),
  left_at TEXT,
  CHECK ((user_id IS NOT NULL) <> (participant_id IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_team_members_team ON team_members(team_id);
CREATE INDEX IF NOT EXISTS idx_team_members_user ON team_members(user_id) WHERE user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_team_members_participant ON team_members(participant_id) WHERE participant_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_team_members_acting ON team_members(acting_user_id) WHERE acting_user_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_team_member_user ON team_members (team_id, user_id) WHERE user_id IS NOT NULL AND status = 'member';
CREATE UNIQUE INDEX IF NOT EXISTS uq_team_member_participant ON team_members (team_id, participant_id) WHERE participant_id IS NOT NULL AND status = 'member';
-- One captain at a time.
CREATE UNIQUE INDEX IF NOT EXISTS uq_team_captain ON team_members (team_id) WHERE role = 'captain' AND status = 'member';

-- Invitations to join a team, by email (no account is looked up: the same answer whoever holds the address, as groups'
-- are) or by a link the captain shares (WhatsApp, a message). Only keyed hashes are kept. Single use; they run out.
CREATE TABLE IF NOT EXISTS team_invitations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  invited_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  kind TEXT NOT NULL CHECK (kind IN ('email', 'link')),
  token_hash TEXT NOT NULL UNIQUE,
  email_hash TEXT,
  expires_at TEXT NOT NULL,
  used_at TEXT,
  used_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  cancelled_at TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  CHECK (kind = 'link' OR email_hash IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_team_invitations_team ON team_invitations(team_id);
CREATE INDEX IF NOT EXISTS idx_team_invitations_by ON team_invitations(invited_by, created_at);

-- A tournament entry that names a team, and the members picked for it (names as they were, so the record stands when a
-- member leaves). The typed roster of names (`roster`) still works for an entry that names no team.
ALTER TABLE tournament_entries ADD COLUMN IF NOT EXISTS team_id INTEGER REFERENCES teams(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_tournament_entries_team ON tournament_entries(team_id) WHERE team_id IS NOT NULL;
CREATE TABLE IF NOT EXISTS tournament_entry_members (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entry_id INTEGER NOT NULL REFERENCES tournament_entries(id) ON DELETE CASCADE,
  team_member_id INTEGER REFERENCES team_members(id) ON DELETE SET NULL,
  name TEXT NOT NULL,
  -- Under 18 on the event's first day, as the member declared, and the guardian's agreement recorded when they joined the team.
  declared_minor BOOLEAN NOT NULL DEFAULT false,
  guardian_agreed_at TEXT,
  UNIQUE (entry_id, team_member_id)
);
CREATE INDEX IF NOT EXISTS idx_tournament_entry_members_member ON tournament_entry_members(team_member_id) WHERE team_member_id IS NOT NULL;

-- ------------------------------------------------------------ team leagues

-- A league of teams for one season: teams enter, a manager sets the match nights, and a generator makes the fixture
-- list. `rules` is the sport's competition rules as for any competition (how a game is scored, lib/tournament-rules.ts);
-- `rubbers` the games a team match is made of (a list of kinds: singles, doubles, or one whole-team match); `table_rules` how a team match earns table points and how the table is
-- ranked. Nothing is sold: no fee.
CREATE TABLE IF NOT EXISTS team_leagues (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  sport TEXT NOT NULL REFERENCES activities(key) ON UPDATE CASCADE,
  template TEXT,
  rules TEXT NOT NULL,
  rubbers TEXT NOT NULL,
  table_rules TEXT NOT NULL,
  -- 1: every team meets every other once; 2: home and away.
  legs INTEGER NOT NULL DEFAULT 1 CHECK (legs IN (1, 2)),
  category TEXT NOT NULL DEFAULT 'open' CHECK (category IN ('open', 'women', 'men')),
  age_min INTEGER CHECK (age_min IS NULL OR age_min BETWEEN 0 AND 120),
  age_max INTEGER CHECK (age_max IS NULL OR age_max BETWEEN 0 AND 120),
  members_only BOOLEAN NOT NULL DEFAULT false,
  level TEXT CHECK (level IN ('beginner', 'intermediate', 'advanced', 'competitive')),
  description TEXT,
  -- The season: every match night falls within it, and ages are counted on its first day.
  starts_on TEXT NOT NULL,
  ends_on TEXT NOT NULL,
  -- Team matches a night can hold at one court-slot: each fixture is held for its rubbers' time.
  slots_per_night INTEGER NOT NULL DEFAULT 2 CHECK (slots_per_night BETWEEN 1 AND 8),
  max_teams INTEGER NOT NULL DEFAULT 12 CHECK (max_teams BETWEEN 2 AND 24),
  entries_close_on TEXT,
  roster_min INTEGER NOT NULL DEFAULT 2 CHECK (roster_min BETWEEN 1 AND 40),
  roster_max INTEGER NOT NULL DEFAULT 12 CHECK (roster_max BETWEEN 1 AND 40),
  -- A player may play in at most this many rubbers of one team match.
  max_rubbers_per_player INTEGER NOT NULL DEFAULT 2 CHECK (max_rubbers_per_player BETWEEN 1 AND 10),
  -- Minutes held on court for one rubber.
  rubber_minutes INTEGER NOT NULL DEFAULT 40 CHECK (rubber_minutes BETWEEN 5 AND 300),
  status TEXT NOT NULL DEFAULT 'forming' CHECK (status IN ('forming', 'scheduled', 'finished', 'closed')),
  created_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  CHECK (age_min IS NULL OR age_max IS NULL OR age_min <= age_max),
  CHECK (roster_min <= roster_max),
  CHECK (ends_on >= starts_on)
);
CREATE INDEX IF NOT EXISTS idx_team_leagues_venue ON team_leagues(venue_id);

-- The venue's resources (courts) the league's fixtures may be played on.
CREATE TABLE IF NOT EXISTS team_league_courts (
  league_id INTEGER NOT NULL REFERENCES team_leagues(id) ON DELETE CASCADE,
  court_id INTEGER NOT NULL REFERENCES courts(id) ON DELETE CASCADE,
  PRIMARY KEY (league_id, court_id)
);

-- The nights the manager sets, and when play starts on each.
CREATE TABLE IF NOT EXISTS team_league_nights (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  league_id INTEGER NOT NULL REFERENCES team_leagues(id) ON DELETE CASCADE,
  night_no INTEGER NOT NULL,
  date TEXT NOT NULL,
  start_min INTEGER NOT NULL CHECK (start_min BETWEEN 0 AND 1439),
  UNIQUE (league_id, date)
);

-- A team in a league: its name as it was entered, the captain's choice of a home court, and the roster picked for the
-- league. `team_id` stays NULL-able so the league's record stands if the team is erased.
CREATE TABLE IF NOT EXISTS team_league_teams (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  league_id INTEGER NOT NULL REFERENCES team_leagues(id) ON DELETE CASCADE,
  team_id INTEGER REFERENCES teams(id) ON DELETE SET NULL,
  name TEXT NOT NULL,
  home_court_id INTEGER REFERENCES courts(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'entered' CHECK (status IN ('entered', 'withdrawn')),
  entered_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  entered_at TEXT NOT NULL DEFAULT datetime('now'),
  withdrawn_at TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_team_league_team ON team_league_teams (league_id, team_id) WHERE team_id IS NOT NULL AND status = 'entered';
CREATE UNIQUE INDEX IF NOT EXISTS uq_team_league_team_name ON team_league_teams (league_id, lower(name)) WHERE status = 'entered';

CREATE TABLE IF NOT EXISTS team_league_roster (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  league_team_id INTEGER NOT NULL REFERENCES team_league_teams(id) ON DELETE CASCADE,
  team_member_id INTEGER REFERENCES team_members(id) ON DELETE SET NULL,
  name TEXT NOT NULL,
  UNIQUE (league_team_id, team_member_id)
);

-- Dates a team cannot play, as the captain gave them; the generator keeps its fixtures off them.
CREATE TABLE IF NOT EXISTS team_league_blackouts (
  league_team_id INTEGER NOT NULL REFERENCES team_league_teams(id) ON DELETE CASCADE,
  date TEXT NOT NULL,
  PRIMARY KEY (league_team_id, date)
);

-- A fixture: two teams, a night, a court and a time. `status`: scheduled; reported (one captain has said how it went);
-- confirmed (the other agrees, staff decide, or nobody objects in time); disputed (staff decide); forfeit (one side
-- did not play: the other is awarded every rubber); void (not counted). A change is made only on the version read.
CREATE TABLE IF NOT EXISTS team_fixtures (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  league_id INTEGER NOT NULL REFERENCES team_leagues(id) ON DELETE CASCADE,
  night_id INTEGER REFERENCES team_league_nights(id) ON DELETE SET NULL,
  leg INTEGER NOT NULL DEFAULT 1,
  round_no INTEGER NOT NULL,
  home_team INTEGER NOT NULL REFERENCES team_league_teams(id) ON DELETE CASCADE,
  away_team INTEGER NOT NULL REFERENCES team_league_teams(id) ON DELETE CASCADE,
  court_id INTEGER REFERENCES courts(id) ON DELETE SET NULL,
  date TEXT NOT NULL,
  start_min INTEGER NOT NULL,
  minutes INTEGER NOT NULL CHECK (minutes > 0),
  status TEXT NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled', 'reported', 'confirmed', 'disputed', 'forfeit', 'void')),
  forfeit_by INTEGER REFERENCES team_league_teams(id) ON DELETE SET NULL,
  reported_by INTEGER REFERENCES team_league_teams(id) ON DELETE SET NULL,
  reported_at TEXT,
  dispute_note TEXT,
  decided_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  moved_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  moved_at TEXT,
  version INTEGER NOT NULL DEFAULT 0,
  updated_at TEXT,
  CHECK (home_team <> away_team)
);
CREATE INDEX IF NOT EXISTS idx_team_fixtures_league ON team_fixtures(league_id, date, start_min);
CREATE INDEX IF NOT EXISTS idx_team_fixtures_home ON team_fixtures(home_team);
CREATE INDEX IF NOT EXISTS idx_team_fixtures_away ON team_fixtures(away_team);
CREATE INDEX IF NOT EXISTS idx_team_fixtures_reported ON team_fixtures(status, reported_at);

-- The games of a fixture, in order. `winner`: the side that won it, NULL while unplayed or where a level score is a draw.
CREATE TABLE IF NOT EXISTS team_fixture_rubbers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fixture_id INTEGER NOT NULL REFERENCES team_fixtures(id) ON DELETE CASCADE,
  rubber_no INTEGER NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('singles', 'doubles', 'team')),
  -- Home side's score first.
  score TEXT,
  winner TEXT CHECK (winner IN ('home', 'away')),
  played BOOLEAN NOT NULL DEFAULT false,
  walkover BOOLEAN NOT NULL DEFAULT false,
  UNIQUE (fixture_id, rubber_no)
);

-- Who plays each rubber, as the captain picked them from the league roster (names as they were).
CREATE TABLE IF NOT EXISTS team_fixture_lineups (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fixture_id INTEGER NOT NULL REFERENCES team_fixtures(id) ON DELETE CASCADE,
  rubber_no INTEGER NOT NULL,
  side TEXT NOT NULL CHECK (side IN ('home', 'away')),
  team_member_id INTEGER REFERENCES team_members(id) ON DELETE SET NULL,
  name TEXT NOT NULL,
  is_junior BOOLEAN NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS idx_team_fixture_lineups_fixture ON team_fixture_lineups(fixture_id, side);
CREATE INDEX IF NOT EXISTS idx_team_fixture_lineups_member ON team_fixture_lineups(team_member_id) WHERE team_member_id IS NOT NULL;

-- A fixture's court time is held as a block, owned by the league like a tournament's, so every booking path treats it as
-- taken and a staff block over it never carves it away.
ALTER TABLE blocks ADD COLUMN IF NOT EXISTS team_league_id INTEGER REFERENCES team_leagues(id) ON DELETE CASCADE;
ALTER TABLE blocks ADD COLUMN IF NOT EXISTS team_fixture_id INTEGER REFERENCES team_fixtures(id) ON DELETE CASCADE;
CREATE INDEX IF NOT EXISTS idx_blocks_team_league ON blocks(team_league_id) WHERE team_league_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_blocks_team_fixture ON blocks(team_fixture_id) WHERE team_fixture_id IS NOT NULL;
