-- Email first; WhatsApp only where a venue switches it on and, on a
-- marketplace, has paid for it in advance.

-- A venue's own choice. Off until somebody at the venue turns it on.
ALTER TABLE venues ADD COLUMN IF NOT EXISTS whatsapp_on INTEGER NOT NULL DEFAULT 0;

-- A calendar file (iCalendar text) sent with an email confirmation.
ALTER TABLE messages ADD COLUMN IF NOT EXISTS calendar TEXT;

-- Prepaid WhatsApp messages, bought in packs and spent one per message.
CREATE TABLE IF NOT EXISTS whatsapp_packs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id),
  messages INTEGER NOT NULL CHECK (messages > 0),
  amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
  status TEXT NOT NULL DEFAULT 'due' CHECK (status IN ('due','paid','void')),
  created_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  paid_at TEXT,
  paid_via TEXT CHECK (paid_via IN ('online','manual'))
);
CREATE INDEX IF NOT EXISTS whatsapp_packs_venue ON whatsapp_packs (venue_id);

-- Every message bought, granted, spent or given back: the balance is the sum.
CREATE TABLE IF NOT EXISTS whatsapp_credit (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id),
  delta INTEGER NOT NULL,
  reason TEXT NOT NULL,
  message_id INTEGER REFERENCES messages(id) ON DELETE SET NULL,
  pack_id INTEGER REFERENCES whatsapp_packs(id),
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS whatsapp_credit_venue ON whatsapp_credit (venue_id);

-- A pack is paid for online through the platform's own account.
ALTER TABLE online_payments ADD COLUMN IF NOT EXISTS pack_id INTEGER REFERENCES whatsapp_packs(id);
ALTER TABLE online_payments DROP CONSTRAINT IF EXISTS online_payments_purpose_check;
ALTER TABLE online_payments ADD CONSTRAINT online_payments_purpose_check
  CHECK (purpose IN ('booking', 'invoice', 'share', 'entry', 'league', 'pack'));

-- Prepaid replaces the monthly allowance and overage charged afterwards.
DROP TABLE IF EXISTS invoice_usage;
ALTER TABLE venues DROP COLUMN IF EXISTS whatsapp_included;
ALTER TABLE venues DROP COLUMN IF EXISTS whatsapp_price;
