-- A customer note keeps its history (ADR 0064, audit D24): every write, change and erase of a venue's note on a number is a row here,
-- appended, never changed (lib/customer-notes.ts). Seen by the same staff as the note itself (the venue's), exported with it and erased
-- with it when the customer's account is erased.
--
--   action:        'written' (there was none), 'edited' (replaced), 'erased' (taken away), 'baseline' (the note as it stood when history began).
--   previous_note: the text before this change (null if there was none); new_note: the text after it (null for an erase).
--   changed_by_name: as it was, so the record reads right after the account is removed.
CREATE TABLE IF NOT EXISTS customer_note_history (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  phone_key TEXT NOT NULL,
  action TEXT NOT NULL CHECK (action IN ('written', 'edited', 'erased', 'baseline')),
  previous_note TEXT,
  new_note TEXT,
  changed_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  changed_by_name TEXT,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS customer_note_history_note ON customer_note_history (venue_id, phone_key, id);

-- Appended, not edited: a row is never updated. (Rows go only with the venue or with the customer's erasure, which is a delete.)
CREATE OR REPLACE FUNCTION customer_note_history_no_update() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'customer_note_history rows are not changed';
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS customer_note_history_no_update ON customer_note_history;
CREATE TRIGGER customer_note_history_no_update BEFORE UPDATE ON customer_note_history FOR EACH ROW EXECUTE FUNCTION customer_note_history_no_update();

-- Notes that exist now start their history as they stand: one 'baseline' row each, with who last wrote it and when. What was changed
-- before this is not known and is not made up. Run again, it adds nothing for a note that already has history.
INSERT INTO customer_note_history (venue_id, phone_key, action, previous_note, new_note, changed_by, changed_by_name, changed_at)
SELECT n.venue_id, n.phone_key, 'baseline', NULL, n.note, n.updated_by, a.name, COALESCE(n.updated_at::timestamptz, now())
  FROM customer_notes n LEFT JOIN admins a ON a.id = n.updated_by
 WHERE NOT EXISTS (SELECT 1 FROM customer_note_history h WHERE h.venue_id = n.venue_id AND h.phone_key = n.phone_key);
