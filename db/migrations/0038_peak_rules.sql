-- When a venue's peak rate applies, venue by venue instead of the same for
-- everybody: peak hours on working days and on the weekend, which days are
-- the weekend (Friday and Saturday in Kedah, Kelantan and Terengganu), and
-- dates priced like the weekend: public, school and festive holidays.
-- The defaults are the rule every venue had until now: weekday evenings
-- from 18:00 and all weekend.
ALTER TABLE venues ADD COLUMN IF NOT EXISTS peak_weekday_from INTEGER NOT NULL DEFAULT 18;
ALTER TABLE venues ADD COLUMN IF NOT EXISTS peak_weekday_until INTEGER NOT NULL DEFAULT 24;
ALTER TABLE venues ADD COLUMN IF NOT EXISTS peak_weekend_days TEXT NOT NULL DEFAULT '0,6';
ALTER TABLE venues ADD COLUMN IF NOT EXISTS peak_weekend_from INTEGER NOT NULL DEFAULT 0;
ALTER TABLE venues ADD COLUMN IF NOT EXISTS peak_weekend_until INTEGER NOT NULL DEFAULT 24;

CREATE TABLE IF NOT EXISTS venue_holidays (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  date TEXT NOT NULL,
  name TEXT NOT NULL,
  UNIQUE (venue_id, date)
);
