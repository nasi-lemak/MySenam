-- A second guardian by verified consent (lib/guardian-requests.ts; ADR 0023,
-- amended 27 October 2026; docs/features/venue-operations.md#another-guardian-by-invitation).
--
-- Reception staff no longer make an adult a fully authorised guardian from a
-- name and a number typed at the counter. Another guardian is a request:
-- somebody authorised starts it (a guardian of the participant, or a venue's
-- staff for a participant the venue knows); the proposed guardian is invited
-- with a single-use code they accept signed in to their own MySenam account,
-- declaring their own relationship and authority; an existing guardian
-- agrees online, or a manager records a narrow exception; only then is a
-- relationship (`participant_guardians`) made. A request grants nothing.
-- Who started, who accepted (the account that proved itself by signing in),
-- who agreed or approved the exception, who refused or cancelled: each kept.

CREATE TABLE IF NOT EXISTS guardian_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  participant_id INTEGER NOT NULL REFERENCES participants(id) ON DELETE CASCADE,
  -- invited: the code is out, nobody has accepted it; awaiting_consent: the
  -- proposed guardian accepted, an existing guardian's agreement or a
  -- manager's exception is still needed; active: the relationship was made;
  -- rejected: an existing guardian or a manager refused it; cancelled:
  -- withdrawn, replaced, or its starter stopped acting for the participant.
  status TEXT NOT NULL DEFAULT 'invited' CHECK (status IN ('invited', 'awaiting_consent', 'active', 'rejected', 'cancelled')),
  -- Who started it: a guardian (their own agreement goes with it) or staff.
  initiated_as TEXT NOT NULL CHECK (initiated_as IN ('guardian', 'staff')),
  initiated_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  initiated_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  initiated_by_name TEXT NOT NULL,
  venue_id INTEGER REFERENCES venues(id) ON DELETE SET NULL,
  -- How staff named the adult, to recognise them: never identity.
  proposed_name TEXT CHECK (proposed_name IS NULL OR length(proposed_name) <= 80),
  -- Where staff named the adult's account by its email: only it may accept.
  proposed_user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
  -- The account that accepted the code, signed in, with its own declaration.
  accepted_by_user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
  accepted_at TIMESTAMPTZ,
  relationship TEXT CHECK (relationship IN ('parent', 'guardian', 'other')),
  authority_declared_at TIMESTAMPTZ,
  -- An existing guardian's agreement (for a guardian's own request, the starter's).
  consented_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  consented_by_name TEXT,
  consented_at TIMESTAMPTZ,
  -- The narrow exception, a manager's (or the platform owner's) only: why,
  -- in a category and in words, and when it is to be looked at again. Never
  -- proof of legal guardianship.
  exception_category TEXT CHECK (exception_category IN ('custody_dispute', 'guardian_unavailable', 'safeguarding')),
  exception_reason TEXT,
  exception_review_on DATE,
  exception_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  exception_by_name TEXT,
  exception_at TIMESTAMPTZ,
  -- The exception requires the other guardians not to be told.
  suppress_notice BOOLEAN NOT NULL DEFAULT false,
  guardianship_id INTEGER REFERENCES participant_guardians(id) ON DELETE SET NULL,
  activated_at TIMESTAMPTZ,
  closed_at TIMESTAMPTZ,
  closed_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  closed_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  closed_by_name TEXT,
  close_reason TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (exception_category IS NULL
         OR (exception_reason IS NOT NULL AND exception_review_on IS NOT NULL AND exception_by_name IS NOT NULL AND exception_at IS NOT NULL)),
  CHECK (NOT suppress_notice OR exception_category IS NOT NULL),
  CHECK (status <> 'active' OR (accepted_by_user_id IS NOT NULL AND activated_at IS NOT NULL
                                AND (consented_at IS NOT NULL OR exception_category IS NOT NULL)))
);
CREATE INDEX IF NOT EXISTS idx_guardian_requests_participant ON guardian_requests (participant_id);
CREATE INDEX IF NOT EXISTS idx_guardian_requests_accepted ON guardian_requests (accepted_by_user_id) WHERE accepted_by_user_id IS NOT NULL;
-- One open acceptance per adult and participant.
CREATE UNIQUE INDEX IF NOT EXISTS uq_guardian_requests_open ON guardian_requests (participant_id, accepted_by_user_id)
  WHERE status = 'awaiting_consent';

-- Codes staff give out too, for a request: who gave it, by name as it was.
ALTER TABLE participant_invites ALTER COLUMN created_by_user_id DROP NOT NULL;
ALTER TABLE participant_invites ADD COLUMN IF NOT EXISTS created_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL;
ALTER TABLE participant_invites ADD COLUMN IF NOT EXISTS created_by_name TEXT;
ALTER TABLE participant_invites ADD COLUMN IF NOT EXISTS request_id INTEGER REFERENCES guardian_requests(id) ON DELETE CASCADE;

-- A relationship made by a request points at it. A relationship can be
-- paused (suspended) by a manager while a reported mistake is looked at: it
-- acts for nobody until restored or revoked. And one can be flagged for a
-- manager's review: made by the round-3 counter shortcut, reported as a
-- mistake by another guardian, or made by an exception.
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS request_id INTEGER REFERENCES guardian_requests(id) ON DELETE SET NULL;
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS suspended_at TIMESTAMPTZ;
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS suspended_by_name TEXT;
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS suspend_reason TEXT;
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS review_reason TEXT
  CHECK (review_reason IS NULL OR review_reason IN ('counter-shortcut', 'reported', 'exception'));
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS review_flagged_at TIMESTAMPTZ;
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS review_note TEXT;
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS reviewed_at TIMESTAMPTZ;
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS reviewed_by_name TEXT;
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS review_outcome TEXT;
CREATE INDEX IF NOT EXISTS idx_participant_guardians_review ON participant_guardians (participant_id)
  WHERE review_reason IS NOT NULL AND reviewed_at IS NULL;

-- The round-3 counter shortcut (addGuardianAtVenue, 26 October 2026) made
-- another adult a guardian at once, on a declaration staff typed in. Any
-- relationship it made stays as it is (nobody loses a relationship they
-- hold) but is flagged for a manager to confirm, suspend or revoke: a
-- `counter` relationship that is not the one recorded with the participant
-- when the venue added them, or that a staff member added to an existing
-- participant (a `guardian.added` entry by staff in its history).
UPDATE participant_guardians g
   SET review_reason = 'counter-shortcut', review_flagged_at = now(),
       review_note = 'Added at the counter on a declaration made to staff, before invitation and consent were required (migration 0152).'
 WHERE g.provenance = 'counter' AND g.revoked_at IS NULL AND g.review_reason IS NULL
   AND (g.user_id IS NOT NULL
        OR g.id > (SELECT MIN(o.id) FROM participant_guardians o WHERE o.participant_id = g.participant_id)
        OR EXISTS (SELECT 1 FROM participant_events e
                    WHERE e.participant_id = g.participant_id AND e.action = 'guardian.added' AND e.actor_user_id IS NULL
                      AND e.created_at >= g.created_at - interval '1 minute' AND e.created_at <= g.created_at + interval '1 minute'));
