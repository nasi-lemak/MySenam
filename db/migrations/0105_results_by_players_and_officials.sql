-- Who enters a tournament's results (lib/match-reports.ts): its staff, as
-- before; or the players, one side reporting and the other confirming, with
-- disputes going to staff. Officials (referees) enter results through a link
-- of their own, which staff can withdraw.
ALTER TABLE tournaments ADD COLUMN IF NOT EXISTS results_by TEXT NOT NULL DEFAULT 'staff' CHECK (results_by IN ('staff', 'players'));

CREATE TABLE IF NOT EXISTS tournament_reports (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournament_id INTEGER NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
  match_id INTEGER NOT NULL REFERENCES tournament_matches(id) ON DELETE CASCADE,
  -- The side that reported it, and the account that did.
  entry_id INTEGER NOT NULL REFERENCES tournament_entries(id),
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  -- Null for a draw, where the rules allow one.
  winner INTEGER REFERENCES tournament_entries(id),
  score TEXT,
  walkover INTEGER NOT NULL DEFAULT 0,
  -- pending: waiting for the other side; confirmed; disputed (staff decide);
  -- superseded (staff or an official entered the result instead).
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'disputed', 'superseded')),
  dispute_note TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  answered_at TEXT
);
-- One report waiting on a match at a time.
CREATE UNIQUE INDEX IF NOT EXISTS uq_tournament_report_open ON tournament_reports(match_id) WHERE status IN ('pending', 'disputed');

-- Who entered each result: "staff", "players" (confirmed by both sides) or "official: <name>".
ALTER TABLE tournament_matches ADD COLUMN IF NOT EXISTS result_by TEXT;

CREATE TABLE IF NOT EXISTS tournament_officials (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournament_id INTEGER NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  -- Only the SHA-256 of the link's secret is kept; the link is shown once.
  token_hash TEXT NOT NULL UNIQUE,
  created_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  revoked_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_tournament_officials_t ON tournament_officials(tournament_id);

-- Box leagues scored and ranked by the competition rules (lib/tournament-rules.ts):
-- a league stored without them reads as the defaults, how its boxes were ranked before.
ALTER TABLE leagues ADD COLUMN IF NOT EXISTS rules TEXT;
ALTER TABLE leagues ADD COLUMN IF NOT EXISTS template TEXT;
