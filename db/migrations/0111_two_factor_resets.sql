-- Two-factor sign-in reset for staff who lost both their authenticator and
-- their recovery codes: who reset whose, why (how they knew it was really
-- that person), and when. By another account with authority over it, or by
-- the server's console for the last platform owner.
CREATE TABLE IF NOT EXISTS two_factor_resets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id INTEGER NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
  reset_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  by_console BOOLEAN NOT NULL DEFAULT false,
  reason TEXT NOT NULL CHECK (length(trim(reason)) >= 10),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (by_console OR reset_by IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_two_factor_resets_admin ON two_factor_resets(admin_id);
