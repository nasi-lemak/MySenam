-- Company and school accounts, audit 9 (C5, C6, C7; docs/features/payments-and-credit.md#company-and-school-accounts,
-- ADR 0061). Nothing here rewrites a past invoice, credit note or receipt: rows are added, and what was stored is read as before.
--
-- C6: a credit note is taken off invoices part by part. One row per allocation says which credit, which invoice, how much,
-- by whom and when; a credit's waiting balance is its amount less its allocations. `account_credits.applied_invoice_id`
-- is no longer written (a credit applied whole before this was copied below, and is read from here); an invoice withdrawn
-- takes its allocations with it, so what it had taken waits again, as before.
CREATE TABLE IF NOT EXISTS account_credit_allocations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  credit_id INTEGER NOT NULL REFERENCES account_credits(id) ON DELETE CASCADE,
  invoice_id INTEGER NOT NULL REFERENCES account_invoices(id) ON DELETE CASCADE,
  amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  -- Who issued the invoice that took it (NULL, with a name saying so, for the scheduler and for history).
  allocated_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  allocated_by_name TEXT NOT NULL DEFAULT 'scheduled invoicing',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_account_credit_allocations_credit ON account_credit_allocations (credit_id);
CREATE INDEX IF NOT EXISTS idx_account_credit_allocations_invoice ON account_credit_allocations (invoice_id);

INSERT INTO account_credit_allocations (credit_id, invoice_id, amount, allocated_by_name, created_at)
SELECT c.id, c.applied_invoice_id, c.amount, 'before allocations were recorded', c.created_at
  FROM account_credits c
 WHERE c.applied_invoice_id IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM account_credit_allocations a WHERE a.credit_id = c.id);

-- What was still waiting when a manager paid it back by hand (the credit's balance at that moment).
ALTER TABLE account_credits ADD COLUMN IF NOT EXISTS settled_amount NUMERIC(12,2);
-- A credit note for a booking on an issued invoice moved to a cheaper court or time: the invoice stays as issued.
ALTER TABLE account_credits ADD COLUMN IF NOT EXISTS for_adjustment BOOLEAN NOT NULL DEFAULT false;

-- C6: an invoice part-paid. One row per amount received, how, by whom and when; the invoice is paid (`paid_on`) when what
-- was received and the credit notes taken off cover it.
CREATE TABLE IF NOT EXISTS account_invoice_payments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id INTEGER NOT NULL REFERENCES account_invoices(id) ON DELETE CASCADE,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  via TEXT NOT NULL CHECK (via IN ('cash', 'qr', 'transfer', 'card')),
  received_on TEXT NOT NULL,
  received_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  received_by_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_account_invoice_payments_invoice ON account_invoice_payments (invoice_id);

-- C5: what the account was charged for each booking when its invoice was issued. The invoice's lines, and what a later
-- cancellation gives back, read this and never the booking's live price. For invoices issued before this, the booking's
-- price as it stands now is the best that is known.
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS invoiced_amount NUMERIC(12,2);
UPDATE bookings SET invoiced_amount = GREATEST(0, total_price - shares_paid) WHERE account_invoice_id IS NOT NULL AND invoiced_amount IS NULL;

-- C7: after how many days overdue an account's invoice stops new bookings on it (NULL = never, as before), and the
-- reminders sent to the account for an invoice past its day.
ALTER TABLE venues ADD COLUMN IF NOT EXISTS company_overdue_block_days INTEGER CHECK (company_overdue_block_days IS NULL OR company_overdue_block_days BETWEEN 1 AND 365);
ALTER TABLE account_invoices ADD COLUMN IF NOT EXISTS overdue_reminders INTEGER NOT NULL DEFAULT 0;
ALTER TABLE account_invoices ADD COLUMN IF NOT EXISTS overdue_reminded_on TEXT;
