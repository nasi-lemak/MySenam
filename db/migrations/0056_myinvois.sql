-- Malaysia's e-invoicing (LHDN MyInvois). A venue that has to, or wants to,
-- sends its sales to LHDN: a consolidated e-invoice each month for customers
-- who did not ask for one of their own, and an e-invoice of their own for
-- those who did.

-- Who the venue is to LHDN, and how MySenam reaches MyInvois for it: its own
-- ERP client credentials, or the platform's as its intermediary.
CREATE TABLE IF NOT EXISTS einvoice_settings (
  venue_id INTEGER PRIMARY KEY REFERENCES venues(id) ON DELETE CASCADE,
  enabled INTEGER NOT NULL DEFAULT 0,
  sandbox INTEGER NOT NULL DEFAULT 1,
  mode TEXT NOT NULL DEFAULT 'own' CHECK (mode IN ('own', 'intermediary')),
  client_id TEXT,
  -- Sealed (lib/secrets.ts), never shown back.
  client_secret TEXT,
  tin TEXT,
  brn TEXT,
  msic_code TEXT,
  msic_name TEXT,
  legal_name TEXT,
  address_line TEXT,
  city TEXT,
  postcode TEXT,
  state_code TEXT,
  phone TEXT,
  email TEXT,
  updated_at TEXT NOT NULL DEFAULT datetime('now')
);

-- Each document sent, or to be sent, and what LHDN made of it.
CREATE TABLE IF NOT EXISTS e_invoices (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('consolidated', 'consolidated_credit', 'individual')),
  -- 01 invoice, 02 credit note.
  type_code TEXT NOT NULL,
  -- Ours, unique at the venue: CON-2026-10, CCN-2026-10, EI-MS-ABC123.
  code_number TEXT NOT NULL,
  -- A consolidated one: the month it covers.
  period TEXT,
  -- An individual one: the receipt it is for (its address ref, and its printed number).
  receipt_ref TEXT,
  receipt_number TEXT,
  -- The buyer, for an individual one, as they gave it.
  buyer TEXT,
  total NUMERIC(12,2) NOT NULL DEFAULT 0,
  document TEXT,
  submission_uid TEXT,
  uuid TEXT,
  long_id TEXT,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'submitted', 'valid', 'invalid', 'failed')),
  error TEXT,
  -- A credit note: the e-invoice it corrects.
  refers_uuid TEXT,
  refers_code TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  submitted_at TEXT,
  checked_at TEXT,
  UNIQUE (venue_id, code_number)
);
CREATE INDEX IF NOT EXISTS e_invoices_venue ON e_invoices (venue_id, created_at);
