-- Who a venue is for.
--   public:  anybody can find it and book (the default, as before).
--   members: bookings need a membership or a place on its list; it may still
--            be found in search (access_listed), so new members can find it.
--   private: absent from every public list; only people on its list (and its
--            staff) can open it, e.g. a condominium's courts, pool or gym.
ALTER TABLE venues ADD COLUMN IF NOT EXISTS access TEXT NOT NULL DEFAULT 'public'
  CHECK (access IN ('public', 'members', 'private'));
ALTER TABLE venues ADD COLUMN IF NOT EXISTS access_listed INTEGER NOT NULL DEFAULT 1;
-- What a visitor who is not on the list is told: how to join, who to ask.
ALTER TABLE venues ADD COLUMN IF NOT EXISTS access_note TEXT;

-- The people a members-only or private venue lets in, by phone number. A
-- resident or member stays until removed; a guest until expires_on.
CREATE TABLE IF NOT EXISTS venue_access_list (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  phone TEXT NOT NULL,
  phone_key TEXT GENERATED ALWAYS AS (phone_key(phone)) STORED,
  name TEXT,
  -- Unit number, membership number: whatever the venue knows them by.
  label TEXT,
  kind TEXT NOT NULL DEFAULT 'resident' CHECK (kind IN ('resident', 'member', 'guest')),
  expires_on TEXT,
  added_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  UNIQUE (venue_id, phone_key)
);
CREATE INDEX IF NOT EXISTS idx_venue_access_phone ON venue_access_list (phone_key);
