-- Guardians a venue recorded by name and number only (ADR 0023, amended
-- 27 October 2026 a second time; lib/contact-guardians.ts;
-- docs/features/venue-operations.md#guardians-without-an-account).
--
-- A name and a number typed at a counter grant nothing by themselves. What
-- this adds is a way for such a guardian to take part in the safeguards
-- the guardians with an account already have, each through the venue's
-- staff and each proved:
--
-- * A one-time code sent to the number recorded for them (through the
--   install's existing phone-check delivery: SMS, or WhatsApp's
--   authentication template), carrying the code and the venue's name and
--   nothing about the child, read back to staff at the counter: their
--   agreement to another adult's request, their own withdrawal, or simply
--   that the number reaches them. Only its keyed hash is kept.
-- * Once a code has come back from the number, the number is known to
--   reach them (`contact_verified_at`), and only then may a notice go to it.
-- * A guardian who registers later takes over their own relationship (the
--   same row, its history kept), proving the recorded number on their
--   account and with a single-use code staff (or another guardian) gave.

CREATE TABLE IF NOT EXISTS guardian_contact_codes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guardianship_id INTEGER NOT NULL REFERENCES participant_guardians(id) ON DELETE CASCADE,
  participant_id INTEGER NOT NULL REFERENCES participants(id) ON DELETE CASCADE,
  -- agree: to a request (request_id); withdraw: their own relationship; verify: that the number reaches them.
  purpose TEXT NOT NULL CHECK (purpose IN ('agree', 'withdraw', 'verify')),
  request_id INTEGER REFERENCES guardian_requests(id) ON DELETE CASCADE,
  venue_id INTEGER REFERENCES venues(id) ON DELETE SET NULL,
  -- The number it went to, as sent (digits with the country code), for the daily limits.
  number TEXT NOT NULL,
  code_hash TEXT NOT NULL,
  channel TEXT NOT NULL CHECK (channel IN ('sms', 'whatsapp', 'log')),
  sent_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  sent_by_name TEXT NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ,
  used_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  used_by_name TEXT,
  cancelled_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (purpose <> 'agree' OR request_id IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_guardian_contact_codes_guardianship ON guardian_contact_codes (guardianship_id, purpose);
CREATE INDEX IF NOT EXISTS idx_guardian_contact_codes_number ON guardian_contact_codes (number, created_at);

-- The number recorded for a guardian without an account reached them: a code
-- sent to it came back to staff (which number, in case it is changed later).
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS contact_verified_at TIMESTAMPTZ;
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS contact_verified_number TEXT;
-- A guardian recorded by name and number who later registered took the
-- relationship over: the same row now carries their account; the name and
-- number staff recorded stay, as the history of how it began.
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS claimed_at TIMESTAMPTZ;
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS claim_method TEXT
  CHECK (claim_method IS NULL OR claim_method IN ('staff_code', 'guardian_code'));
ALTER TABLE participant_guardians ADD COLUMN IF NOT EXISTS claim_code_by_name TEXT;
-- A relationship made on an agreement a manager recorded in person, where no
-- code could be sent: flagged for review like an exception's.
ALTER TABLE participant_guardians DROP CONSTRAINT IF EXISTS participant_guardians_review_reason_check;
ALTER TABLE participant_guardians ADD CONSTRAINT participant_guardians_review_reason_check
  CHECK (review_reason IS NULL OR review_reason IN ('counter-shortcut', 'reported', 'exception', 'in-person-agreement'));

-- A code to take over a guardian's relationship recorded by name and number
-- (`claim`): from staff, for that one relationship (`guardianship_id`), or
-- from another guardian with an account, for the relationship whose number
-- the accepting account proved.
ALTER TABLE participant_invites DROP CONSTRAINT IF EXISTS participant_invites_purpose_check;
ALTER TABLE participant_invites ADD CONSTRAINT participant_invites_purpose_check CHECK (purpose IN ('guardian', 'link', 'claim'));
ALTER TABLE participant_invites ADD COLUMN IF NOT EXISTS guardianship_id INTEGER REFERENCES participant_guardians(id) ON DELETE CASCADE;
