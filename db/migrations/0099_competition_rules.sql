-- How a competition treats somebody who leaves it, and corrections made
-- after its knockout has begun (docs/features/programmes.md#tournaments).

-- Each tournament's own rules, as JSON (lib/tournament-rules.ts); null is
-- the defaults, which is what every tournament before this used.
ALTER TABLE tournaments ADD COLUMN IF NOT EXISTS rules TEXT;

-- Why an entrant is out, and when: withdrew, retired (stopped playing,
-- injured), or was disqualified; before the draw, in the groups, or in the
-- knockout. The entry's status stays 'withdrawn' for all three.
ALTER TABLE tournament_entries ADD COLUMN IF NOT EXISTS out_reason TEXT CHECK (out_reason IN ('withdrawn', 'retired', 'disqualified'));
ALTER TABLE tournament_entries ADD COLUMN IF NOT EXISTS out_stage TEXT CHECK (out_stage IN ('before_draw', 'groups', 'knockout'));
ALTER TABLE tournament_entries ADD COLUMN IF NOT EXISTS out_at TEXT;
ALTER TABLE tournament_entries ADD COLUMN IF NOT EXISTS out_note TEXT;
UPDATE tournament_entries SET out_reason = 'withdrawn' WHERE status = 'withdrawn' AND out_reason IS NULL;

-- A match one side stopped playing part-way: decided, the other side through.
DO $$
DECLARE c TEXT;
BEGIN
  FOR c IN SELECT conname FROM pg_constraint
            WHERE conrelid = 'tournament_matches'::regclass AND contype = 'c' AND pg_get_constraintdef(oid) LIKE '%walkover%'
  LOOP
    EXECUTE format('ALTER TABLE tournament_matches DROP CONSTRAINT %I', c);
  END LOOP;
END $$;
ALTER TABLE tournament_matches ADD CONSTRAINT tournament_matches_status_check
  CHECK (status IN ('scheduled', 'done', 'walkover', 'bye', 'retired'));

-- A correction made after the knockout began, by an organiser who saw what it
-- would change and confirmed it: what it changed, what was there before, why.
CREATE TABLE IF NOT EXISTS tournament_corrections (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournament_id INTEGER NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
  match_id INTEGER REFERENCES tournament_matches(id) ON DELETE SET NULL,
  kind TEXT NOT NULL CHECK (kind IN ('replace', 'standings_only')),
  reason TEXT NOT NULL,
  changes TEXT NOT NULL,
  before_state TEXT NOT NULL,
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  admin_name TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_tournament_corrections_t ON tournament_corrections (tournament_id);
