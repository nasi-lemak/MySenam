-- Concession prices (lib/concessions.ts): a student, senior, child or OKU
-- price a venue offers, as a share off. The customer says which at booking and
-- shows proof at the counter. No proof is ever stored: only that staff saw it,
-- by whom, and until when it counts, so a regular is not asked every visit.
CREATE TABLE IF NOT EXISTS concessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  percent INTEGER NOT NULL CHECK (percent BETWEEN 5 AND 100),
  -- What to show at the counter, in the customer's words: "your student card".
  proof TEXT NOT NULL,
  -- One sport, or every sport here.
  sport TEXT,
  off_peak_only SMALLINT NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  retired_at TEXT
);
CREATE INDEX IF NOT EXISTS concessions_venue ON concessions (venue_id);

-- On the booking: which, what it took off, and where the check stands:
-- 'due' (to see at the counter), 'seen', or 'refused' (full price charged).
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS concession_id INTEGER REFERENCES concessions(id) ON DELETE SET NULL;
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS concession_name TEXT;
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS concession_off NUMERIC(12,2) NOT NULL DEFAULT 0;
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS concession_check TEXT CHECK (concession_check IN ('due', 'seen', 'refused'));

-- Proof seen, remembered for a while. The fact only: no image, no card or IC number.
CREATE TABLE IF NOT EXISTS concession_proofs (
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  phone_key TEXT NOT NULL,
  concession_id INTEGER NOT NULL REFERENCES concessions(id) ON DELETE CASCADE,
  seen_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  seen_on TEXT NOT NULL,
  valid_until TEXT NOT NULL,
  PRIMARY KEY (venue_id, phone_key, concession_id)
);
