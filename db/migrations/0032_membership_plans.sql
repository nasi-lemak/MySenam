-- Memberships a club sells online: a name, how many months, the fee.
CREATE TABLE IF NOT EXISTS membership_plans (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  months INTEGER NOT NULL CHECK (months BETWEEN 1 AND 12),
  price NUMERIC(12,2) NOT NULL CHECK (price >= 1),
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  -- No longer offered; memberships already sold on it are unaffected.
  retired_at TEXT
);
CREATE INDEX IF NOT EXISTS membership_plans_venue ON membership_plans (venue_id);

-- Which plan a membership was bought on, when it was bought online.
ALTER TABLE memberships ADD COLUMN IF NOT EXISTS plan_id INTEGER REFERENCES membership_plans(id) ON DELETE SET NULL;

ALTER TABLE online_payments DROP CONSTRAINT IF EXISTS online_payments_purpose_check;
ALTER TABLE online_payments ADD CONSTRAINT online_payments_purpose_check
  CHECK (purpose IN ('booking', 'invoice', 'share', 'entry', 'league', 'pack', 'topup', 'membership'));
ALTER TABLE online_payments ADD COLUMN IF NOT EXISTS membership_plan_id INTEGER REFERENCES membership_plans(id) ON DELETE SET NULL;
-- Who is joining, and the membership the payment made once it is paid.
ALTER TABLE online_payments ADD COLUMN IF NOT EXISTS member_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE online_payments ADD COLUMN IF NOT EXISTS membership_id INTEGER REFERENCES memberships(id) ON DELETE SET NULL;
