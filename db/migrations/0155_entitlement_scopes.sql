-- Benefits by the scope they apply to (ADR 0025; lib/entitlements.ts;
-- docs/features/pricing.md#what-a-benefit-applies-to).
--
-- A pass, a concession or a membership's benefits say what one use of them
-- covers: the booking as a whole (`booking`: a court pass, a venue's
-- concession on the reservation, a member's price for the court), a resource
-- hired whole for its time (`resource`: a package of court hours), one named
-- person's place (`participant`: a child's swim pass, a child's concession),
-- or every place a booking takes (`places`: a pass spending per person). The
-- product or activity it is good for stays what it was: the sport, and a
-- lesson pack's coach.
--
-- Everything already issued keeps what it does today: every pass, concession
-- and plan is `booking`, explicitly, so no issued pass changes its commercial
-- meaning, and no historical redemption, receipt or refund is touched.

ALTER TABLE passes ADD COLUMN IF NOT EXISTS scope TEXT NOT NULL DEFAULT 'booking';
ALTER TABLE passes DROP CONSTRAINT IF EXISTS passes_scope;
ALTER TABLE passes ADD CONSTRAINT passes_scope CHECK (scope IN ('booking', 'resource', 'participant', 'places'));
UPDATE passes SET scope = 'booking' WHERE scope IS DISTINCT FROM 'booking';

-- Whose a pass is, where it is one person's: the number or account holder
-- themself (`customer`, every pass so far), or a participant they act for
-- (`participant`). A participant's record erased leaves the pass covering
-- nobody, never its guardian.
ALTER TABLE passes ADD COLUMN IF NOT EXISTS holder_kind TEXT NOT NULL DEFAULT 'customer';
ALTER TABLE passes DROP CONSTRAINT IF EXISTS passes_holder_kind;
ALTER TABLE passes ADD CONSTRAINT passes_holder_kind CHECK (holder_kind IN ('customer', 'participant'));
ALTER TABLE passes ADD COLUMN IF NOT EXISTS holder_participant_id INTEGER REFERENCES participants(id) ON DELETE SET NULL;
ALTER TABLE passes DROP CONSTRAINT IF EXISTS passes_holder_participant;
ALTER TABLE passes ADD CONSTRAINT passes_holder_participant CHECK (holder_kind = 'participant' OR holder_participant_id IS NULL);
CREATE INDEX IF NOT EXISTS idx_passes_holder_participant ON passes (holder_participant_id) WHERE holder_participant_id IS NOT NULL;

-- A pass spent per place: which place each entry was spent for (a
-- `booking_participants` row; NULL for a booking as a whole, or a place
-- nobody is named on), and which spend a refund or a withdrawal gives back.
-- A spend is given back at most once, by the database.
ALTER TABLE pass_entries ADD COLUMN IF NOT EXISTS place_id INTEGER;
ALTER TABLE pass_entries ADD COLUMN IF NOT EXISTS settles_entry_id INTEGER REFERENCES pass_entries(id) ON DELETE CASCADE;
CREATE UNIQUE INDEX IF NOT EXISTS uq_pass_entries_settles ON pass_entries (settles_entry_id) WHERE settles_entry_id IS NOT NULL;
-- One spend for a named place on a booking, however many requests arrive at once.
CREATE UNIQUE INDEX IF NOT EXISTS uq_pass_entries_place_spend ON pass_entries (booking_id, place_id) WHERE delta < 0 AND place_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_pass_entries_booking ON pass_entries (booking_id) WHERE booking_id IS NOT NULL;

ALTER TABLE concessions ADD COLUMN IF NOT EXISTS scope TEXT NOT NULL DEFAULT 'booking';
ALTER TABLE concessions DROP CONSTRAINT IF EXISTS concessions_scope;
ALTER TABLE concessions ADD CONSTRAINT concessions_scope CHECK (scope IN ('booking', 'participant'));
UPDATE concessions SET scope = 'booking' WHERE scope IS DISTINCT FROM 'booking';

-- Benefits redeemed for one place of a booking: a concession for one
-- person's place, or a member's price for the member's own place. The money
-- each took off the booking's price is kept with it, so taking that place off
-- the booking gives back exactly that. One of each kind per place while it
-- stands, by the database, so neither two requests at once, nor the counter
-- and the customer, nor a group booking can redeem one twice.
CREATE TABLE IF NOT EXISTS place_benefits (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  -- The place: its `booking_participants` row, or NULL for the customer taking
  -- the booking alone. Not a foreign key: a place withdrawn from the booking
  -- leaves its row for the record (place_withdrawals, migration 0157).
  place_id INTEGER,
  participant_id INTEGER REFERENCES participants(id) ON DELETE SET NULL,
  kind TEXT NOT NULL CHECK (kind IN ('concession', 'membership')),
  concession_id INTEGER REFERENCES concessions(id) ON DELETE SET NULL,
  -- As named when redeemed, and its built-in key (`student`), as on bookings.
  concession_name TEXT,
  concession_preset TEXT,
  membership_id INTEGER REFERENCES memberships(id) ON DELETE SET NULL,
  -- Taken off the booking's price for this place.
  amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
  -- A concession's proof at the counter: due, seen, or refused (the full price charged).
  proof_check TEXT CHECK (proof_check IN ('due', 'seen', 'refused')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- Given back: the place withdrawn, or no proof shown.
  reversed_at TIMESTAMPTZ,
  reversed_why TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_place_benefits_live ON place_benefits (booking_id, COALESCE(place_id, 0), kind) WHERE reversed_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_place_benefits_booking ON place_benefits (booking_id);

-- A concession seen for a participant, remembered as one for a number is
-- (concession_proofs): the fact only, never a card or a number off it. Goes
-- with the participant's record.
CREATE TABLE IF NOT EXISTS participant_concession_proofs (
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  participant_id INTEGER NOT NULL REFERENCES participants(id) ON DELETE CASCADE,
  concession_id INTEGER NOT NULL REFERENCES concessions(id) ON DELETE CASCADE,
  seen_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  seen_on TEXT NOT NULL,
  valid_until TEXT NOT NULL,
  PRIMARY KEY (venue_id, participant_id, concession_id)
);
