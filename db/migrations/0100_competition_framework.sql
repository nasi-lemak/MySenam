DECLARE c TEXT;
BEGIN
  FOR c IN SELECT conname FROM pg_constraint
            WHERE conrelid = 'tournaments'::regclass AND contype = 'c' AND pg_get_constraintdef(oid) LIKE '%knockout%'
  LOOP
    EXECUTE format('ALTER TABLE tournaments DROP CONSTRAINT %I', c);
  END LOOP;
END $$;
