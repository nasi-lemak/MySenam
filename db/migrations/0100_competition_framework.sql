-- Heats and finals are scheduled like matches: a court (a pool, a range) for a time.
DO $$
DECLARE c TEXT;
BEGIN
  FOR c IN SELECT conname FROM pg_constraint
            WHERE conrelid = 'tournament_matches'::regclass AND contype = 'c' AND pg_get_constraintdef(oid) LIKE '%group%'
  LOOP
    EXECUTE format('ALTER TABLE tournament_matches DROP CONSTRAINT %I', c);
  END LOOP;
END $$;
ALTER TABLE tournament_matches ADD CONSTRAINT tournament_matches_stage_check
  CHECK (stage IN ('group', 'knockout', 'heat', 'final'));

-- Each competitor's performance in a heat or final: attempts as recorded
-- (null for a foul), the result they make, or why there is none.
CREATE TABLE IF NOT EXISTS tournament_performances (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournament_id INTEGER NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
  match_id INTEGER NOT NULL REFERENCES tournament_matches(id) ON DELETE CASCADE,
  entry_id INTEGER NOT NULL REFERENCES tournament_entries(id),
  lane INTEGER NOT NULL,
  attempts TEXT,
  result NUMERIC(12,3),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'ok', 'dns', 'dnf', 'dq')),
  note TEXT,
  updated_at TEXT,
  UNIQUE (match_id, entry_id),
  UNIQUE (match_id, lane)
);
CREATE INDEX IF NOT EXISTS idx_tournament_performances_t ON tournament_performances (tournament_id);

-- A correction that leaves the wrong competitor in matches already played:
-- open until an organiser resolves it, and the tournament does not finish
-- while it is.
CREATE TABLE IF NOT EXISTS tournament_issues (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournament_id INTEGER NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
  -- The first match the wrong competitor played, or is in, in place of the right one.
  from_match_id INTEGER NOT NULL REFERENCES tournament_matches(id) ON DELETE CASCADE,
  wrong_entry INTEGER NOT NULL REFERENCES tournament_entries(id),
  right_entry INTEGER REFERENCES tournament_entries(id),
  -- What opened it: the correction's reason and what it found.
  reason TEXT NOT NULL,
  affected TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'stood', 'replayed')),
  opened_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  resolved_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  resolution_reason TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  resolved_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_tournament_issues_open ON tournament_issues (tournament_id) WHERE status = 'open';

-- Corrections now include how an issue was resolved.
DO $$
DECLARE c TEXT;
BEGIN
  FOR c IN SELECT conname FROM pg_constraint
            WHERE conrelid = 'tournament_corrections'::regclass AND contype = 'c' AND pg_get_constraintdef(oid) LIKE '%standings_only%'
  LOOP
    EXECUTE format('ALTER TABLE tournament_corrections DROP CONSTRAINT %I', c);
  END LOOP;
END $$;
ALTER TABLE tournament_corrections ADD CONSTRAINT tournament_corrections_kind_check
  CHECK (kind IN ('replace', 'standings_only', 'stand', 'replay'));

-- A venue's own templates: a tournament's settings kept to start the next one from.
CREATE TABLE IF NOT EXISTS competition_templates (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  sport TEXT NOT NULL REFERENCES activities(key) ON UPDATE CASCADE,
  format TEXT NOT NULL CHECK (format IN ('knockout', 'groups', 'round_robin', 'performance')),
  entry_kind TEXT NOT NULL CHECK (entry_kind IN ('player', 'pair', 'team')),
  roster_min INTEGER,
  roster_max INTEGER,
  match_minutes INTEGER NOT NULL DEFAULT 60,
  group_size INTEGER NOT NULL DEFAULT 4,
  advance INTEGER NOT NULL DEFAULT 2,
  rules TEXT NOT NULL,
  created_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  UNIQUE (venue_id, name)
);
