-- Bookings flagged for staff after a membership stopped covering somebody
-- (lib/membership-flags.ts; docs/features/pricing.md#when-a-membership-stops).
--
-- A membership cancelled at the counter, voided by a chargeback, or a family
-- membership's dependant taken off it: the confirmed bookings from today on,
-- at a members-only venue of its business, that its holder or the people it
-- covered take part in and that it no longer covers, are flagged for staff
-- to decide (cancel on the venue's terms, admit at the desk, or keep), never
-- cancelled silently. The same pattern as a revoked approval's
-- (approval_booking_flags, migration 0125).
CREATE TABLE IF NOT EXISTS membership_booking_flags (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  membership_id INTEGER NOT NULL REFERENCES memberships(id) ON DELETE CASCADE,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  -- Whom it no longer covers on the booking: a participant, or (NULL) the holder's own place.
  participant_id INTEGER REFERENCES participants(id) ON DELETE SET NULL,
  person_name TEXT NOT NULL,
  -- 'cancelled' by staff, 'revoked' by a chargeback, 'uncovered': a dependant taken off a family membership.
  reason TEXT NOT NULL CHECK (reason IN ('cancelled', 'revoked', 'uncovered')),
  -- 'place': a place on a members' session (participation); 'reservation': a resource the holder reserved whole
  -- (a booking privilege, checked when it was made: flagged so staff know, not barred at the door).
  kind TEXT NOT NULL CHECK (kind IN ('place', 'reservation')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  resolved_at TIMESTAMPTZ,
  resolved_by TEXT,
  resolved_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  resolution TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_membership_booking_flags
  ON membership_booking_flags (membership_id, booking_id, COALESCE(participant_id, 0));
CREATE INDEX IF NOT EXISTS idx_membership_booking_flags_open ON membership_booking_flags (venue_id) WHERE resolved_at IS NULL;
