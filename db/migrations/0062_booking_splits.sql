-- Splitting what a booking costs with friends (lib/splits.ts): each pays a share
-- to the venue online through a link, towards the booking; the booker pays the rest.
CREATE TABLE IF NOT EXISTS booking_splits (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL UNIQUE REFERENCES bookings(id) ON DELETE CASCADE,
  -- Ways it is split, the booker's included.
  parts INTEGER NOT NULL CHECK (parts BETWEEN 2 AND 10),
  -- What each friend pays; the booker's part is what is left.
  share NUMERIC(12,2) NOT NULL CHECK (share > 0),
  token TEXT NOT NULL UNIQUE,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);

ALTER TABLE online_payments ADD COLUMN IF NOT EXISTS split_id INTEGER REFERENCES booking_splits(id) ON DELETE SET NULL;
ALTER TABLE online_payments DROP CONSTRAINT IF EXISTS online_payments_purpose_check;
ALTER TABLE online_payments ADD CONSTRAINT online_payments_purpose_check
  CHECK (purpose IN ('booking', 'invoice', 'share', 'entry', 'league', 'pack', 'topup', 'membership', 'voucher', 'split'));
