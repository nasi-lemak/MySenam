-- Moving a class, and a class's instructor as one of the venue's coaches (docs/features/programmes.md).
--
-- 1. A class's instructor may be a coach of the venue. `classes.instructor` stays as the typed name (a venue that wants a
--    name-only instructor keeps one, and no existing class is changed); `classes.coach_id`, where set, is the coach, whose
--    own name is what customers read as the instructor. A coach is never deleted by the app (it retires them), and the
--    reference has no ON DELETE action so a coach teaching a class can never silently lose it.
ALTER TABLE classes ADD COLUMN IF NOT EXISTS coach_id INTEGER REFERENCES coaches(id);
CREATE INDEX IF NOT EXISTS idx_classes_coach ON classes (coach_id) WHERE coach_id IS NOT NULL;

-- 2. A coach in a class is claimed for its time as a coach in a lesson is: the same exclusion constraint keeps a coach in
--    one session at a time, to the minute, whatever the courts. A claim belongs to a booking (a lesson) or to a class.
ALTER TABLE coach_claims ALTER COLUMN booking_id DROP NOT NULL;
ALTER TABLE coach_claims ADD COLUMN IF NOT EXISTS class_id INTEGER REFERENCES classes(id) ON DELETE CASCADE;
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'coach_claims_one_source') THEN
    ALTER TABLE coach_claims ADD CONSTRAINT coach_claims_one_source CHECK ((booking_id IS NULL) <> (class_id IS NULL));
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS idx_coach_claims_class ON coach_claims (class_id);

-- 3. Moving a class (lib/class-moves.ts): one row for each time staff move sessions, with each session's old and new place
--    and time, and (`class_move_offers`) for each enrolment moved the private link by which its customer may cancel for a
--    full refund until `valid_until` (one token is shared by one person's enrolments of one move).
CREATE TABLE IF NOT EXISTS class_moves (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  scope TEXT NOT NULL CHECK (scope IN ('one', 'following', 'term')),
  moved_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  moved_by_name TEXT NOT NULL,
  sessions INTEGER NOT NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_class_moves_venue ON class_moves (venue_id, id);

CREATE TABLE IF NOT EXISTS class_move_sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  move_id INTEGER NOT NULL REFERENCES class_moves(id) ON DELETE CASCADE,
  class_id INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
  from_court_id INTEGER NOT NULL,
  from_date TEXT NOT NULL,
  from_start_min INTEGER NOT NULL,
  from_end_min INTEGER NOT NULL,
  to_court_id INTEGER NOT NULL,
  to_date TEXT NOT NULL,
  to_start_min INTEGER NOT NULL,
  to_end_min INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_class_move_sessions_move ON class_move_sessions (move_id);
CREATE INDEX IF NOT EXISTS idx_class_move_sessions_class ON class_move_sessions (class_id);

CREATE TABLE IF NOT EXISTS class_move_offers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  move_id INTEGER NOT NULL REFERENCES class_moves(id) ON DELETE CASCADE,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  token TEXT NOT NULL,
  -- The end of the window in which the customer may cancel with everything back: the install's window after the move,
  -- or the session's original start if that is sooner.
  valid_until TIMESTAMPTZ NOT NULL,
  cancelled_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_class_move_offers ON class_move_offers (move_id, booking_id);
CREATE INDEX IF NOT EXISTS idx_class_move_offers_token ON class_move_offers (token);
CREATE INDEX IF NOT EXISTS idx_class_move_offers_booking ON class_move_offers (booking_id);

-- Install data (one row, no screen): how long after a move a customer may cancel for everything back.
CREATE TABLE IF NOT EXISTS class_move_rules (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  refund_window_days INTEGER NOT NULL DEFAULT 7 CHECK (refund_window_days BETWEEN 1 AND 60)
);
INSERT INTO class_move_rules (id, refund_window_days) VALUES (1, 7) ON CONFLICT (id) DO NOTHING;
