-- What a venue pays by how many courts and rooms it has. None: every venue
-- pays the marketplace's flat default (MYSENAM_VENUE_FEE), as before. A
-- venue's own monthly_fee still beats both.
CREATE TABLE IF NOT EXISTS plan_tiers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  -- The most resources it covers; NULL on a last tier with no limit.
  up_to INTEGER CHECK (up_to IS NULL OR up_to >= 1),
  monthly_fee NUMERIC(12,2) NOT NULL CHECK (monthly_fee >= 0),
  -- On the last tier only: what each resource past up_to adds.
  extra_each NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (extra_each >= 0)
);

-- What each invoice was worked out from, so a venue can see why it pays
-- what it pays, and a later change of tiers does not rewrite history.
ALTER TABLE venue_invoices ADD COLUMN IF NOT EXISTS plan_name TEXT;
ALTER TABLE venue_invoices ADD COLUMN IF NOT EXISTS resources INTEGER;
ALTER TABLE invoice_lines ADD COLUMN IF NOT EXISTS plan_name TEXT;
ALTER TABLE invoice_lines ADD COLUMN IF NOT EXISTS resources INTEGER;
