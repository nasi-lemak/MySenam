-- The language a booking was made in, so what the venue later tells the
-- customer (a cancellation, a move, a reminder, a receipt) is in it too.
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS locale TEXT;

-- WhatsApp reminders the day before cost a message each, so a venue chooses
-- them; email reminders are always sent.
ALTER TABLE venues ADD COLUMN IF NOT EXISTS whatsapp_reminders INTEGER NOT NULL DEFAULT 0;

-- What happened to a message after it left: WhatsApp reports delivered and
-- read against the id it gave the message; email reports nothing past
-- accepted.
ALTER TABLE messages ADD COLUMN IF NOT EXISTS provider_id TEXT;
ALTER TABLE messages ADD COLUMN IF NOT EXISTS delivered_at TEXT;
ALTER TABLE messages ADD COLUMN IF NOT EXISTS read_at TEXT;
ALTER TABLE messages ADD COLUMN IF NOT EXISTS delivery_error TEXT;
CREATE INDEX IF NOT EXISTS messages_provider ON messages (provider_id);

-- News the customer must not miss: the venue cancelled their booking, or
-- moved it. Open until the customer taps "Seen it" or staff record that they
-- told them some other way.
CREATE TABLE IF NOT EXISTS urgent_notices (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id),
  booking_id INTEGER REFERENCES bookings(id) ON DELETE SET NULL,
  kind TEXT NOT NULL CHECK (kind IN ('cancelled', 'moved')),
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  email TEXT,
  -- When the booking was for, so the soonest come first.
  date TEXT NOT NULL,
  start_hour INTEGER NOT NULL,
  summary TEXT NOT NULL,
  ack_token TEXT NOT NULL UNIQUE,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  acked_at TEXT,
  resolved_at TEXT,
  resolved_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  resolution TEXT CHECK (resolution IN ('acknowledged', 'told'))
);
CREATE INDEX IF NOT EXISTS urgent_notices_open ON urgent_notices (venue_id, resolved_at);

ALTER TABLE messages ADD COLUMN IF NOT EXISTS notice_id INTEGER REFERENCES urgent_notices(id) ON DELETE SET NULL;
