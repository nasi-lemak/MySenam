-- The owner's decisions of 5 November 2026 on court time held for ladder challenges, round two
-- (docs/architecture/decisions/0050-ladder-agreement-counts-and-expired-holds-do-not.md, which amends ADR 0048;
-- docs/features/tournaments.md#court-time-held-by-the-venue-an-optional-setting-per-ladder; lib/ladder-holds.ts):
--   1. an exact time one player proposed and the other explicitly accepted is both players' agreement: the hold is made confirmed, and what each agreed is kept;
--   2. a change the players did not both agree (a manager's move) makes the new hold tentative again, with what changed kept;
--   3. the "holds made in 7 days" creation quota is replaced by an ACTIVE-hold limit per player (holds live now) and a separate ANTI-ABUSE limit
--      (holds a player created and abandoned in a rolling window) whose consequence is a cooldown on creating new holds.
-- Everything is additive. Nothing is deleted or rewritten: an expired or released hold stays in ladder_court_holds as history.

-- ---------------------------------------------------------------- what was agreed, kept as history

-- One row per player per hold made by agreement: the exact specification that player agreed to (the day, the start, the minutes held for the match, and the
-- court that was shown and held). `role` says whether that player proposed it or accepted it.
CREATE TABLE IF NOT EXISTS ladder_agreed_times (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  held_id INTEGER NOT NULL REFERENCES ladder_court_holds(id) ON DELETE CASCADE,
  challenge_id INTEGER NOT NULL REFERENCES ladder_challenges(id) ON DELETE CASCADE,
  player_id INTEGER NOT NULL REFERENCES ladder_players(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('proposed', 'accepted')),
  date TEXT NOT NULL,
  start_min INTEGER NOT NULL,
  minutes INTEGER NOT NULL,
  court_id INTEGER REFERENCES courts(id) ON DELETE SET NULL,
  agreed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (held_id, player_id)
);
CREATE INDEX IF NOT EXISTS idx_ladder_agreed_times_challenge ON ladder_agreed_times (challenge_id);

-- A hold made by exact agreement of both players is confirmed when it is made (confirmed_at set, no confirm-by); this says so.
ALTER TABLE ladder_court_holds ADD COLUMN IF NOT EXISTS agreed_exactly BOOLEAN NOT NULL DEFAULT false;
-- A hold a manager moved (or made where there was none) that the players had not agreed: tentative again, with what it replaced, as JSON
-- ({"date":..,"startMin":..,"minutes":..,"courtId":..,"court":..}), shown to both so each can confirm the new specification.
ALTER TABLE ladder_court_holds ADD COLUMN IF NOT EXISTS changed_from TEXT;

-- ---------------------------------------------------------------- history for abuse detection

-- Who made a hold (the place that acted; NULL for a manager's or one made before this migration), and who abandoned it: set when a hold expired
-- unconfirmed (to the one who made it) or was withdrawn while still tentative (to the one who withdrew it). A hold that was played, released by the
-- venue, moved, forfeited and the rest is never abandoned. Nothing here deletes or edits a hold: it is the record the count reads.
ALTER TABLE ladder_court_holds ADD COLUMN IF NOT EXISTS made_by_place INTEGER;
ALTER TABLE ladder_court_holds ADD COLUMN IF NOT EXISTS abandoned_place INTEGER;
ALTER TABLE ladder_court_holds ADD COLUMN IF NOT EXISTS abandoned_at TIMESTAMPTZ;
CREATE INDEX IF NOT EXISTS idx_ladder_holds_abandoned ON ladder_court_holds (abandoned_place, abandoned_at) WHERE abandoned_at IS NOT NULL;

-- ---------------------------------------------------------------- the two limits: active holds, and abandoned holds

-- (a) ACTIVE-hold limit per player: holds live now (tentative or confirmed, not released, not lapsed). It carries over what the old "holds made in 7 days"
-- cap (`max_per_player_week`, `cap_week`, week_min/week_max) was set to: the same number, now counted over live holds. The old columns stay as they were,
-- as history of what was set, and nothing reads them. Copied once, when the new column is first added, so running this again changes nothing.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'ladder_hold_limits' AND column_name = 'max_active_per_player') THEN
    ALTER TABLE ladder_hold_limits ADD COLUMN max_active_per_player INTEGER NOT NULL DEFAULT 4 CHECK (max_active_per_player >= 1);
    ALTER TABLE ladder_hold_limits ADD COLUMN active_min INTEGER NOT NULL DEFAULT 1 CHECK (active_min >= 1);
    ALTER TABLE ladder_hold_limits ADD COLUMN active_max INTEGER NOT NULL DEFAULT 20 CHECK (active_max <= 50);
    UPDATE ladder_hold_limits SET max_active_per_player = max_per_player_week, active_min = week_min, active_max = week_max;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'venue_ladder_hold_limits' AND column_name = 'max_active_per_player') THEN
    ALTER TABLE venue_ladder_hold_limits ADD COLUMN max_active_per_player INTEGER CHECK (max_active_per_player IS NULL OR max_active_per_player BETWEEN 1 AND 50);
    UPDATE venue_ladder_hold_limits SET max_active_per_player = max_per_player_week;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'ladders' AND column_name = 'cap_active') THEN
    ALTER TABLE ladders ADD COLUMN cap_active INTEGER CHECK (cap_active IS NULL OR cap_active BETWEEN 1 AND 50);
    UPDATE ladders SET cap_active = cap_week;
  END IF;
END
$$;

-- (b) ANTI-ABUSE limit: holds a player created and abandoned in a rolling window. Beyond the threshold a cooldown applies to creating new holds. Install
-- data, with a venue setting and a ladder override for the threshold inside bounds, as the other caps (ADR 0048); the window and the cooldown are install data.
ALTER TABLE ladder_hold_limits ADD COLUMN IF NOT EXISTS abuse_limit INTEGER NOT NULL DEFAULT 6 CHECK (abuse_limit >= 1);
ALTER TABLE ladder_hold_limits ADD COLUMN IF NOT EXISTS abuse_min INTEGER NOT NULL DEFAULT 2 CHECK (abuse_min >= 1);
ALTER TABLE ladder_hold_limits ADD COLUMN IF NOT EXISTS abuse_max INTEGER NOT NULL DEFAULT 50 CHECK (abuse_max <= 200);
ALTER TABLE ladder_hold_limits ADD COLUMN IF NOT EXISTS abuse_window_days INTEGER NOT NULL DEFAULT 7 CHECK (abuse_window_days BETWEEN 1 AND 90);
ALTER TABLE ladder_hold_limits ADD COLUMN IF NOT EXISTS abuse_cooldown_hours INTEGER NOT NULL DEFAULT 24 CHECK (abuse_cooldown_hours BETWEEN 1 AND 720);
ALTER TABLE venue_ladder_hold_limits ADD COLUMN IF NOT EXISTS abuse_limit INTEGER CHECK (abuse_limit IS NULL OR abuse_limit BETWEEN 1 AND 200);
ALTER TABLE ladders ADD COLUMN IF NOT EXISTS cap_abuse INTEGER CHECK (cap_abuse IS NULL OR cap_abuse BETWEEN 1 AND 200);
