-- A guardian's authorisation to show a child's full name on public pages
-- (docs/architecture/privacy.md#minors-names-on-public-pages; lib/public-name-consents.ts).
--
-- By default a declared minor is shown by first name and the initial of the next on every public page, public API
-- payload and notice to another family (lib/public-names.ts). The one exception is this: the account that manages the
-- participant (ADR 0022) may allow their full name on public pages, for one event (a tournament; a league's or a
-- ladder's current season) or for all the child's competitive entries at one venue for 12 months. It is recorded as the
-- guardian declared it (who, when, what scope, the wording they were shown, in the language they saw it), is never
-- implied by entering, never collected from the child and never offered to a venue to tick on a guardian's behalf, and
-- is withdrawn by the guardian at once: nothing reads it but a live query, so a withdrawal is in force on the next request.
-- Where it stops applying (revoked, past `expires_at`, the event or season over, the guardian no longer managing the child)
-- the child is shown short again, with no step of anybody's.
CREATE TABLE IF NOT EXISTS public_name_consents (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  participant_id INTEGER NOT NULL REFERENCES participants(id) ON DELETE CASCADE,
  -- The guardian's account; the authorisation applies only while this account still manages the participant.
  granted_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  -- 'event': this tournament, or this league's or ladder's season (`season_id`); 'venue': every competitive entry at the venue.
  scope TEXT NOT NULL CHECK (scope IN ('event', 'venue')),
  event_kind TEXT CHECK (event_kind IS NULL OR event_kind IN ('tournament', 'league', 'ladder')),
  event_id INTEGER,
  -- A league's or ladder's season the authorisation was given for: it ends with that season.
  season_id INTEGER,
  -- The wording the guardian saw, as shown, and the language it was shown in.
  wording TEXT NOT NULL,
  wording_locale TEXT NOT NULL,
  granted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- The latest it can apply: the event's last day, or twelve months for a venue; a season's end can come sooner.
  expires_at TIMESTAMPTZ NOT NULL,
  revoked_at TIMESTAMPTZ,
  CHECK ((scope = 'event') = (event_kind IS NOT NULL AND event_id IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_public_name_consents_participant ON public_name_consents (participant_id, venue_id) WHERE revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_public_name_consents_user ON public_name_consents (granted_by_user_id);
