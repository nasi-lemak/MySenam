-- Stars and a few words from somebody who played (lib/reviews.ts): one per
-- phone number per venue, written again rather than added to.
CREATE TABLE IF NOT EXISTS venue_reviews (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  booking_id INTEGER REFERENCES bookings(id) ON DELETE SET NULL,
  phone_key TEXT NOT NULL,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  -- As shown: a first name and an initial.
  author TEXT NOT NULL,
  rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
  body TEXT,
  played_on TEXT NOT NULL,
  locale TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  updated_at TEXT NOT NULL DEFAULT datetime('now'),
  -- The venue's public answer.
  reply TEXT,
  replied_at TEXT,
  -- The venue asking the platform to look at it, and the platform's decision.
  reported_at TEXT,
  report_reason TEXT,
  hidden_at TEXT,
  hidden_reason TEXT,
  UNIQUE (venue_id, phone_key)
);
CREATE INDEX IF NOT EXISTS venue_reviews_venue ON venue_reviews (venue_id, updated_at);

-- Whether customers are emailed once, after their first visit, asking how it was.
ALTER TABLE venues ADD COLUMN IF NOT EXISTS review_requests INTEGER NOT NULL DEFAULT 1;
