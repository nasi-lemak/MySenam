-- A link to set a new password, emailed on request. Only a keyed hash of the
-- token is kept; it works once, for 30 minutes.
CREATE TABLE IF NOT EXISTS password_resets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL CHECK (kind IN ('user', 'admin')),
  account_id INTEGER NOT NULL,
  token_hash TEXT NOT NULL UNIQUE,
  expires_at TEXT NOT NULL,
  used_at TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS password_resets_account ON password_resets (kind, account_id, created_at);
