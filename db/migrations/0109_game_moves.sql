-- Moving an open game's booking to another time (lib/game-moves.ts).
--
-- A game with players in it moves only as an explicit change: proposed by
-- its host and agreed by each player (or left by them), or made by a venue
-- manager with a reason. Either way it is kept here, with what it moved from
-- and to, and who decided.
CREATE TABLE IF NOT EXISTS game_moves (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_id INTEGER NOT NULL REFERENCES open_games(id) ON DELETE CASCADE,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  -- 'proposal': the host's, waiting for the players; 'venue': a manager's, made at once.
  kind TEXT NOT NULL CHECK (kind IN ('proposal', 'venue')),
  host_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  reason TEXT,
  from_date TEXT NOT NULL,
  from_start_min INTEGER NOT NULL,
  from_end_min INTEGER NOT NULL,
  from_court_id INTEGER REFERENCES courts(id) ON DELETE SET NULL,
  to_date TEXT NOT NULL,
  to_start_min INTEGER NOT NULL,
  to_end_min INTEGER NOT NULL,
  to_court_id INTEGER REFERENCES courts(id) ON DELETE SET NULL,
  -- What the court time's price changed by when it moved (an unpaid booking is repriced).
  price_change NUMERIC(12,2) NOT NULL DEFAULT 0,
  status TEXT NOT NULL CHECK (status IN ('pending', 'applied', 'withdrawn', 'expired', 'failed')),
  -- A proposal's hold on the new time lasts until then.
  expires_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  decided_at TIMESTAMPTZ,
  -- Why it ended as it did, in words (a failed proposal: what was in the way).
  outcome TEXT,
  CHECK (to_end_min > to_start_min AND from_end_min > from_start_min),
  CHECK ((kind = 'venue') = (admin_id IS NOT NULL)),
  CHECK (kind <> 'venue' OR reason IS NOT NULL)
);
-- One change waiting at a time for a game.
CREATE UNIQUE INDEX IF NOT EXISTS idx_game_moves_pending ON game_moves(game_id) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS idx_game_moves_expiring ON game_moves(expires_at) WHERE status = 'pending';

-- Each player's answer to a change: kept, never rewritten.
CREATE TABLE IF NOT EXISTS game_move_answers (
  move_id INTEGER NOT NULL REFERENCES game_moves(id) ON DELETE CASCADE,
  player_id INTEGER NOT NULL REFERENCES open_game_players(id) ON DELETE CASCADE,
  answer TEXT NOT NULL CHECK (answer IN ('yes', 'left')),
  answered_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (move_id, player_id)
);

-- A player in the game asked about a change and not yet answered: the
-- proposal waiting for them, or the venue's change they have not confirmed.
ALTER TABLE open_game_players ADD COLUMN IF NOT EXISTS move_id INTEGER REFERENCES game_moves(id) ON DELETE SET NULL;

-- Where and when a game was, kept once it is called off: the booking under
-- it may move afterwards, and the game's record should not move with it.
ALTER TABLE open_games ADD COLUMN IF NOT EXISTS was_date TEXT;
ALTER TABLE open_games ADD COLUMN IF NOT EXISTS was_start_min INTEGER;
ALTER TABLE open_games ADD COLUMN IF NOT EXISTS was_end_min INTEGER;
ALTER TABLE open_games ADD COLUMN IF NOT EXISTS was_court_id INTEGER REFERENCES courts(id) ON DELETE SET NULL;

-- A proposal holds the new time on the court, as a waiting-list offer does,
-- until it is agreed, withdrawn or runs out: a claim of its own kind.
ALTER TABLE claims ADD COLUMN IF NOT EXISTS move_id INTEGER REFERENCES game_moves(id) ON DELETE CASCADE;
ALTER TABLE claims DROP CONSTRAINT IF EXISTS claims_kind_check;
ALTER TABLE claims ADD CONSTRAINT claims_kind_check CHECK (kind IN ('booking', 'offer', 'class', 'block', 'outage', 'move'));
ALTER TABLE claims ADD CONSTRAINT claims_move_source CHECK ((kind = 'move') = (move_id IS NOT NULL));
CREATE INDEX IF NOT EXISTS idx_claims_move ON claims(move_id) WHERE move_id IS NOT NULL;
