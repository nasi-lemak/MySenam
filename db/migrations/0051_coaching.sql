-- One-to-one coaching: a venue's coaches, the hours each takes lessons, and
-- the lessons booked. A lesson is a court booking with a coach on it, the
-- coach's fee on top of the court's price.
CREATE TABLE IF NOT EXISTS coaches (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  bio TEXT,
  -- Comma-separated sports they coach.
  sports TEXT NOT NULL,
  -- Per hour, on top of the court.
  rate NUMERIC(12,2) NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS coaches_venue ON coaches (venue_id);

-- When each takes lessons, week by week: weekday 0 is Sunday.
CREATE TABLE IF NOT EXISTS coach_hours (
  coach_id INTEGER NOT NULL REFERENCES coaches(id) ON DELETE CASCADE,
  weekday INTEGER NOT NULL CHECK (weekday BETWEEN 0 AND 6),
  from_hour DOUBLE PRECISION NOT NULL,
  until_hour DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS coach_hours_coach ON coach_hours (coach_id);

-- A coach is in one place at a time: one row per slot of each lesson, so two
-- lessons cannot take the same coach at once, whatever courts they are on.
CREATE TABLE IF NOT EXISTS coach_slots (
  coach_id INTEGER NOT NULL REFERENCES coaches(id) ON DELETE CASCADE,
  date TEXT NOT NULL,
  hour DOUBLE PRECISION NOT NULL,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  PRIMARY KEY (coach_id, date, hour)
);

ALTER TABLE bookings ADD COLUMN IF NOT EXISTS coach_id INTEGER REFERENCES coaches(id) ON DELETE SET NULL;
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS coach_fee NUMERIC(12,2) NOT NULL DEFAULT 0;
