-- CLSB: a lesson's time moved by staff, and an attendance register (docs/features/programmes.md, ADR 0042).
--
-- 1. A coached lesson moved by staff (lib/lesson-venue-moves.ts): each move is recorded with where the lesson was and is, what the
--    new time would have cost against the agreed price (kept, never charged or refunded without a manager's explicit adjustment),
--    who moved it, and the window in which its customer may cancel with everything back because the venue moved it. Two venue
--    settings, install data per venue: how many days that window is, and how many days after a session its register stays
--    editable by the instructor and the desk.
ALTER TABLE venues ADD COLUMN IF NOT EXISTS lesson_move_refund_days INTEGER NOT NULL DEFAULT 7;
ALTER TABLE venues ADD COLUMN IF NOT EXISTS attendance_lock_days INTEGER NOT NULL DEFAULT 14;
ALTER TABLE venues DROP CONSTRAINT IF EXISTS venues_lesson_move_refund_days_check;
ALTER TABLE venues ADD CONSTRAINT venues_lesson_move_refund_days_check CHECK (lesson_move_refund_days BETWEEN 0 AND 60);
ALTER TABLE venues DROP CONSTRAINT IF EXISTS venues_attendance_lock_days_check;
ALTER TABLE venues ADD CONSTRAINT venues_attendance_lock_days_check CHECK (attendance_lock_days BETWEEN 0 AND 365);

CREATE TABLE IF NOT EXISTS lesson_moves (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  venue_id INTEGER NOT NULL REFERENCES venues(id),
  from_date TEXT NOT NULL,
  from_start_min INTEGER NOT NULL,
  from_end_min INTEGER NOT NULL,
  from_court_id INTEGER,
  to_date TEXT NOT NULL,
  to_start_min INTEGER NOT NULL,
  to_end_min INTEGER NOT NULL,
  to_court_id INTEGER,
  -- The price as agreed, which stays; and what the court time at the new time comes to against it (positive: dearer, negative:
  -- cheaper). Staff saw it before moving; changing the price is a manager's logged price adjustment (lib/price-adjustments.ts).
  price_kept NUMERIC(12,2) NOT NULL DEFAULT 0,
  price_difference NUMERIC(12,2) NOT NULL DEFAULT 0,
  moved_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  moved_by_name TEXT NOT NULL,
  moved_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- The customer may cancel with everything back until here: the venue's days after the move, or the lesson's old time if sooner
  -- (never past the new start).
  window_ends_at TIMESTAMPTZ NOT NULL,
  -- When the customer took it: the lesson cancelled, all of it back through the venue's own refund paths.
  cancelled_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_lesson_moves_booking ON lesson_moves (booking_id, id DESC);

-- A counter payment owed back after a customer took the venue-moved lesson's refund is owed back like any the venue cancelled.
ALTER TABLE counter_refunds_owed DROP CONSTRAINT IF EXISTS counter_refunds_owed_cause_check;
ALTER TABLE counter_refunds_owed ADD CONSTRAINT counter_refunds_owed_cause_check
  CHECK (cause IN ('closure', 'outage', 'rain', 'api', 'class', 'test', 'lesson_moved'));

-- 2. Attendance registers (lib/attendance.ts). A session is a class's session (`classes.id`) or a coached lesson (`bookings.id`):
--    both ids survive a move, so a register stays with its session. A mark is the instructor's or the desk's record of who came;
--    declared, never verified, and nothing else reads it: no money, pass, rating, result or level.
CREATE TABLE IF NOT EXISTS attendance_sessions (
  kind TEXT NOT NULL CHECK (kind IN ('class', 'lesson')),
  session_id INTEGER NOT NULL,
  venue_id INTEGER NOT NULL REFERENCES venues(id),
  session_date TEXT NOT NULL,
  -- A manager closed the register: from then only a manager corrects it, with a reason.
  locked_at TIMESTAMPTZ,
  locked_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  locked_by_name TEXT,
  PRIMARY KEY (kind, session_id)
);
CREATE INDEX IF NOT EXISTS idx_attendance_sessions_date ON attendance_sessions (session_date);

CREATE TABLE IF NOT EXISTS attendance_marks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL CHECK (kind IN ('class', 'lesson')),
  session_id INTEGER NOT NULL,
  venue_id INTEGER NOT NULL REFERENCES venues(id),
  session_date TEXT NOT NULL,
  -- Who: 'c:<booking id>' the booking's own customer, 'p:<booking id>:<participant id>' a person booked for, 'w:<n>' a walk-in.
  person_key TEXT NOT NULL,
  booking_id INTEGER REFERENCES bookings(id) ON DELETE SET NULL,
  participant_id INTEGER REFERENCES participants(id) ON DELETE SET NULL,
  -- The account whose own place it was (a customer sees their own history by it); never set for a child's place.
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  walk_in_name TEXT,
  mark TEXT NOT NULL CHECK (mark IN ('present', 'absent', 'late', 'excused')),
  note TEXT,
  marked_by_kind TEXT NOT NULL CHECK (marked_by_kind IN ('staff', 'coach')),
  marked_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  marked_by_coach_id INTEGER REFERENCES coaches(id) ON DELETE SET NULL,
  marked_by_name TEXT NOT NULL,
  marked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- The person's account or record was erased: the mark is kept as a count, naming nobody.
  anonymised_at TIMESTAMPTZ,
  UNIQUE (kind, session_id, person_key)
);
CREATE INDEX IF NOT EXISTS idx_attendance_marks_venue_date ON attendance_marks (venue_id, session_date);
CREATE INDEX IF NOT EXISTS idx_attendance_marks_user ON attendance_marks (user_id) WHERE user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_attendance_marks_participant ON attendance_marks (participant_id) WHERE participant_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_attendance_marks_booking ON attendance_marks (booking_id) WHERE booking_id IS NOT NULL;

-- Every change to a mark after it was first made: what it was and became, the reason a manager gave for a late correction, and who.
CREATE TABLE IF NOT EXISTS attendance_changes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mark_id INTEGER NOT NULL REFERENCES attendance_marks(id) ON DELETE CASCADE,
  was_mark TEXT,
  now_mark TEXT NOT NULL,
  was_note TEXT,
  now_note TEXT,
  reason TEXT,
  -- A correction after the register was locked or past its days: a manager's, with a reason.
  late BOOLEAN NOT NULL DEFAULT false,
  by_name TEXT NOT NULL,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_attendance_changes_mark ON attendance_changes (mark_id, id);
