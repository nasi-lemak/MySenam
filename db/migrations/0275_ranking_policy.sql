-- A venue's ranking policy: public rankings are published only when a manager deliberately switches them on, and what
-- counts as ranked is the venue's choice within bounds (docs/features/tournaments.md#ratings-and-rankings, ADR 0034;
-- lib/ratings.ts `rankingPolicy`, `setRankingPolicy`). The rating maths constants stay install data in `rating_rules`.
--
-- Until now a venue's rankings page appeared as soon as one rated result existed. Every venue that exists when this runs
-- therefore has public rankings OFF (the columns default to false and no row is created for anybody): nobody's public page
-- changes silently, the page is removed from the public until the venue's manager switches it on. Private rankings (a
-- player's own /ratings, a guardian's, the manager's Ratings panel) never depended on the switch and are unchanged.
ALTER TABLE venue_rating_settings ADD COLUMN IF NOT EXISTS public_rankings BOOLEAN NOT NULL DEFAULT false;
-- Players with fewer counted results than `rank_after` may be shown in a separate, plainly-labelled section, never ranked.
ALTER TABLE venue_rating_settings ADD COLUMN IF NOT EXISTS show_provisional BOOLEAN NOT NULL DEFAULT false;
-- Counted results before a player is ranked: NULL is the install's default (rating_rules `provisionalGames`, 8); a venue
-- may choose 3 to 30. Changing it re-classes who is ranked and who is provisional; it never touches the ledger.
ALTER TABLE venue_rating_settings ADD COLUMN IF NOT EXISTS rank_after INTEGER CHECK (rank_after IS NULL OR (rank_after >= 3 AND rank_after <= 30));
ALTER TABLE venue_rating_settings ADD COLUMN IF NOT EXISTS updated_by TEXT;

-- The provisional section needs public rankings on.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'venue_rating_settings_provisional_needs_public') THEN
    ALTER TABLE venue_rating_settings ADD CONSTRAINT venue_rating_settings_provisional_needs_public CHECK (NOT show_provisional OR public_rankings);
  END IF;
END $$;

-- Who changed what, when: the policy above, whether an event counts in the ratings (who marked it rated, and when), and
-- the business-wide listing. Append-only; the activity log carries the same changes for the dashboard's timeline.
CREATE TABLE IF NOT EXISTS rating_policy_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('public_rankings', 'show_provisional', 'rank_after', 'event_rated', 'business_board')),
  -- The event, for 'event_rated' ("tournament 12"); otherwise NULL.
  subject TEXT,
  old_value TEXT,
  new_value TEXT NOT NULL,
  by_name TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_rating_policy_log_venue ON rating_policy_log (venue_id, id);
