-- Passes and memberships sold at the counter from the venue's own products at
-- their price (lib/counter-prices.ts, lib/pass-products.ts;
-- docs/features/pricing.md#selling-at-the-counter).
--
-- A pass product is what a manager offers to sell over the counter: what it
-- spends and covers, how long it lasts, and its price. Retired, it is sold no
-- more; passes already sold keep what they were sold as (a pass copies the
-- product's terms, and names the product it was sold from).
CREATE TABLE IF NOT EXISTS pass_products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  name TEXT NOT NULL CHECK (length(trim(name)) BETWEEN 2 AND 60),
  sport TEXT,
  coach_id INTEGER REFERENCES coaches(id) ON DELETE SET NULL,
  kind TEXT NOT NULL DEFAULT 'session' CHECK (kind IN ('session', 'time')),
  entries INTEGER NOT NULL CHECK (entries >= 1),
  entry_minutes INTEGER,
  max_minutes INTEGER,
  scope TEXT NOT NULL DEFAULT 'booking' CHECK (scope IN ('booking', 'resource', 'participant', 'places')),
  price NUMERIC(10,2) NOT NULL CHECK (price >= 0),
  valid_days INTEGER NOT NULL CHECK (valid_days BETWEEN 1 AND 744),
  created_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  retired_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS pass_products_venue ON pass_products (venue_id) WHERE retired_at IS NULL;
ALTER TABLE passes ADD COLUMN IF NOT EXISTS product_id INTEGER REFERENCES pass_products(id) ON DELETE SET NULL;

-- A price (or term) other than the plan's or product's, or a sale with
-- neither: only a manager, with a reason, written with the sale. One row per
-- sale; the activity log carries the same as `sale.price_set`.
CREATE TABLE IF NOT EXISTS counter_price_overrides (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('membership', 'pass')),
  sale_id INTEGER NOT NULL,
  -- The plan's or product's price; NULL when sold from neither.
  list_price NUMERIC(10,2),
  price NUMERIC(10,2) NOT NULL,
  reason TEXT NOT NULL CHECK (length(trim(reason)) >= 5 AND length(reason) <= 300),
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  admin_name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (kind, sale_id)
);
CREATE INDEX IF NOT EXISTS counter_price_overrides_venue ON counter_price_overrides (venue_id, created_at);
