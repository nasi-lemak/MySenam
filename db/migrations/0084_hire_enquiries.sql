-- Private hire enquiries (lib/enquiries.ts): a tournament, a company day,
-- a birthday party; asked from the venue's page, answered by its staff.
CREATE TABLE IF NOT EXISTS hire_enquiries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  phone_key TEXT GENERATED ALWAYS AS (phone_key(phone)) STORED,
  email TEXT,
  -- What for: 'event', 'tournament', 'corporate', 'party', 'school', 'other'.
  kind TEXT NOT NULL,
  -- The day they have in mind, if they have one, and roughly how many come.
  wanted_on TEXT,
  people INTEGER,
  message TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'replied', 'booked', 'declined')),
  handled_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  handled_at TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS hire_enquiries_venue ON hire_enquiries (venue_id, status, created_at);
CREATE INDEX IF NOT EXISTS hire_enquiries_created ON hire_enquiries (created_at);
