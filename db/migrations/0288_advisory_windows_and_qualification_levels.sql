-- The strength of a requirement (ADR 0046; docs/features/booking.md#advisory-and-hard-windows,
-- docs/features/venue-operations.md#qualification-levels).
--
-- Two owner decisions of 5 November 2026 share one idea, how firmly something is required. A launch or tide window is the
-- venue's own judgement (advisory) unless the venue marks it hard; a manager may book or move through an advisory one with a
-- reason that is kept, and never through a hard one. A role's qualification is recommended, required by the venue, or declared
-- legally required (the claim and its reference are recorded; the app never judges lawfulness and never lets it be overridden).

-- ---------------------------------------------------------------- launch and tide windows

-- A rule's strength. Existing rules are advisory (the default), which is what a rule's text always called them: the venue's own
-- data, so the venue may waive it for one booking. `hard`: nobody overrides it from the counter.
ALTER TABLE launch_rules ADD COLUMN IF NOT EXISTS strength TEXT NOT NULL DEFAULT 'advisory';
ALTER TABLE launch_rules DROP CONSTRAINT IF EXISTS launch_rules_strength_check;
ALTER TABLE launch_rules ADD CONSTRAINT launch_rules_strength_check CHECK (strength IN ('advisory', 'hard'));

-- A closure, an outage or a block (a rain-out's included) the venue marks as a safety closure. Nothing overrides a closure; the
-- flag says which are for safety, so the record, the logs and the report name it, and no later path can treat it as advisory.
-- Existing ones are not safety closures unless a manager marks them.
ALTER TABLE venue_closures ADD COLUMN IF NOT EXISTS safety BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE court_outages ADD COLUMN IF NOT EXISTS safety BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE blocks ADD COLUMN IF NOT EXISTS safety BOOLEAN NOT NULL DEFAULT false;

-- What a manager's override of an advisory window let through: one row per booking or class session made or moved outside its
-- day's window, with who, when, why, which rule and what the window was. Never deleted with the booking's history: it is the audit
-- record (the activity log says it too). `rule_id` is kept as a number once a rule is gone (the window text says what it was).
CREATE TABLE IF NOT EXISTS booking_window_overrides (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  booking_id INTEGER REFERENCES bookings(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  class_id INTEGER REFERENCES classes(id) ON DELETE CASCADE,
  court_id INTEGER REFERENCES courts(id) ON DELETE SET NULL,
  rule_id INTEGER,
  -- The refusal gone past: LAUNCH_WINDOW, LAUNCH_RETURN, LAUNCH_CLOSED, TIDE_NO_DATA or LAUNCH_WEEK.
  refusal_code TEXT NOT NULL,
  -- What the booking was: made new, moved to another time or court, or a class term's session.
  action TEXT NOT NULL DEFAULT 'booked' CHECK (action IN ('booked', 'moved', 'class')),
  date TEXT NOT NULL,
  start_min INTEGER NOT NULL,
  end_min INTEGER NOT NULL,
  -- The day's window as the venue's rule left it, as a line ("7:10 AM–10:40 AM, back by 10:10 AM"; "closed").
  window_text TEXT NOT NULL,
  reason TEXT NOT NULL CHECK (length(reason) >= 1),
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  admin_name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (booking_id IS NOT NULL OR class_id IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_window_overrides_venue ON booking_window_overrides (venue_id, created_at);
CREATE INDEX IF NOT EXISTS idx_window_overrides_booking ON booking_window_overrides (booking_id) WHERE booking_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_window_overrides_class ON booking_window_overrides (class_id) WHERE class_id IS NOT NULL;

-- Install data (one row): how short a reason may be, and how many overrides in a week raise a needs-attention line. A venue's own
-- settings (below) replace either; 0 alerts is "no alert".
CREATE TABLE IF NOT EXISTS window_override_defaults (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  reason_min INTEGER NOT NULL CHECK (reason_min BETWEEN 3 AND 300),
  weekly_alert INTEGER NOT NULL CHECK (weekly_alert BETWEEN 0 AND 1000)
);
INSERT INTO window_override_defaults (id, reason_min, weekly_alert) VALUES (1, 15, 5) ON CONFLICT (id) DO NOTHING;

-- A venue's own settings. A row only where a manager has changed something; no row means the defaults, with the override allowed
-- (the owner's decision is that managers may override advisory windows; a venue may turn it off).
CREATE TABLE IF NOT EXISTS venue_window_override_settings (
  venue_id INTEGER PRIMARY KEY REFERENCES venues(id) ON DELETE CASCADE,
  enabled BOOLEAN NOT NULL DEFAULT true,
  reason_min INTEGER CHECK (reason_min IS NULL OR reason_min BETWEEN 3 AND 300),
  weekly_alert INTEGER CHECK (weekly_alert IS NULL OR weekly_alert BETWEEN 0 AND 1000),
  updated_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------- qualifications

-- How firmly a role's qualification is required. `recommended`: a person without it still counts as supervising, flagged.
-- `venue_required`: they count only with the qualification recorded and unexpired (round 10's rule, which every role had).
-- `legally_required`: as venue_required, never let stand by a manager; the venue's reference or wording for the claim is kept
-- (never judged). Existing roles keep `venue_required`, which is what they did.
ALTER TABLE roster_roles ADD COLUMN IF NOT EXISTS qualification_level TEXT NOT NULL DEFAULT 'venue_required';
ALTER TABLE roster_roles DROP CONSTRAINT IF EXISTS roster_roles_qualification_level_check;
ALTER TABLE roster_roles ADD CONSTRAINT roster_roles_qualification_level_check CHECK (qualification_level IN ('recommended', 'venue_required', 'legally_required'));
ALTER TABLE roster_roles ADD COLUMN IF NOT EXISTS qualification_reference TEXT;

-- The instructor starter is a recommendation by the owner's decision: where the venue has not changed its suggested qualification,
-- it is recommended. A venue that edited it, or that made a role of its own, keeps what it set.
UPDATE roster_roles SET qualification_level = 'recommended'
 WHERE builtin AND key = 'instructor' AND qualification = 'Instructor certificate' AND qualification_level = 'venue_required';
