-- A court's rates, and its own hours, from a date (audit R8 X1-13; ADR 0027;
-- docs/features/pricing.md#prices-from-a-date). The court's own columns, its
-- activities' rates and its booking rules stay what is in force today; a
-- change set from a later date waits here as a whole set and the date booked
-- decides which applies. A booking keeps the price it was sold at: nothing
-- here is read to re-price one already made.
--
-- `rates`: off-peak, peak and the member rates, and the court's other
-- activities' own rates (JSON [{sport, offPeakRate, peakRate}], null rates
-- meaning the court's). `hours`: the court's own hours by weekday as a booking
-- policy keeps them (lib/week-hours.ts), null putting it back on the venue's.
CREATE TABLE IF NOT EXISTS court_changes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  court_id INTEGER NOT NULL REFERENCES courts(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('rates', 'hours')),
  from_date TEXT NOT NULL CHECK (from_date ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'),
  off_peak_rate NUMERIC(12,2) CHECK (off_peak_rate IS NULL OR off_peak_rate >= 0),
  peak_rate NUMERIC(12,2) CHECK (peak_rate IS NULL OR peak_rate >= 0),
  member_off_peak_rate NUMERIC(12,2) CHECK (member_off_peak_rate IS NULL OR member_off_peak_rate >= 0),
  member_peak_rate NUMERIC(12,2) CHECK (member_peak_rate IS NULL OR member_peak_rate >= 0),
  activity_rates TEXT NOT NULL DEFAULT '[]',
  week_hours TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (court_id, kind, from_date),
  CHECK (kind <> 'rates' OR (off_peak_rate IS NOT NULL AND peak_rate IS NOT NULL)),
  CHECK (kind <> 'hours' OR (off_peak_rate IS NULL AND peak_rate IS NULL AND member_off_peak_rate IS NULL AND member_peak_rate IS NULL))
);

-- The list on the court row too, kept by the database, so everything that
-- reads a court has it: JSON [{id, kind, from, ...}], soonest first.
ALTER TABLE courts ADD COLUMN IF NOT EXISTS dated_changes TEXT NOT NULL DEFAULT '[]';
CREATE OR REPLACE FUNCTION court_changes_list(court INTEGER) RETURNS TEXT LANGUAGE sql STABLE AS $$
  SELECT COALESCE(json_agg(json_build_object('id', x.id, 'kind', x.kind, 'from', x.from_date,
                                             'offPeakRate', x.off_peak_rate, 'peakRate', x.peak_rate,
                                             'memberOffPeakRate', x.member_off_peak_rate, 'memberPeakRate', x.member_peak_rate,
                                             'activities', x.activity_rates::json,
                                             'weekHours', CASE WHEN x.week_hours IS NULL THEN NULL ELSE x.week_hours::json END)
                           ORDER BY x.from_date, x.kind)::text, '[]')
    FROM court_changes x
   WHERE x.court_id = court
$$;
CREATE OR REPLACE FUNCTION court_changes_changed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP <> 'INSERT' THEN
    UPDATE courts SET dated_changes = court_changes_list(OLD.court_id) WHERE id = OLD.court_id;
  END IF;
  IF TG_OP <> 'DELETE' THEN
    UPDATE courts SET dated_changes = court_changes_list(NEW.court_id) WHERE id = NEW.court_id;
  END IF;
  RETURN NULL;
END
$$;
DROP TRIGGER IF EXISTS court_changes_list ON court_changes;
CREATE TRIGGER court_changes_list AFTER INSERT OR UPDATE OR DELETE ON court_changes
  FOR EACH ROW EXECUTE FUNCTION court_changes_changed();
