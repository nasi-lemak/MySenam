-- Each refund of an online payment: made through the gateway's API with one
-- click (Stripe), or made by staff in the gateway's dashboard and marked done
-- (Billplz, which has no refund API). `provider_ref` is the gateway's own id
-- for it, unique so the same refund reported twice is counted once.
CREATE TABLE IF NOT EXISTS online_refunds (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id INTEGER NOT NULL REFERENCES online_payments(id) ON DELETE CASCADE,
  amount NUMERIC(12,2) NOT NULL,
  provider_ref TEXT UNIQUE,
  pending INTEGER NOT NULL DEFAULT 0,
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS online_refunds_payment ON online_refunds (payment_id);
