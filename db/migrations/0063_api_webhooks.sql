-- A venue's own systems talking to MySenam (lib/api-keys.ts, lib/webhooks.ts).

-- Keys for the public API, one venue each. Only a hash is kept; the key is
-- shown once, when made.
CREATE TABLE IF NOT EXISTS venue_api_keys (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  -- The first characters, to tell keys apart in the list.
  prefix TEXT NOT NULL,
  key_hash TEXT NOT NULL UNIQUE,
  -- 'read', or 'write' (which can also book and cancel).
  scope TEXT NOT NULL DEFAULT 'read' CHECK (scope IN ('read', 'write')),
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  last_used_at TEXT,
  revoked_at TEXT
);
CREATE INDEX IF NOT EXISTS venue_api_keys_venue ON venue_api_keys (venue_id);

-- Where a venue wants to hear of its bookings changing, signed with a secret.
CREATE TABLE IF NOT EXISTS webhook_endpoints (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  url TEXT NOT NULL,
  -- Sealed like a payment key (lib/secrets.ts).
  secret TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  -- Turned off after failing for a day, so a dead address is not tried for ever.
  failing_since TEXT
);
CREATE INDEX IF NOT EXISTS webhook_endpoints_venue ON webhook_endpoints (venue_id);

CREATE TABLE IF NOT EXISTS webhook_deliveries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  endpoint_id INTEGER NOT NULL REFERENCES webhook_endpoints(id) ON DELETE CASCADE,
  event TEXT NOT NULL,
  payload TEXT NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0,
  next_at TEXT NOT NULL DEFAULT datetime('now'),
  delivered_at TEXT,
  last_status INTEGER,
  last_error TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS webhook_deliveries_due ON webhook_deliveries (delivered_at, next_at);

-- What each booking looked like when its venue's webhooks were last told,
-- so a sweep can tell what changed however it changed.
CREATE TABLE IF NOT EXISTS webhook_seen (
  booking_id INTEGER PRIMARY KEY REFERENCES bookings(id) ON DELETE CASCADE,
  state TEXT NOT NULL
);

