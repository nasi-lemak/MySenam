-- Somebody admitted at the desk although their membership no longer covers
-- the session (lib/store.ts checkIn, markPlace; docs/features/venue-operations.md#check-in-and-live-crowd-levels).
--
-- Self check-in and the door code refuse a place on a members' session whose
-- person's membership was cancelled, voided or has ended for that date. At
-- the desk staff are warned and decide; admitting them anyway is kept here,
-- with who decided and why, besides the activity log.
CREATE TABLE IF NOT EXISTS membership_admissions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  -- The person's place on the booking, where it names them (booking_participants).
  place_id INTEGER,
  participant_id INTEGER REFERENCES participants(id) ON DELETE SET NULL,
  person_name TEXT NOT NULL,
  -- What staff were told: 'ended', 'cancelled' or 'none', and the end date where it ended.
  lapse TEXT NOT NULL CHECK (lapse IN ('ended', 'cancelled', 'none')),
  ended_on TEXT,
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  admin_name TEXT NOT NULL,
  note TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_membership_admissions_booking ON membership_admissions (booking_id);
