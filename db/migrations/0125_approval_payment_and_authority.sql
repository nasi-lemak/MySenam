-- Approval to booking, payment, authority and revocation (lib/approvals.ts;
-- docs/features/activities.md#registering-online-for-approval; ADR 0020).
--
-- Approval establishes eligibility, never payment: a slot booked on approval
-- at a venue that asks payment to hold is held by the ordinary booking hold
-- (bookings.hold_until, lib/holds.ts) until paid, or let go.

-- Who may grant it. 'safety': a competency assessment (a belay check, a range
-- safety briefing, paddling competence), approved only by a manager, a coach
-- the venue names for it, or front-desk staff it delegates by name;
-- 'administrative': checking that an application is complete or a membership
-- held, which any of the venue's staff may approve.
ALTER TABLE approval_requirements ADD COLUMN IF NOT EXISTS review_level TEXT NOT NULL DEFAULT 'safety'
  CHECK (review_level IN ('administrative', 'safety'));
-- Hours an approved customer has to pay for the slot booked, where the venue
-- asks payment to hold (never past the slot's start).
ALTER TABLE approval_requirements ADD COLUMN IF NOT EXISTS pay_hours INTEGER NOT NULL DEFAULT 24
  CHECK (pay_hours BETWEEN 1 AND 168);

-- Front-desk staff a manager delegates, by name, to make safety decisions on an activity.
CREATE TABLE IF NOT EXISTS approval_delegates (
  requirement_id INTEGER NOT NULL REFERENCES approval_requirements(id) ON DELETE CASCADE,
  admin_id INTEGER NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
  PRIMARY KEY (requirement_id, admin_id)
);

-- A slot booked on approval and waiting for its payment, and one whose payment
-- deadline passed unpaid (the booking let go).
ALTER TABLE approval_requests DROP CONSTRAINT IF EXISTS approval_requests_slot_status_check;
ALTER TABLE approval_requests ADD CONSTRAINT approval_requests_slot_status_check
  CHECK (slot_status IN ('held', 'lapsed', 'released', 'booked', 'taken', 'awaiting_payment', 'payment_lapsed'));
-- The administrative check (the application is complete; a membership held), apart from the safety decision.
ALTER TABLE approval_requests ADD COLUMN IF NOT EXISTS admin_checked_at TIMESTAMPTZ;
ALTER TABLE approval_requests ADD COLUMN IF NOT EXISTS admin_checked_by TEXT;
-- The booking a slot became was the session for the in-person step (not held to the sign-off).
ALTER TABLE approval_requests ADD COLUMN IF NOT EXISTS slot_assessment BOOLEAN NOT NULL DEFAULT false;

-- A coach decides only signed in to their own MySenam account, which a
-- manager links to the coach record; a private link alone decides nothing.
ALTER TABLE coaches ADD COLUMN IF NOT EXISTS user_id INTEGER REFERENCES users(id) ON DELETE SET NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_coaches_venue_user ON coaches (venue_id, user_id) WHERE user_id IS NOT NULL;
-- The account a coach decided from.
ALTER TABLE approval_events ADD COLUMN IF NOT EXISTS user_id INTEGER REFERENCES users(id) ON DELETE SET NULL;

-- Attendance a manager arranged under staff supervision: recorded, and never
-- a door code (it authorises no unmanned use, now or later).
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS staff_supervised BOOLEAN NOT NULL DEFAULT false;

-- Confirmed future bookings of somebody whose approval was revoked: flagged
-- for staff to decide (cancel, supervise, or keep), never cancelled silently.
CREATE TABLE IF NOT EXISTS approval_booking_flags (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id INTEGER NOT NULL REFERENCES approval_requests(id) ON DELETE CASCADE,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  resolved_at TIMESTAMPTZ,
  resolved_by TEXT,
  resolution TEXT,
  UNIQUE (request_id, booking_id)
);
CREATE INDEX IF NOT EXISTS idx_approval_booking_flags_open ON approval_booking_flags (venue_id) WHERE resolved_at IS NULL;
