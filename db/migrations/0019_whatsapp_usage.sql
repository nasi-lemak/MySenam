-- WhatsApp messages a venue's monthly fee includes, and what each one past
-- that costs. NULL: the marketplace's defaults (MYSENAM_WHATSAPP_INCLUDED,
-- MYSENAM_WHATSAPP_PRICE).
ALTER TABLE venues ADD COLUMN IF NOT EXISTS whatsapp_included INTEGER
  CHECK (whatsapp_included IS NULL OR (whatsapp_included >= 0 AND whatsapp_included <= 1000000));
ALTER TABLE venues ADD COLUMN IF NOT EXISTS whatsapp_price NUMERIC(6,3)
  CHECK (whatsapp_price IS NULL OR (whatsapp_price >= 0 AND whatsapp_price <= 5));

-- 1 when it went as a reply in a chat the customer opened, which Meta does
-- not charge for, rather than as a paid template.
ALTER TABLE messages ADD COLUMN IF NOT EXISTS free INTEGER NOT NULL DEFAULT 0;
CREATE INDEX IF NOT EXISTS messages_venue_sent ON messages (venue_id, sent_at);

-- A month's WhatsApp messages, as charged on the next month's invoice.
CREATE TABLE IF NOT EXISTS invoice_usage (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id INTEGER NOT NULL REFERENCES venue_invoices(id) ON DELETE CASCADE,
  venue_id INTEGER NOT NULL REFERENCES venues(id),
  -- YYYY-MM the messages were sent in.
  month TEXT NOT NULL,
  messages INTEGER NOT NULL,
  included INTEGER NOT NULL,
  unit_price NUMERIC(6,3) NOT NULL,
  amount NUMERIC(12,2) NOT NULL,
  UNIQUE (venue_id, month)
);
CREATE INDEX IF NOT EXISTS invoice_usage_invoice ON invoice_usage (invoice_id);
