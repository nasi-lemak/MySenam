-- A coach's time off (lib/coaching.ts), set by the venue or by the coach at
-- their own link: no lessons can be booked with them on those days. Lessons
-- already booked then stand, for the venue to move.
CREATE TABLE IF NOT EXISTS coach_time_off (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coach_id INTEGER NOT NULL REFERENCES coaches(id) ON DELETE CASCADE,
  from_date TEXT NOT NULL,
  until_date TEXT NOT NULL,
  reason TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  CHECK (until_date >= from_date)
);
CREATE INDEX IF NOT EXISTS coach_time_off_coach ON coach_time_off (coach_id, until_date);
-- When the coach last changed their own hours or time off, for the venue to see.
ALTER TABLE coaches ADD COLUMN IF NOT EXISTS self_changed_at TEXT;
