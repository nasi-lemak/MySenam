-- Supervised group messaging for eligible minors, guardian controls, and a real notification digest
-- (docs/features/player-messages.md#supervised-youth-groups; ADR 0044; lib/youth-messages.ts, lib/message-digest.ts).
--
-- The owner's decision of 5 November 2026: allow supervised group messaging for eligible minors, prohibit unsolicited private
-- messaging, with moderation, reporting, age-appropriate guardian controls and safeguarding measures; and a 6-hour notification
-- digest by default, with immediate delivery for urgent safety or moderation events.
--
-- A minor's account (declared under 18, or not said) can be a seat only in the shared thread of a community group marked as a
-- supervised youth group, and only with three things all live: the minor's own opt-in, a linked and live guardian's consent for that
-- child and that group, and the group being marked. Nothing else here gives a minor a thread: there is no one-to-one thread for a
-- minor by any route, and the trigger at the end refuses a message from anybody not declared 18 or over outside a youth group's thread.
-- Everything is the people's word (ages, guardianship, roles), recorded as declared, never as verified.

-- ---------------------------------------------------------------- the group

-- A community group marked as a supervised youth group, by its adult organiser. `venue_requested_id` is the venue the organiser asked
-- to look after it; `venue_id` is set only when that venue's manager accepts (so a venue never sees a group nobody gave it). The
-- quiet window may only lengthen the install's (YOUTH_QUIET_HOURS), never shorten it. `ended_at`: no longer a youth group; its
-- thread is closed for good and never becomes an ordinary one.
CREATE TABLE IF NOT EXISTS youth_groups (
  group_id INTEGER PRIMARY KEY REFERENCES community_groups(id) ON DELETE CASCADE,
  marked_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  marked_at TEXT NOT NULL DEFAULT datetime('now'),
  venue_id INTEGER REFERENCES venues(id) ON DELETE SET NULL,
  venue_requested_id INTEGER REFERENCES venues(id) ON DELETE SET NULL,
  venue_confirmed_by TEXT,
  venue_confirmed_at TEXT,
  quiet_from_min INTEGER CHECK (quiet_from_min IS NULL OR quiet_from_min BETWEEN 0 AND 1439),
  quiet_to_min INTEGER CHECK (quiet_to_min IS NULL OR quiet_to_min BETWEEN 0 AND 1439),
  ended_at TEXT,
  ended_by TEXT,
  ended_reason TEXT
);
CREATE INDEX IF NOT EXISTS idx_youth_groups_venue ON youth_groups (venue_id) WHERE venue_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_youth_groups_requested ON youth_groups (venue_requested_id) WHERE venue_requested_id IS NOT NULL;

-- The adults in a youth group's thread, each with a declared role. A `supervisor` can remove a message, mute a member and close the
-- thread; an `adult` was let in by a supervisor and can write. A member who is an adult and is not here has no seat: an adult is never
-- added to the thread without supervisor action. The organiser is always a supervisor (declared role `organiser`).
CREATE TABLE IF NOT EXISTS youth_group_adults (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id INTEGER NOT NULL REFERENCES community_groups(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('supervisor', 'adult')),
  declared_role TEXT NOT NULL CHECK (declared_role IN ('organiser', 'coach', 'venue_staff', 'volunteer', 'parent', 'other')),
  added_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  removed_at TEXT,
  removed_by TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_youth_group_adults_live ON youth_group_adults (group_id, user_id) WHERE removed_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_youth_group_adults_user ON youth_group_adults (user_id) WHERE removed_at IS NULL;

-- ---------------------------------------------------------------- the minor and the guardian

-- The minor's own opt-in, per group (revocable at any time).
CREATE TABLE IF NOT EXISTS youth_message_optins (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id INTEGER NOT NULL REFERENCES community_groups(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  opted_in_at TEXT NOT NULL DEFAULT datetime('now'),
  revoked_at TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_youth_message_optins_live ON youth_message_optins (group_id, user_id) WHERE revoked_at IS NULL;

-- A guardian's explicit consent, for one child in one group: default off, revocable, per child and per group. It counts only while
-- that guardian is still a live guardian of the participant whose own login is the minor's account (checked on every call, never
-- copied). Any live guardian switching it off ends every live consent for that child and group at once.
CREATE TABLE IF NOT EXISTS youth_message_consents (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id INTEGER NOT NULL REFERENCES community_groups(id) ON DELETE CASCADE,
  minor_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  guardian_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  participant_id INTEGER NOT NULL REFERENCES participants(id) ON DELETE CASCADE,
  granted_at TEXT NOT NULL DEFAULT datetime('now'),
  revoked_at TEXT,
  revoked_by INTEGER REFERENCES users(id) ON DELETE SET NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_youth_message_consents_live ON youth_message_consents (group_id, minor_user_id, guardian_user_id) WHERE revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_youth_message_consents_minor ON youth_message_consents (minor_user_id) WHERE revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_youth_message_consents_guardian ON youth_message_consents (guardian_user_id) WHERE revoked_at IS NULL;

-- How often notices about a child's group messages are sent, by the guardian's choice (it governs, whatever the child chose).
CREATE TABLE IF NOT EXISTS youth_guardian_settings (
  minor_user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  notice_mode TEXT NOT NULL DEFAULT 'digest' CHECK (notice_mode IN ('immediate', 'digest', 'daily', 'off')),
  updated_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  updated_at TEXT NOT NULL DEFAULT datetime('now')
);

-- ---------------------------------------------------------------- supervision

-- Somebody who may read a youth thread and not write in it: muted by a supervisor, by staff, or automatically when a report names
-- them, until the report is reviewed. At most one in force for a person and group.
CREATE TABLE IF NOT EXISTS youth_thread_mutes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id INTEGER NOT NULL REFERENCES community_groups(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  source TEXT NOT NULL CHECK (source IN ('supervisor', 'report')),
  report_id INTEGER REFERENCES player_message_reports(id) ON DELETE SET NULL,
  reason TEXT,
  muted_by TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  lifted_at TEXT,
  lifted_by TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_youth_thread_mutes_live ON youth_thread_mutes (group_id, user_id) WHERE lifted_at IS NULL;

-- What was done about a youth group and its people, by whom and when: marks, supervisors and adults, consents, opt-ins, mutes, removed
-- messages (by number), what a guardian or staff member read. Never a message's text. Staff's reads are also in the staff activity log.
CREATE TABLE IF NOT EXISTS youth_message_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id INTEGER NOT NULL REFERENCES community_groups(id) ON DELETE CASCADE,
  minor_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  actor_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  actor_kind TEXT NOT NULL CHECK (actor_kind IN ('organiser', 'supervisor', 'guardian', 'minor', 'staff', 'system')),
  action TEXT NOT NULL,
  detail TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_youth_message_events_group ON youth_message_events (group_id, id);

-- ---------------------------------------------------------------- the thread and its messages

-- A youth group's thread. `youth_since_id`: what was written before the group was marked is never shown in it.
ALTER TABLE player_message_threads ADD COLUMN IF NOT EXISTS youth INTEGER NOT NULL DEFAULT 0 CHECK (youth IN (0, 1));
ALTER TABLE player_message_threads ADD COLUMN IF NOT EXISTS youth_since_id INTEGER NOT NULL DEFAULT 0;
-- A message a supervisor removed: not shown to members or guardians; kept for staff review until YOUTH_REMOVED_RETENTION_DAYS.
ALTER TABLE player_messages ADD COLUMN IF NOT EXISTS hidden_at TEXT;
ALTER TABLE player_messages ADD COLUMN IF NOT EXISTS hidden_by TEXT;
-- A report in a youth thread, or by or about a minor: urgent (immediate notice, a longer frozen copy, the reported person muted).
ALTER TABLE player_message_reports ADD COLUMN IF NOT EXISTS urgent INTEGER NOT NULL DEFAULT 0 CHECK (urgent IN (0, 1));

-- ---------------------------------------------------------------- the digest

-- How a person is told they have unread messages: 'digest' (one email per conversation per period, MESSAGE_DIGEST_HOURS, 6 by
-- default), 'immediate' (an email for a message, within the daily limits), or 'daily'. Never the text of a message.
ALTER TABLE player_message_settings ADD COLUMN IF NOT EXISTS notice_mode TEXT NOT NULL DEFAULT 'digest' CHECK (notice_mode IN ('immediate', 'digest', 'daily'));
-- A notice covers messages up to `through_id`: the scheduler never tells the same person about the same messages twice.
ALTER TABLE player_message_notices ADD COLUMN IF NOT EXISTS through_id INTEGER;
ALTER TABLE player_message_notices ADD COLUMN IF NOT EXISTS message_count INTEGER;
CREATE UNIQUE INDEX IF NOT EXISTS uq_player_message_notices_through ON player_message_notices (user_id, thread_id, through_id) WHERE through_id IS NOT NULL;

-- ---------------------------------------------------------------- never private, never outside a youth group

-- A message from anybody not declared 18 or over is accepted only in the thread of a community group marked as a supervised youth
-- group. The code decides who may write (lib/youth-messages.ts); this is the database refusing the one thing no code path may do.
CREATE OR REPLACE FUNCTION player_messages_minor_only_in_youth_group() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.sender_id IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM player_profiles p WHERE p.user_id = NEW.sender_id AND p.adult = 1)
     AND NOT EXISTS (SELECT 1 FROM player_message_threads t WHERE t.id = NEW.thread_id AND t.youth = 1 AND t.context_kind = 'group') THEN
    RAISE EXCEPTION 'a message from somebody not declared 18 or over is only for a supervised youth group''s thread';
  END IF;
  RETURN NEW;
END
$$;
DROP TRIGGER IF EXISTS player_messages_minor_only_in_youth_group ON player_messages;
CREATE TRIGGER player_messages_minor_only_in_youth_group BEFORE INSERT ON player_messages
  FOR EACH ROW EXECUTE FUNCTION player_messages_minor_only_in_youth_group();
