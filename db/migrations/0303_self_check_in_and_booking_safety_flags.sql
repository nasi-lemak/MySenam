-- Safety and access after a booking was made (ADR 0058; docs/features/venue-operations.md#check-in-and-live-crowd-levels,
-- #unstaffed-hours-and-door-codes and #bookings-that-need-a-decision).
--
-- 1. Who recorded an arrival. A customer's own QR check-in and a door code revealed on their phone carry no proof of presence,
--    so they are recorded as what they are ('self', 'door') and are verified attendance only once staff confirm them
--    (`confirmed_at`); a desk's check-in (the default, and every row already there) is verified. Only verified attendance
--    clears a desk's no-show, freezes a class move or counts as having played for a review.
ALTER TABLE check_ins ADD COLUMN IF NOT EXISTS source TEXT NOT NULL DEFAULT 'desk';
ALTER TABLE check_ins ADD COLUMN IF NOT EXISTS confirmed_at TEXT;
ALTER TABLE check_ins ADD COLUMN IF NOT EXISTS confirmed_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL;
ALTER TABLE check_ins ADD COLUMN IF NOT EXISTS confirmed_by_name TEXT;
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'check_ins_source_check') THEN
    ALTER TABLE check_ins ADD CONSTRAINT check_ins_source_check CHECK (source IN ('desk', 'self', 'door'));
  END IF;
END
$$;

-- 2. Confirmed bookings a venue's own decision left in doubt, for staff to decide (cancel with a refund, or leave), never
--    cancelled silently: 'blocked' (the venue refused the number after it booked) and 'eligibility' (a sign-off, certification,
--    induction or waiver was taken back after it booked). The pattern of approval_booking_flags (0125) and
--    membership_booking_flags (0195). No personal data of its own: the person is the booking's.
CREATE TABLE IF NOT EXISTS booking_safety_flags (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('blocked', 'eligibility')),
  -- What was taken back: 'sign-off', 'certification', 'induction', 'waiver'; for a blocked number, 'blocked'.
  what TEXT NOT NULL,
  -- Why, as the staff member who took it back said it (blank for a blocked number: the reason is on the block).
  reason TEXT,
  -- Who took it back, by name as it was.
  by_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- The customer was told once (NULL: not yet, or not reachable).
  told_at TIMESTAMPTZ,
  resolved_at TIMESTAMPTZ,
  resolved_by TEXT,
  resolution TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_booking_safety_flags_open ON booking_safety_flags (booking_id, kind, what) WHERE resolved_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_booking_safety_flags_open ON booking_safety_flags (venue_id) WHERE resolved_at IS NULL;
