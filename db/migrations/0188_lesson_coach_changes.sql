-- A lesson given to another coach by the venue (lib/lesson-coaches.ts;
-- docs/features/programmes.md#giving-a-lesson-to-another-coach).
--
-- A manager gives a booked lesson to another active coach of its sport, with
-- or without a new time. The new coach's fee for the lesson's minutes takes
-- the place of the old one on the booking (`bookings.coach_fee`, what the
-- coach is owed). On a lesson not yet paid the price simply changes by the
-- difference. On a paid one the manager chooses, and the choice is kept here:
--
--   kept      the price stays as paid; the venue absorbs the difference
--             (`absorbed`, signed: more than the customer paid for the coach
--             when positive, less when negative);
--   adjusted  a higher fee is owed by the customer (`owed`), collected at the
--             counter on a receipt of its own; a lower one goes back the way
--             the lesson was paid (`refunded`, `refund_how`) with a credit
--             note of its own.
--
-- The booking's price as sold, and so its receipt, does not change on a paid
-- lesson: the receipt keeps the coach and fee it was sold with (the first
-- paid change's `from_*`), and what went back here is left out of any later
-- refund on cancelling (lib/store.ts paidPartLeft).

CREATE TABLE IF NOT EXISTS lesson_coach_changes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  venue_id INTEGER REFERENCES venues(id) ON DELETE SET NULL,
  from_coach_id INTEGER REFERENCES coaches(id) ON DELETE SET NULL,
  to_coach_id INTEGER REFERENCES coaches(id) ON DELETE SET NULL,
  -- As they were named then, so the record reads the same after a coach is renamed.
  from_coach_name TEXT NOT NULL,
  to_coach_name TEXT NOT NULL,
  from_fee NUMERIC(12,2) NOT NULL CHECK (from_fee >= 0),
  to_fee NUMERIC(12,2) NOT NULL CHECK (to_fee >= 0),
  -- Was the lesson paid when it was given to the other coach.
  paid BOOLEAN NOT NULL,
  -- 'repriced': not paid, the price changed by the difference; 'kept' or 'adjusted' on a paid one.
  money TEXT NOT NULL CHECK (money IN ('repriced', 'kept', 'adjusted')),
  absorbed NUMERIC(12,2) NOT NULL DEFAULT 0,
  owed NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (owed >= 0),
  -- The difference owed, collected at the counter (its receipt is `lesson-coach:<id>`), or no longer owed.
  owed_paid_at TIMESTAMPTZ,
  owed_paid_via TEXT,
  owed_cleared_at TIMESTAMPTZ,
  refunded NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (refunded >= 0),
  refund_how TEXT CHECK (refund_how IS NULL OR refund_how IN ('credit', 'online', 'hand')),
  by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  by_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_lesson_coach_changes_booking ON lesson_coach_changes (booking_id);
CREATE INDEX IF NOT EXISTS idx_lesson_coach_changes_owed ON lesson_coach_changes (booking_id)
  WHERE owed > 0 AND owed_paid_at IS NULL AND owed_cleared_at IS NULL;

-- Credit given back for a cheaper coach: apart from the booking's own refund on cancelling.
ALTER TABLE wallet_entries ADD COLUMN IF NOT EXISTS coach_change_id INTEGER REFERENCES lesson_coach_changes(id) ON DELETE SET NULL;
