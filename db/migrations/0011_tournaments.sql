-- Tournaments run by venues (lib/tournaments.ts): entries, a draw, matches
-- scheduled onto courts the tournament holds, results, and who goes through.

CREATE TABLE IF NOT EXISTS tournaments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  sport TEXT NOT NULL,
  -- 'knockout': straight elimination. 'groups': round-robin groups, then the
  -- best of each group into a knockout.
  format TEXT NOT NULL CHECK (format IN ('knockout', 'groups')),
  -- 1 for singles, 2 for doubles.
  team_size INTEGER NOT NULL DEFAULT 1 CHECK (team_size IN (1, 2)),
  level TEXT CHECK (level IN ('beginner', 'intermediate', 'advanced', 'competitive')),
  entry_fee NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (entry_fee >= 0),
  max_entries INTEGER NOT NULL CHECK (max_entries BETWEEN 2 AND 128),
  group_size INTEGER NOT NULL DEFAULT 4 CHECK (group_size BETWEEN 3 AND 6),
  -- How many from each group go through to the knockout.
  advance INTEGER NOT NULL DEFAULT 2 CHECK (advance BETWEEN 1 AND 2),
  starts_on TEXT NOT NULL,
  ends_on TEXT NOT NULL,
  -- The hours of each day it holds its courts.
  start_hour INTEGER NOT NULL,
  end_hour INTEGER NOT NULL,
  description TEXT,
  status TEXT NOT NULL DEFAULT 'open'
    CHECK (status IN ('open', 'closed', 'drawn', 'finished', 'cancelled')),
  created_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  CHECK (ends_on >= starts_on),
  CHECK (end_hour > start_hour)
);
CREATE INDEX IF NOT EXISTS idx_tournaments_venue ON tournaments(venue_id);

CREATE TABLE IF NOT EXISTS tournament_courts (
  tournament_id INTEGER NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
  court_id INTEGER NOT NULL REFERENCES courts(id) ON DELETE CASCADE,
  PRIMARY KEY (tournament_id, court_id)
);

-- The hours a tournament holds are ordinary blocks, so every booking path
-- already treats them as taken; this says whose they are.
ALTER TABLE slot_blocks ADD COLUMN IF NOT EXISTS tournament_id INTEGER REFERENCES tournaments(id) ON DELETE CASCADE;

CREATE TABLE IF NOT EXISTS tournament_entries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournament_id INTEGER NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  -- As shown in the draw: a player's name, or "Lim / Tan" for a pair.
  name TEXT NOT NULL,
  partner_name TEXT,
  status TEXT NOT NULL DEFAULT 'entered' CHECK (status IN ('entered', 'waitlisted', 'withdrawn')),
  seed INTEGER,
  paid_at TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_tournament_entries_t ON tournament_entries(tournament_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_tournament_entry_user ON tournament_entries(tournament_id, user_id)
  WHERE user_id IS NOT NULL AND status <> 'withdrawn';

CREATE TABLE IF NOT EXISTS tournament_matches (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournament_id INTEGER NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
  stage TEXT NOT NULL CHECK (stage IN ('group', 'knockout')),
  -- Group stage: which group (1, 2, ...). Knockout: NULL.
  group_no INTEGER,
  -- Knockout: 1 is the first round. Group stage: the round of the round-robin.
  round INTEGER NOT NULL,
  -- Its place in the round, top to bottom.
  position INTEGER NOT NULL,
  entry_a INTEGER REFERENCES tournament_entries(id),
  entry_b INTEGER REFERENCES tournament_entries(id),
  -- Where the winner goes next, in a knockout.
  next_match_id INTEGER REFERENCES tournament_matches(id),
  next_slot TEXT CHECK (next_slot IN ('a', 'b')),
  court_id INTEGER REFERENCES courts(id),
  date TEXT,
  hour INTEGER,
  score TEXT,
  winner INTEGER REFERENCES tournament_entries(id),
  status TEXT NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled', 'done', 'walkover', 'bye')),
  updated_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_tournament_matches_t ON tournament_matches(tournament_id);

-- An entry fee paid online, to the venue.
ALTER TABLE online_payments DROP CONSTRAINT IF EXISTS online_payments_purpose_check;
ALTER TABLE online_payments ADD CONSTRAINT online_payments_purpose_check
  CHECK (purpose IN ('booking', 'invoice', 'share', 'entry'));
ALTER TABLE online_payments ADD COLUMN IF NOT EXISTS tournament_entry_id INTEGER
  REFERENCES tournament_entries(id) ON DELETE SET NULL;
