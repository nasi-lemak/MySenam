-- Player matching: a player who has booked a court opens it to others, who
-- ask to join and pay their share of the court to the venue (lib/games.ts).

-- How good somebody says they are, sport by sport.
CREATE TABLE IF NOT EXISTS player_levels (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  sport TEXT NOT NULL,
  level TEXT NOT NULL CHECK (level IN ('beginner', 'intermediate', 'advanced', 'competitive')),
  updated_at TEXT NOT NULL DEFAULT datetime('now'),
  PRIMARY KEY (user_id, sport)
);

-- A booking with places for others. One per booking.
CREATE TABLE IF NOT EXISTS open_games (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL UNIQUE REFERENCES bookings(id) ON DELETE CASCADE,
  host_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  -- The level wanted; NULL for anybody.
  level TEXT CHECK (level IN ('beginner', 'intermediate', 'advanced', 'competitive')),
  spots INTEGER NOT NULL CHECK (spots BETWEEN 1 AND 10),
  -- What each player who joins pays towards the court.
  share NUMERIC(12,2) NOT NULL CHECK (share >= 0),
  auto_accept INTEGER NOT NULL DEFAULT 0,
  note TEXT,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed', 'cancelled')),
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_open_games_status ON open_games(status);

CREATE TABLE IF NOT EXISTS open_game_players (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_id INTEGER NOT NULL REFERENCES open_games(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'requested'
    CHECK (status IN ('requested', 'accepted', 'declined', 'left', 'removed')),
  no_show INTEGER NOT NULL DEFAULT 0,
  paid_at TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  decided_at TEXT,
  UNIQUE (game_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_open_game_players_user ON open_game_players(user_id);

-- A share paid online is a payment of its own, to the venue, for one player.
ALTER TABLE online_payments DROP CONSTRAINT IF EXISTS online_payments_purpose_check;
ALTER TABLE online_payments ADD CONSTRAINT online_payments_purpose_check
  CHECK (purpose IN ('booking', 'invoice', 'share'));
ALTER TABLE online_payments ADD COLUMN IF NOT EXISTS game_player_id INTEGER
  REFERENCES open_game_players(id) ON DELETE SET NULL;

-- What other players have paid towards a booking: what its host still owes
-- is the rest.
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS shares_paid NUMERIC(12,2) NOT NULL DEFAULT 0;
