-- Matchmaking and community play, on the open games that already exist
-- (lib/games.ts, lib/matchmaking.ts, lib/groups.ts).

-- What a player says about how they like to play: only what matching needs.
-- An area and an approximate point (two decimal places, about a kilometre),
-- never an address; levels stay in player_levels, sport by sport.
CREATE TABLE IF NOT EXISTS player_profiles (
  user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  area TEXT,
  near_lat NUMERIC(6,2),
  near_lng NUMERIC(6,2),
  max_km INTEGER NOT NULL DEFAULT 10 CHECK (max_km BETWEEN 1 AND 100),
  -- Days (0 Sunday … 6 Saturday) and parts of the day, comma-separated: "6,0" and "evening".
  days TEXT,
  times TEXT,
  intensity TEXT NOT NULL DEFAULT 'any' CHECK (intensity IN ('casual', 'competitive', 'any')),
  -- The most they would pay as a share; NULL for no limit.
  max_share NUMERIC(12,2),
  -- Hosts may find them for their games (opt-in, adults only).
  discoverable INTEGER NOT NULL DEFAULT 0,
  -- Anybody may invite them, not only hosts they have played with or groups they are in (opt-in).
  invitable INTEGER NOT NULL DEFAULT 0,
  -- Declared 18 or over (1), under 18 (0), or not said (NULL): the player's word, not verified.
  adult INTEGER CHECK (adult IS NULL OR adult IN (0, 1)),
  -- Suggested games by email: never, a daily digest, or each as it opens (capped).
  notify_matches TEXT NOT NULL DEFAULT 'digest' CHECK (notify_matches IN ('none', 'digest', 'each')),
  updated_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_player_profiles_discoverable ON player_profiles(discoverable) WHERE discoverable = 1;

-- A game's own settings beyond the court: who can find it, whether a full
-- game takes a waiting list, the kind of game, adults only, and its series.
ALTER TABLE open_games ADD COLUMN IF NOT EXISTS visibility TEXT NOT NULL DEFAULT 'public' CHECK (visibility IN ('public', 'private'));
-- Games opened before this keep turning people away when full; new ones choose.
ALTER TABLE open_games ADD COLUMN IF NOT EXISTS waitlist INTEGER NOT NULL DEFAULT 0;
ALTER TABLE open_games ADD COLUMN IF NOT EXISTS intensity TEXT NOT NULL DEFAULT 'any' CHECK (intensity IN ('casual', 'competitive', 'any'));
ALTER TABLE open_games ADD COLUMN IF NOT EXISTS adults_only INTEGER NOT NULL DEFAULT 0;
ALTER TABLE open_games ADD COLUMN IF NOT EXISTS series_id INTEGER;
CREATE INDEX IF NOT EXISTS idx_open_games_series ON open_games(series_id) WHERE series_id IS NOT NULL;

-- Every way somebody stands in a game, in one row per person per game:
-- invited (by the host or a player, until it expires), requested, accepted,
-- declined, left (withdrew), removed (by the host; a revoked invitation),
-- waitlisted, offered (a freed place held for them until it expires), expired.
ALTER TABLE open_game_players DROP CONSTRAINT IF EXISTS open_game_players_status_check;
ALTER TABLE open_game_players ADD CONSTRAINT open_game_players_status_check
  CHECK (status IN ('requested', 'accepted', 'declined', 'left', 'removed', 'invited', 'waitlisted', 'offered', 'expired'));
ALTER TABLE open_game_players ADD COLUMN IF NOT EXISTS invited_by INTEGER REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE open_game_players ADD COLUMN IF NOT EXISTS expires_at TEXT;
CREATE INDEX IF NOT EXISTS idx_open_game_players_game_status ON open_game_players(game_id, status);
CREATE INDEX IF NOT EXISTS idx_open_game_players_expiring ON open_game_players(expires_at) WHERE status IN ('invited', 'offered');

-- A link to a game, private or not, for its host to share: only the SHA-256
-- of its secret is kept; it expires and can be withdrawn.
CREATE TABLE IF NOT EXISTS game_links (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_id INTEGER NOT NULL REFERENCES open_games(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  expires_at TEXT NOT NULL,
  revoked_at TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);

-- One player blocking another: neither finds, invites or joins the other.
CREATE TABLE IF NOT EXISTS player_blocks (
  blocker_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  blocked_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  PRIMARY KEY (blocker_id, blocked_id),
  CHECK (blocker_id <> blocked_id)
);
CREATE INDEX IF NOT EXISTS idx_player_blocks_blocked ON player_blocks(blocked_id);

-- A report about a player, for the platform's owners to look at.
CREATE TABLE IF NOT EXISTS player_reports (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  reported_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
  game_id INTEGER REFERENCES open_games(id) ON DELETE SET NULL,
  reason TEXT NOT NULL CHECK (reason IN ('no_show', 'abuse', 'spam', 'safety', 'other')),
  note TEXT,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'reviewed')),
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  reviewed_at TEXT
);

-- A weekly game: the host's own repeating booking (bookings.series_code),
-- each of whose dates is an open game of its own. Nothing here holds a court:
-- a date with no booking has no game.
CREATE TABLE IF NOT EXISTS game_series (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  host_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  booking_series_code TEXT NOT NULL,
  title TEXT,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'ended')),
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  UNIQUE (booking_series_code)
);

-- Community groups: a doubles four, a futsal side, a Wednesday crowd.
CREATE TABLE IF NOT EXISTS community_groups (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  sport TEXT NOT NULL,
  area TEXT,
  description TEXT,
  organiser_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  -- public: findable, anyone may ask to join; private: by invitation only.
  privacy TEXT NOT NULL DEFAULT 'public' CHECK (privacy IN ('public', 'private')),
  capacity INTEGER NOT NULL DEFAULT 20 CHECK (capacity BETWEEN 2 AND 60),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'closed')),
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_community_groups_sport ON community_groups(sport) WHERE status = 'active';

CREATE TABLE IF NOT EXISTS group_members (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id INTEGER NOT NULL REFERENCES community_groups(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role TEXT NOT NULL DEFAULT 'member' CHECK (role IN ('organiser', 'member')),
  status TEXT NOT NULL CHECK (status IN ('invited', 'requested', 'member', 'left', 'removed', 'declined')),
  invited_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  UNIQUE (group_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_group_members_user ON group_members(user_id);

-- Suggested games already told to a player, so none is suggested twice.
CREATE TABLE IF NOT EXISTS match_notices (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  game_id INTEGER NOT NULL REFERENCES open_games(id) ON DELETE CASCADE,
  sent_at TEXT NOT NULL DEFAULT datetime('now'),
  PRIMARY KEY (user_id, game_id)
);
