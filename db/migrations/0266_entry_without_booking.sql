-- Entry with no set time (docs/features/venue-operations.md#entry-with-no-set-time; lib/entries.ts): a climbing wall,
-- a bouldering room or a gym floor that admits people as they come, up to its places, rather than only for a booked
-- time. Off for every resource until a venue turns it on; the booking invariants are unchanged (bookings still claim
-- their places, and the database still refuses an overbooking of them).
--
-- Booking rules, set at any level of a venue's booking policies like the rest (a venue, an activity there, one
-- resource), and only ever acting on a resource with places:
-- * entry_mode: the resource admits people with no set time, while it has places free.
-- * entry_price: what one entry costs paid at the counter (a walk-in); none set, nobody is sold one.
-- * entry_max_stay: the longest an entry counts for, in minutes, after which it stops counting by itself.
-- * entry_self_check_in: a customer with a membership, pass or day pass that admits them may let themself in by the
--   check-in code; otherwise only the desk admits.
ALTER TABLE booking_policies ADD COLUMN IF NOT EXISTS entry_mode BOOLEAN;
ALTER TABLE booking_policies ADD COLUMN IF NOT EXISTS entry_price NUMERIC(10, 2) CHECK (entry_price IS NULL OR entry_price >= 0);
ALTER TABLE booking_policies ADD COLUMN IF NOT EXISTS entry_max_stay INTEGER CHECK (entry_max_stay IS NULL OR entry_max_stay BETWEEN 30 AND 1440);
ALTER TABLE booking_policies ADD COLUMN IF NOT EXISTS entry_self_check_in BOOLEAN;

-- A membership plan (tier) whose members are let in with no booking: at any resource taking entries in the venue's
-- business, or only at those offering one activity. Off by default: plans already sold admit nobody they did not.
ALTER TABLE membership_plans ADD COLUMN IF NOT EXISTS admits_entry BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE membership_plans ADD COLUMN IF NOT EXISTS admits_entry_sport TEXT REFERENCES activities(key) ON UPDATE CASCADE;

-- A day pass: a pass of one entry for one person that, once used, admits them again all that day (the venue's date
-- of its first use, kept on the pass), and nothing on any other day. Sold from a product like any pass.
ALTER TABLE pass_products ADD COLUMN IF NOT EXISTS day_pass BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE passes ADD COLUMN IF NOT EXISTS day_pass BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE passes ADD COLUMN IF NOT EXISTS day_used_on DATE;

-- Each person let in: open from admission until checked out, or until `stay_until` (the longest stay), after which
-- it no longer counts whether or not anybody closes it. What let them in is kept: the membership, the pass (whose
-- ledger line names the entry), or the counter sale that sold a walk-in entry.
CREATE TABLE IF NOT EXISTS entries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  court_id INTEGER NOT NULL REFERENCES courts(id) ON DELETE CASCADE,
  -- Who: the customer themself (by their number), or a participant (admitted as themself, their guardian's number).
  takes_part_as TEXT NOT NULL CHECK (takes_part_as IN ('customer', 'participant')),
  participant_id INTEGER REFERENCES participants(id) ON DELETE SET NULL,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  admitted_by TEXT NOT NULL CHECK (admitted_by IN ('membership', 'pass', 'day_pass', 'walk_in')),
  membership_id INTEGER REFERENCES memberships(id) ON DELETE SET NULL,
  pass_id INTEGER REFERENCES passes(id) ON DELETE SET NULL,
  sale_id INTEGER REFERENCES counter_sales(id) ON DELETE SET NULL,
  -- At the desk, or by the customer's own check-in.
  channel TEXT NOT NULL CHECK (channel IN ('desk', 'self')),
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  admin_name TEXT,
  admitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  stay_until TIMESTAMPTZ NOT NULL,
  checked_out_at TIMESTAMPTZ,
  -- Checked out by somebody, or closed by the scheduler after the longest stay.
  out_reason TEXT CHECK (out_reason IS NULL OR out_reason IN ('checked_out', 'stay_ended')),
  CHECK (stay_until > admitted_at),
  -- A participant's entry keeps naming nobody once the participant is erased; a customer's never names one.
  CHECK (takes_part_as = 'participant' OR participant_id IS NULL),
  CHECK ((checked_out_at IS NULL) = (out_reason IS NULL))
);
CREATE INDEX IF NOT EXISTS entries_open ON entries (court_id, stay_until) WHERE checked_out_at IS NULL;
CREATE INDEX IF NOT EXISTS entries_venue_day ON entries (venue_id, admitted_at);
CREATE INDEX IF NOT EXISTS entries_user ON entries (user_id) WHERE user_id IS NOT NULL;

-- A pass's ledger line spent on an entry.
ALTER TABLE pass_entries ADD COLUMN IF NOT EXISTS entry_id INTEGER REFERENCES entries(id) ON DELETE SET NULL;
