-- Refunds a gateway reports that MySenam did not ask for: made by the venue
-- (or the platform) in the gateway's own dashboard (lib/payments.ts
-- `recordGatewayRefunds`; docs/features/payments-and-credit.md#refunds-made-in-the-gateways-dashboard).
--
-- Stripe reports every refund on a payment (`charge.refunded`,
-- `charge.refund.updated`). A refund MySenam made carries its own key and is
-- already recorded in `online_refunds`; anything else is written here, once
-- per gateway refund, and matched in this order:
--
-- * `matched_hand`: a refund staff marked as made by hand on that payment,
--   for the same amount, with no gateway reference yet: the same money, so it
--   is linked (its `online_refunds.provider_ref` becomes the gateway's id);
-- * `matched_owed`: money owed back on the payment (a booking cancelled, a
--   membership cancelled with a refund): recorded as that refund, made in the
--   gateway, so it is never asked for again;
-- * `unasked`: the rest, which nothing in MySenam owed. Bookings and
--   memberships are not changed: staff are told, it is raised by the
--   integrity check and the activity log, and `unasked_left` counts towards
--   whatever is owed back on that payment later, so the gateway is not asked
--   to refund the same money twice.
CREATE TABLE IF NOT EXISTS gateway_refunds (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id INTEGER NOT NULL REFERENCES online_payments(id) ON DELETE CASCADE,
  provider TEXT NOT NULL,
  provider_refund_id TEXT NOT NULL UNIQUE,
  amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  matched_hand NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (matched_hand >= 0),
  matched_owed NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (matched_owed >= 0),
  unasked NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (unasked >= 0),
  unasked_left NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (unasked_left >= 0 AND unasked_left <= unasked),
  seen_at TEXT NOT NULL DEFAULT datetime('now'),
  CHECK (matched_hand + matched_owed + unasked = amount)
);
CREATE INDEX IF NOT EXISTS idx_gateway_refunds_payment ON gateway_refunds (payment_id);
CREATE INDEX IF NOT EXISTS idx_gateway_refunds_left ON gateway_refunds (payment_id) WHERE unasked_left > 0;
