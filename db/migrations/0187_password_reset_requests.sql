-- Forgotten passwords: the request queued, not worked through while the
-- customer waits.
--
-- Asking for a reset link already answered the same whether or not an
-- account held the address, but only an account's request did the work of
-- making and queuing a link before answering, so the reply took longer when
-- one did. Now every request is written here and the reply is sent; whether
-- an account holds the address is found out afterwards, in the background and
-- by the scheduler (lib/password-reset.ts; docs/architecture/authentication.md
-- #forgotten-passwords).
--
-- Kept: the address only until the request is worked through, seconds as a
-- rule; a request not worked through within the link's 30 minutes is dropped.
CREATE TABLE IF NOT EXISTS password_reset_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL CHECK (kind IN ('user', 'admin')),
  email TEXT NOT NULL,
  locale TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_password_reset_requests_created ON password_reset_requests (created_at);
