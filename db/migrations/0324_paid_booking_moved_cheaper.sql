-- Post-audit hardening (ADR 0067; docs/features/booking.md#changing-the-date-or-time): a paid booking moved to a cheaper time
-- (audit B16 = C12 = D15, DEC-16) gives the difference back by the way it was paid instead of silently keeping it.
--
-- The booking's price and its receipt stay as sold (nothing already written is edited); what goes back is a row of its own here, the
-- way a cheaper coach (`lesson_coach_changes`), a place taken off (`place_withdrawals`) and a manager's adjustment
-- (`booking_price_adjustments`) each leave one, and `paidPartLeft` (lib/store.ts) takes it off what a later cancellation gives back.
-- Rows are only ever added.
CREATE TABLE IF NOT EXISTS booking_move_refunds (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  -- Who moved it: the customer, or staff (with who, as the activity log has them).
  moved_by TEXT NOT NULL CHECK (moved_by IN ('customer', 'staff')),
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  admin_name TEXT,
  -- Where it was and where it went (kept as they were, the booking having moved on).
  from_date TEXT NOT NULL,
  from_start_min INTEGER NOT NULL,
  from_court_id INTEGER,
  to_date TEXT NOT NULL,
  to_start_min INTEGER NOT NULL,
  to_court_id INTEGER,
  -- What the booker had paid for the booking itself before the move, what it costs at the new time, and the difference given back.
  paid_before NUMERIC(12,2) NOT NULL,
  price_after NUMERIC(12,2) NOT NULL,
  amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  -- The way it was paid, and so the way the difference goes back: online (owed back on the payment), the counter (owed back at
  -- the counter, on the owed-back list), or stored credit (credit it was taken from).
  how TEXT NOT NULL CHECK (how IN ('online', 'counter', 'credit')),
  payment_id INTEGER REFERENCES online_payments(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_booking_move_refunds_booking ON booking_move_refunds (booking_id);

-- Credit given back for a cheaper move is not the booking's own refund on cancelling (as a place taken off, or a cheaper coach).
ALTER TABLE wallet_entries ADD COLUMN IF NOT EXISTS move_refund_id INTEGER REFERENCES booking_move_refunds(id) ON DELETE SET NULL;
