-- Counter money owed back on bookings the venue itself called off
-- (lib/counter-refunds.ts; docs/features/payments-and-credit.md#owed-back-after-the-venue-cancels).
--
-- Closing a day, taking a court out of service, a rain-out, the venue's API
-- key and calling off a class (its enrolments) cancel bookings without staff
-- settling each at the till, and nobody stands at the till for
-- each. A booking among them paid at the counter (cash, QR, transfer, card
-- terminal, or a tick whose method was never recorded) is written here as
-- owed back: how much, how it was paid, and why it was cancelled. Nothing has
-- left the till yet, so no credit note is written then.
--
-- Staff settle it later from the day list, as a staff cancellation settles:
-- handed back at the counter (a `counter_payouts` row, with its credit note,
-- in the cash-up of the day and the member of staff who paid it out) or, for
-- a booking made from an account, as stored credit (a `wallet_entries` row,
-- the credit note saying so). Who settled it, how and when are kept here.
--
-- One per booking: a booking is cancelled once, and settled once (the row is
-- claimed by its `settled_at` in the settling transaction).
CREATE TABLE IF NOT EXISTS counter_refunds_owed (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  booking_id INTEGER NOT NULL UNIQUE REFERENCES bookings(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  -- How it was paid and so how it goes back; null where the counter payment's method was never recorded.
  via TEXT CHECK (via IS NULL OR via IN ('cash', 'qr', 'transfer', 'card')),
  -- What cancelled it: a closed day, a court out of service, a rain-out, the venue's API key, or its class called off.
  cause TEXT NOT NULL CHECK (cause IN ('closure', 'outage', 'rain', 'api', 'class')),
  owed_since TIMESTAMPTZ NOT NULL DEFAULT now(),
  settled_at TIMESTAMPTZ,
  -- `back`: handed back at the counter; `credit`: given as stored credit.
  outcome TEXT CHECK (outcome IS NULL OR outcome IN ('back', 'credit')),
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  -- As it was, so the record reads right after the account is removed (as the activity log keeps it).
  admin_name TEXT,
  CHECK ((settled_at IS NULL) = (outcome IS NULL) AND (settled_at IS NULL) = (admin_name IS NULL))
);
CREATE INDEX IF NOT EXISTS idx_counter_refunds_owed_open ON counter_refunds_owed (venue_id) WHERE settled_at IS NULL;
