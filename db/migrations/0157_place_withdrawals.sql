-- Taking one person off a booking without cancelling it (ADR 0025;
-- lib/place-withdrawals.ts; docs/features/booking.md#taking-one-person-off-a-booking).
--
-- A guardian withdraws one child from a session the others still go to; a
-- group gives up a place it no longer needs. The person's row leaves
-- `booking_participants` (so the door, the roster, the summary on the booking
-- and every eligibility check simply no longer see them), and what happened is
-- kept here: who was on it, what their place cost, what went back and how,
-- what the venue kept on a late withdrawal, the pass entries returned, who did
-- it and why. A place withdrawn from a booking already paid leaves the
-- booking's price as it was sold (its receipt does not change); what was
-- given back has its own credit note, and the place's price (`price` where
-- `paid`) is left out of any later refund. On a booking not yet paid the
-- place's price simply comes off what is owed. The booking rows themselves
-- gain no column.

CREATE TABLE IF NOT EXISTS place_withdrawals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  -- The `booking_participants` row the person had (gone with the withdrawal); NULL for places nobody was named on.
  place_id INTEGER,
  takes_part_as TEXT NOT NULL CHECK (takes_part_as IN ('customer', 'participant', 'unnamed')),
  participant_id INTEGER REFERENCES participants(id) ON DELETE SET NULL,
  -- As named on the booking; cleared with the booking's names (lib/privacy.ts).
  name TEXT,
  -- Places given up: one for a person, or so many unnamed ones.
  places INTEGER NOT NULL DEFAULT 1 CHECK (places >= 1),
  -- What the places cost as charged (0 where nothing is priced per person: a court hired whole).
  price NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (price >= 0),
  -- Was the booking paid when it was done: money went back (true), or the price came off what is owed (false).
  paid BOOLEAN NOT NULL,
  -- Given back (to credit, owed back on an online payment, or by hand), and kept by the venue on a late withdrawal.
  refunded NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (refunded >= 0),
  kept NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (kept >= 0),
  late BOOLEAN NOT NULL DEFAULT false,
  kept_percent INTEGER,
  -- Pass entries (or minutes) given back for the place.
  units_returned INTEGER NOT NULL DEFAULT 0,
  -- Places freed on a shared-capacity session (0 on a court hired whole).
  released INTEGER NOT NULL DEFAULT 0,
  by_kind TEXT NOT NULL CHECK (by_kind IN ('customer', 'staff')),
  by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  by_name TEXT,
  reason TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_place_withdrawals_booking ON place_withdrawals (booking_id);
CREATE INDEX IF NOT EXISTS idx_place_withdrawals_participant ON place_withdrawals (participant_id) WHERE participant_id IS NOT NULL;
-- One withdrawal of a named place.
CREATE UNIQUE INDEX IF NOT EXISTS uq_place_withdrawals_place ON place_withdrawals (place_id) WHERE place_id IS NOT NULL;

-- A participant's record erased takes their name off the places they were
-- taken off, however the record goes (lib/participants.ts erases it).
CREATE OR REPLACE FUNCTION place_withdrawals_forget() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE place_withdrawals SET name = NULL WHERE participant_id = OLD.id;
  RETURN OLD;
END
$$;
DROP TRIGGER IF EXISTS participants_forget_withdrawals ON participants;
CREATE TRIGGER participants_forget_withdrawals BEFORE DELETE ON participants
  FOR EACH ROW EXECUTE FUNCTION place_withdrawals_forget();

-- Credit given back for a withdrawn place: apart from the booking's own refund on cancelling.
ALTER TABLE wallet_entries ADD COLUMN IF NOT EXISTS withdrawal_id INTEGER REFERENCES place_withdrawals(id) ON DELETE SET NULL;

-- Whether one person may be taken off a booking here, as a booking rule
-- inherited like the others (lib/booking-rules.ts `separatePlaces`): unset
-- means yes. A venue selling places as one package says no.
ALTER TABLE booking_policies ADD COLUMN IF NOT EXISTS separate_places BOOLEAN;
