-- Credit on a company or school account (lib/accounts.ts; lib/place-withdrawals.ts;
-- docs/features/payments-and-credit.md#company-and-school-accounts).
--
-- One person taken off a booking charged to an account after the month's
-- invoice was issued: the invoice is a document the account already has, so
-- it never changes. The place's price as charged (on the venue's cancellation
-- terms) becomes a credit note on the account instead, against the invoice
-- the booking was on (`invoice_id`), and comes off the account's next
-- invoice (`applied_invoice_id`), whole, in the order the credits were made.
-- Before the invoice is issued, nothing here: the place's price simply comes
-- off the booking's charge.
--
-- An invoice withdrawn before it is paid gives its credits back to the
-- account (applied_invoice_id goes NULL), to come off the next one.

CREATE TABLE IF NOT EXISTS account_credits (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id INTEGER NOT NULL REFERENCES venue_accounts(id) ON DELETE CASCADE,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  booking_id INTEGER REFERENCES bookings(id) ON DELETE SET NULL,
  -- The withdrawal it is for: one credit each.
  withdrawal_id INTEGER UNIQUE REFERENCES place_withdrawals(id) ON DELETE SET NULL,
  -- The invoice the booking was on when the credit was made (its number is on the credit note). Not a
  -- foreign key: withdrawing that invoice at the same moment never waits on, or deadlocks with, the credit.
  invoice_id INTEGER,
  amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  -- Its credit note (receipts, kind credit_note).
  receipt_id INTEGER REFERENCES receipts(id) ON DELETE SET NULL,
  -- The invoice it came off; NULL while it waits for the next one.
  applied_invoice_id INTEGER REFERENCES account_invoices(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_account_credits_account ON account_credits (account_id) WHERE applied_invoice_id IS NULL;
CREATE INDEX IF NOT EXISTS idx_account_credits_applied ON account_credits (applied_invoice_id) WHERE applied_invoice_id IS NOT NULL;
