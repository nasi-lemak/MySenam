-- Signing up by an emailed link: the request queued, not worked through while
-- the visitor waits.
--
-- Signing up used to make the account at once and answer 409 when an account
-- already had the address, so the form told anybody who typed an address
-- whether it belonged to a customer. Now it takes the address only and always
-- answers "check your email"; every request is written here and the reply is
-- sent, the same work whatever the address. Whether an account holds it is
-- found out afterwards, in the background and by the scheduler, exactly as a
-- forgotten password's request is (migration 0187; lib/registration.ts;
-- docs/architecture/authentication.md#signing-up).
--
-- Kept: the address only until the request is worked through, seconds as a
-- rule; a request not worked through within a link's 60 minutes is dropped.
CREATE TABLE IF NOT EXISTS registration_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  locale TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_registration_requests_created ON registration_requests (created_at);
