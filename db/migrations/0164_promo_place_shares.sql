-- A booking-wide promo code's share of each place (lib/discounts.ts;
-- lib/entitlements.ts `placeShares`; ADR 0025, changes of 27 October 2026).
--
-- On a booking priced by the place, a code's discount is worked out on the
-- court time after each place's member price and concession, then shared
-- between the places in proportion to what each place costs by then, to the
-- sen, by largest remainder (the earlier place first on a tie). Each named
-- place's share is kept here, so taking that person off the booking takes
-- off exactly their part of the code: no more, no less. Places nobody is
-- named on share what is left evenly. A share is never deleted: a place
-- withdrawn, or a discount worked out again (a concession added or refused
-- on the booking), marks it given back.
--
-- What a withdrawn place's share was is kept on the withdrawal too
-- (`place_withdrawals.promo_share`): on a booking already paid the code's
-- use stays as sold (its receipt does not change), and that part of it is
-- the withdrawn place's, not the places left.
--
-- Bookings made before keep what they have: no share is recorded for them,
-- and their code is shared evenly between their places, as it was.

CREATE TABLE IF NOT EXISTS promo_place_shares (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  -- The place's `booking_participants` row (not a foreign key: a withdrawn place's row goes, its share stays on record).
  place_id INTEGER NOT NULL,
  amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  reversed_at TIMESTAMPTZ,
  reversed_why TEXT CHECK (reversed_why IN ('withdrawn', 'repriced', 'released'))
);
-- One live share for one place.
CREATE UNIQUE INDEX IF NOT EXISTS uq_promo_place_shares_live ON promo_place_shares (booking_id, place_id) WHERE reversed_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_promo_place_shares_booking ON promo_place_shares (booking_id);

ALTER TABLE place_withdrawals ADD COLUMN IF NOT EXISTS promo_share NUMERIC(12,2) NOT NULL DEFAULT 0;
