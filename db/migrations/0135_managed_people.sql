-- Children (and others) an adult manages from their own account
-- (lib/managed-people.ts; docs/features/activities.md#applying-for-somebody-you-manage;
-- docs/architecture/privacy.md#people-an-adult-manages; ADR 0022).
--
-- A parent, legal guardian or other person with authority applies, signs the
-- waiver, books and is told on behalf of somebody who has no MySenam login of
-- their own. What is held is the least that does it: a name the family uses,
-- a declared birth year only where an activity needs an age, and the adult's
-- declaration of their relationship and authority, with when it was made.
-- Declared, never verified; no email, phone, photo, school or identity number.
-- Eligibility stays the person's own: a sign-off written for them counts only
-- for them, never for their parent or a sibling, and theirs never for them.

CREATE TABLE IF NOT EXISTS managed_people (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- The adult who manages them; erased with that adult's account.
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  -- A first name, or what the family calls them.
  display_name TEXT NOT NULL CHECK (length(display_name) BETWEEN 1 AND 40),
  -- As the adult declared it, and only where an activity needs an age.
  birth_year INTEGER CHECK (birth_year IS NULL OR birth_year BETWEEN 1900 AND 2200),
  -- As the adult declared it: parent, legal guardian, or another person with authority.
  relationship TEXT NOT NULL CHECK (relationship IN ('parent', 'guardian', 'other')),
  -- When the adult last declared that they have the authority to act for them.
  authority_declared_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- No longer managed from the account: nothing new for them; what exists stays.
  archived_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_managed_people_user ON managed_people (user_id);

-- Per activity: an adult applying for somebody else needs staff to record that
-- they reviewed the adult's authority before approval. Off unless the venue sets it.
ALTER TABLE approval_requirements ADD COLUMN IF NOT EXISTS guardian_check INTEGER NOT NULL DEFAULT 0 CHECK (guardian_check IN (0, 1));

-- An application made by the account's adult for somebody they manage: who it
-- is for, the relationship as declared then, the adult's declaration of
-- authority for this application, and the staff review of it where asked.
ALTER TABLE approval_requests ADD COLUMN IF NOT EXISTS managed_person_id INTEGER REFERENCES managed_people(id) ON DELETE SET NULL;
ALTER TABLE approval_requests ADD COLUMN IF NOT EXISTS relationship TEXT CHECK (relationship IS NULL OR relationship IN ('parent', 'guardian', 'other'));
ALTER TABLE approval_requests ADD COLUMN IF NOT EXISTS authority_declared_at TIMESTAMPTZ;
ALTER TABLE approval_requests ADD COLUMN IF NOT EXISTS authority_reviewed_at TIMESTAMPTZ;
ALTER TABLE approval_requests ADD COLUMN IF NOT EXISTS authority_reviewed_by TEXT;
-- One live application per person, activity and venue: the adult's own, and each person's they manage.
DROP INDEX IF EXISTS uq_approval_requests_live;
CREATE UNIQUE INDEX IF NOT EXISTS uq_approval_requests_live ON approval_requests (user_id, COALESCE(managed_person_id, 0), venue_id, sport)
  WHERE status IN ('pending', 'info_requested', 'in_person_due');
CREATE INDEX IF NOT EXISTS idx_approval_requests_managed ON approval_requests (managed_person_id) WHERE managed_person_id IS NOT NULL;

-- A sign-off or certification for somebody an adult manages: the account is
-- the adult's, the phone the adult's (to reach them), the eligibility theirs alone.
ALTER TABLE sign_offs ADD COLUMN IF NOT EXISTS managed_person_id INTEGER REFERENCES managed_people(id) ON DELETE SET NULL;
DROP INDEX IF EXISTS uq_sign_offs_live;
CREATE UNIQUE INDEX IF NOT EXISTS uq_sign_offs_live
  ON sign_offs (COALESCE(venue_id, 0), COALESCE(business_id, 0), phone_key(phone), COALESCE(sport, ''), kind, COALESCE(managed_person_id, 0))
  WHERE revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_sign_offs_managed ON sign_offs (managed_person_id) WHERE managed_person_id IS NOT NULL;

-- Who a booking is for, where the adult booked for somebody they manage: the
-- booking checks, door codes and staff views use that person's eligibility.
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS participant_id INTEGER REFERENCES managed_people(id) ON DELETE SET NULL;
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS participant_name TEXT;
CREATE INDEX IF NOT EXISTS idx_bookings_participant ON bookings (participant_id) WHERE participant_id IS NOT NULL;

-- A waiver the adult agreed to on behalf of somebody they manage: the adult
-- signs (name and number), the person takes part. Kept as the venue's record
-- of consent, as every signature is; the person's own agreement is apart from
-- the adult's.
ALTER TABLE waiver_signatures ADD COLUMN IF NOT EXISTS managed_person_id INTEGER REFERENCES managed_people(id) ON DELETE SET NULL;
ALTER TABLE waiver_signatures ADD COLUMN IF NOT EXISTS participant_name TEXT;
ALTER TABLE waiver_signatures DROP CONSTRAINT IF EXISTS waiver_signatures_pkey;
CREATE UNIQUE INDEX IF NOT EXISTS uq_waiver_signatures_own ON waiver_signatures (waiver_id, phone_key) WHERE participant_name IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_waiver_signatures_for ON waiver_signatures (waiver_id, managed_person_id) WHERE managed_person_id IS NOT NULL;
