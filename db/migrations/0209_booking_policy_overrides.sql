-- A manager's override of a venue policy for one booking (lib/policy-overrides.ts;
-- ADR 0026; docs/features/booking.md#manager-overrides).
--
-- Written in the same transaction as the booking it lets through (lib/store.ts
-- createBookingSeries), one row per policy gone past: which policy and the
-- refusal it answered, why (required), and which manager, by id and by name
-- as it was then, as the activity log keeps it. The activity log carries the
-- same as `booking.policy_overridden`.
--
-- Checked at commit, as every row pointing at a booking is (migration 0206).
CREATE TABLE IF NOT EXISTS booking_policy_overrides (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  policy TEXT NOT NULL CHECK (policy IN ('house_rules', 'strikes', 'guest_surge', 'assisted')),
  refusal_code TEXT NOT NULL,
  reason TEXT NOT NULL CHECK (length(trim(reason)) >= 5 AND length(reason) <= 300),
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  admin_name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (booking_id, policy)
);
CREATE INDEX IF NOT EXISTS idx_booking_policy_overrides_venue ON booking_policy_overrides (venue_id, created_at);
