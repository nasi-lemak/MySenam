-- An interrupted e-invoice submission is "outcome unknown", not "not sent"
-- (lib/myinvois.ts; docs/integrations/myinvois.md#sending-once).
--
-- When a sender stops between asking LHDN and writing its answer down, LHDN
-- may hold the document. Migration 0256 marked such a draft `failed` and the
-- screen said "Not sent", which is a claim MySenam cannot make. The owner's
-- decision of 29 October 2026: keep the rule that it is never sent again by
-- itself, but say "Needs verification: submission outcome unknown", have
-- staff reconcile against LHDN before retrying, and keep the history of the
-- attempt.
--
-- `status` stays `failed` for every existing reader (nothing here reached
-- LHDN as far as MySenam recorded, so the sent-frozen trigger, migrations
-- 0220 and 0226, still does not hold it); what is new is the mark that says
-- LHDN may have it, kept as history, and a record of every attempt.

-- When MySenam found that LHDN's answer was not recorded (the claim went
-- stale, or LHDN was asked and did not answer cleanly): the draft is shown as
-- needing verification until staff record what LHDN holds (it then has
-- LHDN's identifiers and is no longer a draft) or confirm LHDN does not have
-- it (the mark is cleared and the attempt stays in the history).
ALTER TABLE e_invoices ADD COLUMN IF NOT EXISTS outcome_unknown_at TEXT;
-- When the latest attempt to send it began: the claim's own start, kept when
-- the claim is cleared.
ALTER TABLE e_invoices ADD COLUMN IF NOT EXISTS last_attempt_at TEXT;
-- What the latest attempt sent, as built when it was claimed (a JSON object:
-- the document, its total, the receipts it covered, what it corrects), kept
-- only while LHDN's answer is unknown so that, if staff find LHDN holds it,
-- the record says exactly what was sent. Cleared when LHDN's answer is
-- written, and when staff confirm LHDN does not have it.
ALTER TABLE e_invoices ADD COLUMN IF NOT EXISTS attempt_payload TEXT;

-- Each attempt to send a document, and each staff step on one whose outcome
-- was unknown. Append-only: never edited, and never deleted while its
-- document exists (a draft that never reached LHDN, and was never in doubt,
-- is deleted by the retention run with its history; a document LHDN may hold
-- is not).
CREATE TABLE IF NOT EXISTS e_invoice_attempts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  e_invoice_id INTEGER NOT NULL REFERENCES e_invoices(id) ON DELETE CASCADE,
  at TEXT NOT NULL DEFAULT datetime('now'),
  -- claimed: a sender took it and is about to ask LHDN; sent / rejected: LHDN
  -- answered; not_sent: it did not reach LHDN; outcome_unknown: LHDN may have
  -- it; confirmed_not_at_lhdn / recorded_from_portal: what staff found.
  event TEXT NOT NULL CHECK (event IN ('claimed', 'sent', 'rejected', 'not_sent', 'outcome_unknown', 'confirmed_not_at_lhdn', 'recorded_from_portal')),
  -- A staff step: who, by name as it was (the account may be removed later).
  admin_id INTEGER,
  admin_name TEXT,
  detail TEXT
);
CREATE INDEX IF NOT EXISTS e_invoice_attempts_doc ON e_invoice_attempts (e_invoice_id, id);

CREATE OR REPLACE FUNCTION e_invoice_attempts_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  -- The only way a row goes: with the draft it belongs to (the cascade).
  IF TG_OP = 'DELETE' AND NOT EXISTS (SELECT 1 FROM e_invoices WHERE id = OLD.e_invoice_id) THEN
    RETURN OLD;
  END IF;
  RAISE EXCEPTION 'the history of an e-invoice is never edited or deleted' USING ERRCODE = 'check_violation';
END
$$;

DROP TRIGGER IF EXISTS e_invoice_attempts_append_only ON e_invoice_attempts;
CREATE TRIGGER e_invoice_attempts_append_only BEFORE UPDATE OR DELETE ON e_invoice_attempts
  FOR EACH ROW EXECUTE FUNCTION e_invoice_attempts_append_only();

-- Drafts already marked as interrupted (migration 0256's wording) are now
-- outcome unknown. The claim's start was not kept for them: the attempt shows
-- when this was recorded, not when it happened.
UPDATE e_invoices SET outcome_unknown_at = datetime('now')
 WHERE status = 'failed' AND outcome_unknown_at IS NULL
   AND document IS NULL AND submission_uid IS NULL AND uuid IS NULL AND cleared_at IS NULL
   AND error LIKE 'Sending was interrupted before LHDN%';
INSERT INTO e_invoice_attempts (e_invoice_id, event, detail)
SELECT id, 'outcome_unknown', NULL
  FROM e_invoices
 WHERE status = 'failed' AND outcome_unknown_at IS NOT NULL
   AND document IS NULL AND submission_uid IS NULL AND uuid IS NULL AND cleared_at IS NULL
   AND error LIKE 'Sending was interrupted before LHDN%';
