-- Scanning a failed supporting document again, and why documents were removed
-- (lib/document-scanning.ts, lib/approval-retention.ts;
-- docs/architecture/security.md#malware-scanning; ADR 0024, amended
-- 27 October 2026).
--
-- Every request to scan a failed document again is recorded: the platform
-- owner's (`manual`, with their reason), or the app's own once a scanner
-- answers again (`recovery`); refused requests too, with why. A retry puts
-- the same bytes back in quarantine; it never changes them and never releases
-- the document. Its outcome is written when the scan settles. At most one
-- retry of a document is open at a time. The history goes with the document.

CREATE TABLE IF NOT EXISTS approval_document_scan_retries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id INTEGER NOT NULL REFERENCES approval_documents(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('manual', 'recovery')),
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  by_name TEXT NOT NULL,
  reason TEXT NOT NULL,
  requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  outcome TEXT NOT NULL CHECK (outcome IN (
    'queued', 'clean', 'rejected', 'failed_scanner_unavailable', 'failed_unscannable',
    'refused_not_failed', 'refused_bytes_gone', 'refused_integrity', 'refused_limit')),
  settled_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_approval_document_scan_retries_document ON approval_document_scan_retries (document_id, id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_approval_document_scan_retries_open ON approval_document_scan_retries (document_id) WHERE outcome = 'queued';

-- Each supporting document removed, and under which rule: `retention` (its
-- own period: the documents' period or review window, its application
-- minimised or deleted, or left without one), `quarantine` (refused by the
-- scan, or unscannable with a working scanner, after the quarantine period)
-- or `erasure` (its applicant's account erased). Never because no scanner was
-- there: documents waiting for one are not removed for that. Numbers and
-- states only: no name, file name or content. Kept as long as the record of
-- who opened documents (lib/privacy.ts RETENTION.approvalAuditDays).
CREATE TABLE IF NOT EXISTS approval_document_removals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id INTEGER NOT NULL,
  request_id INTEGER,
  venue_id INTEGER,
  why TEXT NOT NULL CHECK (why IN ('retention', 'quarantine', 'erasure')),
  scan_status TEXT NOT NULL,
  scan_failure TEXT,
  legacy_reason TEXT,
  removed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_approval_document_removals_at ON approval_document_removals (removed_at);
CREATE INDEX IF NOT EXISTS idx_approval_document_removals_document ON approval_document_removals (document_id);
