-- Players invited to an open game or a community group by email: an
-- invitation, not a lookup.
--
-- Inviting by email used to look the address up and, where an account held
-- it, put that account's row in the game or the group at once, with its first
-- name on the host's or organiser's list: whoever typed an address could find
-- out whether it has a MySenam account, whose it is and whether it may be
-- invited. Now the address is sent a single-use link instead, the same
-- whether or not an account holds it (lib/player-invitations.ts;
-- docs/features/matchmaking.md#invitations-links-and-private-games). The host
-- or organiser sees "invited (email)" until the account that signs in with
-- that address accepts it, and the rules on who may be invited are applied
-- then (ADR 0016).
--
-- Kept: hashes only. The token is a keyed hash (as a password reset's), the
-- address a keyed hash of its lower-case form, to check the accepting account
-- is the one it was sent to without keeping the address.
CREATE TABLE IF NOT EXISTS player_invitations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- The one game or the one group it is for; nothing else.
  game_id INTEGER REFERENCES open_games(id) ON DELETE CASCADE,
  group_id INTEGER REFERENCES community_groups(id) ON DELETE CASCADE,
  invited_by INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  email_hash TEXT NOT NULL,
  -- After this it cannot be accepted: a game's, never past its start.
  expires_at TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  used_at TEXT,
  used_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  -- Replaced by a newer invitation to the same address.
  cancelled_at TEXT,
  CHECK ((game_id IS NULL) <> (group_id IS NULL))
);
-- One open invitation per address per game or group: inviting again replaces it.
CREATE UNIQUE INDEX IF NOT EXISTS idx_player_invitations_open_game ON player_invitations (game_id, email_hash)
  WHERE game_id IS NOT NULL AND used_at IS NULL AND cancelled_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_player_invitations_open_group ON player_invitations (group_id, email_hash)
  WHERE group_id IS NOT NULL AND used_at IS NULL AND cancelled_at IS NULL;
-- The daily limit on invitations counts every one sent.
CREATE INDEX IF NOT EXISTS idx_player_invitations_by ON player_invitations (invited_by, created_at);
