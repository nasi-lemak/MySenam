-- A message a customer is owed is written down in the same transaction as the fact it is about, so a stop between the two cannot
-- lose it (audit 9, G11 and C17). The request that did the thing still writes the message at once, as before; this row is only
-- what lets a later sweep (lib/notify.ts `tellOwedNotices`) find a booking, a venue's cancellation or a customer's cancellation
-- whose message was never written, and write it. One row per booking and kind; `told_at` is set by the sweep once the message
-- exists (or there is nothing left to say), never by the request, so there is nothing for a request to forget.
-- The foreign key is deferred like every other that points at a booking (0206, 0285).
CREATE TABLE IF NOT EXISTS notices_owed (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL CHECK (kind IN ('booking_confirmed', 'booking_cancelled_by_venue', 'booking_cancelled')),
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  told_at TEXT,
  UNIQUE (kind, booking_id)
);
CREATE INDEX IF NOT EXISTS idx_notices_owed_untold ON notices_owed (id) WHERE told_at IS NULL;
