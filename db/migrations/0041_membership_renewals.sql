-- A membership bought online that renews itself: the subscription at the
-- gateway (Stripe) that charges the plan's price again every period, until
-- the member or the venue stops it. Each charge is an online payment of its
-- own, and makes the next membership, run on from the last.
CREATE TABLE IF NOT EXISTS membership_subscriptions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  plan_id INTEGER REFERENCES membership_plans(id) ON DELETE SET NULL,
  provider TEXT NOT NULL,
  subscription_id TEXT NOT NULL UNIQUE,
  -- The membership its latest charge made.
  membership_id INTEGER REFERENCES memberships(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'stopped')),
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  stopped_at TEXT
);
CREATE INDEX IF NOT EXISTS membership_subscriptions_user ON membership_subscriptions (user_id, venue_id);

