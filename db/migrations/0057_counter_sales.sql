-- Things sold over the counter on their own, with no booking (lib/counter-sales.ts):
-- a drink, a tube of shuttles, a grip, a racket hired by a walk-in. Each is
-- receipted (receipts.source 'sale:<id>'); voiding one writes a credit note.
CREATE TABLE IF NOT EXISTS counter_sales (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  customer_name TEXT,
  customer_phone TEXT,
  -- [{ addonId, name, quantity, unitPrice }]: as sold, whatever the list says later.
  lines TEXT NOT NULL,
  total NUMERIC(12,2) NOT NULL CHECK (total > 0),
  paid_via TEXT NOT NULL CHECK (paid_via IN ('cash', 'qr', 'transfer', 'card')),
  voided_at TEXT,
  voided_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  void_reason TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS counter_sales_venue ON counter_sales (venue_id, created_at);
