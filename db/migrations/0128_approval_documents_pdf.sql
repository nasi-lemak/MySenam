-- Supporting documents as PDFs as well as images, and a record of every time
-- one is opened (lib/approval-documents.ts; docs/architecture/security.md#supporting-documents;
-- ADR 0021).
--
-- A photo or scan is still redrawn as an image. A PDF cannot be redrawn without
-- rendering it, which the server never does, so it is kept as sent once its
-- structure has been checked (no encryption, scripts, actions, attachments or
-- forms; a page limit), and is only ever handed out as a download. Both stay
-- in the database, never in the public photo store.

ALTER TABLE approval_documents ADD COLUMN IF NOT EXISTS file_name TEXT;
-- A PDF's page count, as counted when it was checked; NULL for an image.
ALTER TABLE approval_documents ADD COLUMN IF NOT EXISTS pages INTEGER;
ALTER TABLE approval_documents ADD COLUMN IF NOT EXISTS sha256 TEXT;
ALTER TABLE approval_documents DROP CONSTRAINT IF EXISTS approval_documents_type;
ALTER TABLE approval_documents ADD CONSTRAINT approval_documents_type CHECK (content_type IN ('image/webp', 'application/pdf'));
ALTER TABLE approval_documents DROP CONSTRAINT IF EXISTS approval_documents_pdf_pages;
ALTER TABLE approval_documents ADD CONSTRAINT approval_documents_pdf_pages CHECK (content_type <> 'application/pdf' OR pages IS NOT NULL);

-- Who opened which document, and when. No foreign key to the document or the
-- application: the record of an access outlives both, for its own period
-- (lib/approval-retention.ts), and names nothing of the document's contents.
CREATE TABLE IF NOT EXISTS approval_document_access (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id INTEGER NOT NULL,
  request_id INTEGER NOT NULL,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  at TIMESTAMPTZ NOT NULL DEFAULT now(),
  viewer TEXT NOT NULL CHECK (viewer IN ('customer', 'staff', 'coach')),
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  coach_id INTEGER REFERENCES coaches(id) ON DELETE SET NULL,
  viewer_name TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_approval_document_access_request ON approval_document_access (request_id, id);
CREATE INDEX IF NOT EXISTS idx_approval_document_access_at ON approval_document_access (at);
