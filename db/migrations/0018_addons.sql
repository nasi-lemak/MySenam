-- Extras a customer can add when booking a court or enrolling in a class
-- (lib/addons.ts): things to hire for the hour, things to buy.

CREATE TABLE IF NOT EXISTS venue_addons (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  name TEXT NOT NULL CHECK (char_length(name) BETWEEN 2 AND 60),
  -- 'rental': handed out for the booking and back after (a racket, a mat);
  -- 'sale': kept (a tube of shuttles, a drink).
  kind TEXT NOT NULL CHECK (kind IN ('rental', 'sale')),
  price NUMERIC(12,2) NOT NULL CHECK (price >= 0 AND price <= 1000),
  -- Rentals: how many there are, shared by every booking in the same hour.
  -- NULL: as many as asked for.
  stock INTEGER CHECK (stock IS NULL OR stock BETWEEN 1 AND 500),
  -- Offered only with this sport's courts and classes. NULL: with any.
  sport TEXT,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_venue_addons_venue ON venue_addons(venue_id);

-- What a booking came with, at the price it was then.
CREATE TABLE IF NOT EXISTS booking_addons (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  addon_id INTEGER NOT NULL REFERENCES venue_addons(id),
  name TEXT NOT NULL,
  kind TEXT NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 20),
  unit_price NUMERIC(12,2) NOT NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_booking_addons_booking ON booking_addons(booking_id);
CREATE INDEX IF NOT EXISTS idx_booking_addons_addon ON booking_addons(addon_id);
