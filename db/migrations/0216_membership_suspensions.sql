-- Memberships suspended for a period, and reactivated (the owner's decision
-- of 28 October 2026; lib/membership-suspensions.ts;
-- docs/features/pricing.md#suspending-a-membership).
--
-- A manager suspends a membership with a reason, from a date (today or
-- later) until a date or until it is reactivated. One row per suspension,
-- never overwritten, so the history is kept: who suspended it, when and why,
-- and who lifted it early, when and why. The membership row itself is not
-- changed, except its end where its plan extends it by the time suspended.
--
-- A membership covers nobody on a date inside a suspension: from
-- `starts_on` to `ends_on` inclusive (NULL: until reactivated). `until_on`
-- is the last day as it was set; `ends_on` the last day it applies, the same
-- until it is lifted early, then the day before it was lifted (before
-- `starts_on` where it was lifted before it began, so it covers no day).
CREATE TABLE IF NOT EXISTS membership_suspensions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  membership_id INTEGER NOT NULL REFERENCES memberships(id) ON DELETE CASCADE,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  starts_on TEXT NOT NULL,
  until_on TEXT,
  ends_on TEXT,
  reason TEXT NOT NULL,
  by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  by_name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  lifted_at TIMESTAMPTZ,
  lifted_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  lifted_by TEXT,
  lift_reason TEXT,
  -- A suspension still in force when the holder's next term starts (a renewal, however it was bought) is carried on
  -- to it, so a renewal never lifts it silently: the row it was carried from, and the first row of the chain, which
  -- is lifted as one.
  carried_from INTEGER REFERENCES membership_suspensions(id) ON DELETE SET NULL,
  chain_id INTEGER,
  -- The plan's "extend expiry by the time suspended" as it was when suspended, and the days this suspension has
  -- added to the membership's end in total (applied once, corrected when lifted early; never twice).
  extends_expiry BOOLEAN NOT NULL DEFAULT false,
  extended_days INTEGER NOT NULL DEFAULT 0,
  -- Why the end was not moved, where it could not be (a later term already starts the day after it).
  extension_note TEXT,
  CONSTRAINT membership_suspensions_dates CHECK (until_on IS NULL OR until_on >= starts_on),
  CONSTRAINT membership_suspensions_extended CHECK (extended_days >= 0)
);
CREATE INDEX IF NOT EXISTS idx_membership_suspensions_membership ON membership_suspensions (membership_id, starts_on);
CREATE UNIQUE INDEX IF NOT EXISTS uq_membership_suspensions_carried ON membership_suspensions (membership_id, carried_from) WHERE carried_from IS NOT NULL;
