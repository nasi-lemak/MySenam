-- Staff rosters and supervision rules (ADR 0036; docs/features/venue-operations.md#who-supervises-a-session).
--
-- A venue defines the roles it rosters (range officer, lifeguard, instructor, or its own), optionally tied to a qualification
-- the person must hold; rosters its staff accounts and its coaches in a weekly pattern with dated exceptions; and marks an
-- activity, or a resource's activity, as needing n people in a role on shift. A booking, class session or open game there is
-- bookable only where that many qualified people are rostered (lib/rosters.ts).

-- The roles a venue rosters. `key` is a built-in starter ('range_officer', 'lifeguard', 'instructor') or the venue's own ('role-<n>').
CREATE TABLE IF NOT EXISTS roster_roles (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  key TEXT NOT NULL,
  name TEXT NOT NULL,
  builtin BOOLEAN NOT NULL DEFAULT false,
  -- The qualification a holder must have (compared without case); NULL: none needed.
  qualification TEXT,
  active BOOLEAN NOT NULL DEFAULT true,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_roster_roles_key ON roster_roles (venue_id, key);

-- A qualification a person holds, as the venue recorded it (a reference seen, not a document kept), with the last day it holds.
-- A person is a member of the venue's staff ('staff', an admins row) or one of its coaches ('coach').
CREATE TABLE IF NOT EXISTS roster_qualifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  person_kind TEXT NOT NULL CHECK (person_kind IN ('staff', 'coach')),
  person_id INTEGER NOT NULL,
  qualification TEXT NOT NULL,
  reference TEXT,
  -- The last day it holds (inclusive, the venue's calendar); NULL: until taken back.
  expires_on TEXT,
  recorded_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  recorded_by_name TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  revoked_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_roster_quals_person ON roster_qualifications (venue_id, person_kind, person_id);

-- The weekly pattern: this person in this role on this weekday (0 Sunday), from the minute of the day it starts to the minute
-- it ends, which runs past 1440 for a shift that crosses midnight (22:00 to 06:00 is 1320 to 1800). The venue's clock, so
-- the instants it means follow the zone's own offset on the day (lib/interval.ts instantOf).
CREATE TABLE IF NOT EXISTS roster_shifts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  role_id INTEGER NOT NULL REFERENCES roster_roles(id) ON DELETE CASCADE,
  person_kind TEXT NOT NULL CHECK (person_kind IN ('staff', 'coach')),
  person_id INTEGER NOT NULL,
  weekday INTEGER NOT NULL CHECK (weekday BETWEEN 0 AND 6),
  from_min INTEGER NOT NULL CHECK (from_min >= 0 AND from_min < 1440),
  to_min INTEGER NOT NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  CHECK (to_min > from_min AND to_min <= from_min + 1440)
);
CREATE INDEX IF NOT EXISTS idx_roster_shifts_venue ON roster_shifts (venue_id, weekday);
CREATE INDEX IF NOT EXISTS idx_roster_shifts_person ON roster_shifts (person_kind, person_id);

-- Dated exceptions: an extra shift on one date (needs a role), or leave (from the time it names, the whole day when it names none).
CREATE TABLE IF NOT EXISTS roster_exceptions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  person_kind TEXT NOT NULL CHECK (person_kind IN ('staff', 'coach')),
  person_id INTEGER NOT NULL,
  date TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('extra', 'leave')),
  role_id INTEGER REFERENCES roster_roles(id) ON DELETE CASCADE,
  from_min INTEGER,
  to_min INTEGER,
  note TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  CHECK (kind = 'leave' OR (role_id IS NOT NULL AND from_min IS NOT NULL AND to_min IS NOT NULL AND to_min > from_min AND to_min <= from_min + 1440))
);
CREATE INDEX IF NOT EXISTS idx_roster_exceptions_venue ON roster_exceptions (venue_id, date);

-- What needs somebody on shift: n people in a role for an activity at the venue, for one resource (any activity on it), or for
-- one resource's activity. A booking, class session or open game on it is bookable only where every rule that applies is met.
CREATE TABLE IF NOT EXISTS supervision_rules (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  court_id INTEGER REFERENCES courts(id) ON DELETE CASCADE,
  activity TEXT,
  role_id INTEGER NOT NULL REFERENCES roster_roles(id) ON DELETE CASCADE,
  needed INTEGER NOT NULL DEFAULT 1 CHECK (needed BETWEEN 1 AND 20),
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  CHECK (court_id IS NOT NULL OR activity IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_supervision_rules ON supervision_rules (venue_id, COALESCE(court_id, 0), COALESCE(activity, ''), role_id);

-- Who supervises a session (a booking, which an open game rides on, or a class session): the person rostered when it was
-- made, kept as a record whatever the roster does afterwards; a person a manager put on it to cover; or a manager's decision to
-- let the session stand without one ('override', with the reason). `during` is the part of the session the row covers.
-- Rows are never deleted: a session moved or re-checked deactivates its old 'rostered' rows (`active` false) and writes new ones.
CREATE TABLE IF NOT EXISTS session_supervisors (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  booking_id INTEGER REFERENCES bookings(id) ON DELETE CASCADE,
  class_id INTEGER REFERENCES classes(id) ON DELETE CASCADE,
  role_id INTEGER REFERENCES roster_roles(id) ON DELETE SET NULL,
  role_key TEXT NOT NULL,
  role_name TEXT NOT NULL,
  person_kind TEXT CHECK (person_kind IN ('staff', 'coach')),
  person_id INTEGER,
  person_name TEXT,
  how TEXT NOT NULL CHECK (how IN ('rostered', 'covered', 'override')),
  during TSTZRANGE NOT NULL,
  reason TEXT,
  recorded_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  recorded_by_name TEXT,
  active BOOLEAN NOT NULL DEFAULT true,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  CHECK (booking_id IS NOT NULL OR class_id IS NOT NULL),
  CHECK (how = 'override' OR (person_kind IS NOT NULL AND person_id IS NOT NULL)),
  CHECK (how <> 'override' OR reason IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_session_supervisors_booking ON session_supervisors (booking_id) WHERE booking_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_session_supervisors_class ON session_supervisors (class_id) WHERE class_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_session_supervisors_person ON session_supervisors (person_kind, person_id) WHERE active;

-- A member of staff's own calendar of their shifts: found by the token's hash, as coaches' links are (lib/coach-schedule.ts).
CREATE TABLE IF NOT EXISTS roster_calendar_links (
  admin_id INTEGER PRIMARY KEY REFERENCES admins(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  expires_at TEXT NOT NULL
);
