-- A customer disputing a card payment with their bank (a chargeback): what
-- the gateway says about it, against the payment it is about.
CREATE TABLE IF NOT EXISTS payment_disputes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id INTEGER NOT NULL REFERENCES online_payments(id) ON DELETE CASCADE,
  provider_dispute_id TEXT NOT NULL UNIQUE,
  amount NUMERIC(12,2) NOT NULL,
  reason TEXT NOT NULL,
  -- The gateway's own word for where it stands: needs_response, under_review, won, lost...
  status TEXT NOT NULL,
  -- When the venue must answer by, to have a chance of keeping the money.
  due_by TEXT,
  outcome TEXT CHECK (outcome IN ('won', 'lost')),
  opened_at TEXT NOT NULL DEFAULT datetime('now'),
  updated_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS payment_disputes_payment ON payment_disputes (payment_id);
