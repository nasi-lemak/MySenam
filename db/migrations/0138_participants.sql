-- Participants apart from accounts (lib/participants.ts; ADR 0023;
-- docs/architecture/privacy.md#participants).
--
-- A user account is somebody who can sign in and act. A participant is the
-- person who actually takes part in a booking, class, competition, induction
-- or assessment, where that is not the account holder themself. The two are
-- related, never the same thing: a parent books for two children, a coach
-- registers people without taking part, staff book for somebody at the
-- counter. The account holder taking part as themself stays as before (no
-- participant row: the account, its number and its own records).
--
-- `managed_people` (0135) becomes `participants`: every reference to it
-- (applications, sign-offs, bookings, waiver signatures) follows the rename.
-- Who may act for a participant moves to `participant_guardians`, one row
-- per guardian and declaration, so a child can have two guardians and a
-- relationship can be corrected or revoked with its history kept. Stable ids
-- are the identity: never a name, a phone number or an email address, which
-- people share and change.

ALTER TABLE managed_people RENAME TO participants;

-- Somebody declared their relationship and authority to act for a participant.
CREATE TABLE IF NOT EXISTS participant_guardians (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  participant_id INTEGER NOT NULL REFERENCES participants(id) ON DELETE CASCADE,
  -- The guardian's account; erased with it. NULL: a guardian a venue's staff
  -- recorded by name and number only (no account), for that venue.
  user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
  -- Contact details only where there is no account: to reach them, never to identify anybody.
  contact_name TEXT CHECK (contact_name IS NULL OR length(contact_name) BETWEEN 2 AND 80),
  contact_phone TEXT,
  -- As declared: parent, legal guardian, or another person with authority.
  relationship TEXT NOT NULL CHECK (relationship IN ('parent', 'guardian', 'other')),
  -- When they last declared that they have the authority to act for the participant.
  authority_declared_at TIMESTAMPTZ NOT NULL,
  -- How it was established: declared online by the account holder; declared at
  -- a venue's counter to a named member of staff; or recorded by staff after
  -- reviewing it (with a reason).
  provenance TEXT NOT NULL CHECK (provenance IN ('online', 'counter', 'staff_review')),
  -- Staff who recorded it at the counter, or reviewed it: their name as it was.
  recorded_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  recorded_by_name TEXT,
  venue_id INTEGER REFERENCES venues(id) ON DELETE SET NULL,
  note TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- No longer managed by this guardian for now: nothing new; they may bring it back.
  archived_at TIMESTAMPTZ,
  -- Ended or corrected: for good, with who and why. History stays.
  revoked_at TIMESTAMPTZ,
  revoked_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  revoked_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  revoked_by_name TEXT,
  revoke_reason TEXT,
  CHECK (user_id IS NOT NULL OR (contact_name IS NOT NULL AND contact_phone IS NOT NULL)),
  CHECK (provenance = 'online' OR recorded_by_name IS NOT NULL)
);
-- One live relationship per guardian account and participant.
CREATE UNIQUE INDEX IF NOT EXISTS uq_participant_guardians_live
  ON participant_guardians (participant_id, user_id) WHERE user_id IS NOT NULL AND revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_participant_guardians_user ON participant_guardians (user_id) WHERE user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_participant_guardians_participant ON participant_guardians (participant_id);
CREATE INDEX IF NOT EXISTS idx_participant_guardians_contact ON participant_guardians (phone_key(contact_phone)) WHERE contact_phone IS NOT NULL;

-- Every managed person so far was added online by one adult, who declared the
-- relationship and authority then: that declaration, with its own times, is
-- the relationship's evidence, kept as it was.
INSERT INTO participant_guardians (participant_id, user_id, relationship, authority_declared_at, provenance, created_at, archived_at)
SELECT id, user_id, relationship, authority_declared_at, 'online', created_at, archived_at FROM participants;

DROP INDEX IF EXISTS idx_managed_people_user;
ALTER TABLE participants DROP COLUMN user_id;
ALTER TABLE participants DROP COLUMN relationship;
ALTER TABLE participants DROP COLUMN authority_declared_at;
ALTER TABLE participants DROP COLUMN archived_at;

-- Where the record came from: an account holder online, or a venue's staff
-- (and which venue, and who). A venue's own participants are seen by that
-- venue (and its business), and by their guardians; never by other venues.
ALTER TABLE participants ADD COLUMN IF NOT EXISTS origin TEXT NOT NULL DEFAULT 'account' CHECK (origin IN ('account', 'venue'));
ALTER TABLE participants ADD COLUMN IF NOT EXISTS venue_id INTEGER REFERENCES venues(id) ON DELETE SET NULL;
ALTER TABLE participants ADD COLUMN IF NOT EXISTS created_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE participants ADD COLUMN IF NOT EXISTS created_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL;
-- The participant's own login, once they have one and it was linked by an
-- agreed procedure (a guardian handed over and the account accepted, or staff
-- with a reason). One participant per account. Their bookings, sign-offs,
-- inductions and waivers stay theirs; that account's eligibility includes them.
ALTER TABLE participants ADD COLUMN IF NOT EXISTS linked_user_id INTEGER UNIQUE REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE participants ADD COLUMN IF NOT EXISTS linked_at TIMESTAMPTZ;
UPDATE participants p SET created_by_user_id = g.user_id FROM participant_guardians g WHERE g.participant_id = p.id;

-- A code one guardian gives another guardian, or the participant's own
-- account, to accept: both sides agree. Only its hash is kept.
CREATE TABLE IF NOT EXISTS participant_invites (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  participant_id INTEGER NOT NULL REFERENCES participants(id) ON DELETE CASCADE,
  purpose TEXT NOT NULL CHECK (purpose IN ('guardian', 'link')),
  code_hash TEXT NOT NULL UNIQUE,
  created_by_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ,
  used_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  cancelled_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_participant_invites_participant ON participant_invites (participant_id);

-- Who did what to a participant's record, on whose behalf, at which venue:
-- created, changed, a guardian added, corrected or revoked, linked, an
-- induction assigned. Goes with the participant.
CREATE TABLE IF NOT EXISTS participant_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  participant_id INTEGER NOT NULL REFERENCES participants(id) ON DELETE CASCADE,
  action TEXT NOT NULL,
  actor_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  actor_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  actor_name TEXT,
  venue_id INTEGER REFERENCES venues(id) ON DELETE SET NULL,
  detail TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_participant_events_participant ON participant_events (participant_id);
INSERT INTO participant_events (participant_id, action, actor_user_id, detail, created_at)
SELECT participant_id, 'guardian.declared', user_id, 'migration 0138: declared online when added (0135)', created_at FROM participant_guardians;

-- An application for a participant must never turn into the adult's own:
-- the participant is not deleted while an application rests on them.
ALTER TABLE approval_requests DROP CONSTRAINT IF EXISTS approval_requests_managed_person_id_fkey;
ALTER TABLE approval_requests ADD CONSTRAINT approval_requests_managed_person_id_fkey
  FOREIGN KEY (managed_person_id) REFERENCES participants(id) ON DELETE RESTRICT;
-- One live application per participant, activity and venue, whichever guardian made it.
CREATE UNIQUE INDEX IF NOT EXISTS uq_approval_requests_live_participant ON approval_requests (managed_person_id, venue_id, sport)
  WHERE managed_person_id IS NOT NULL AND status IN ('pending', 'info_requested', 'in_person_due');
