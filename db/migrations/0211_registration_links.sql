-- What a sign-up request sent (lib/registration.ts): for an address no
-- account holds, a link to finish making the account; for one that has an
-- account, a notice saying so, with how to sign in, and no link at all.
--
-- A link is 24 random bytes, kept only as a keyed hash (as a password
-- reset's). It works once, for 60 minutes, and only the newest for an address
-- works: issuing another replaces it, and at most one is open per address
-- (the partial unique index). Using it and making the account are one
-- transaction; the unique address on `users` is the backstop when two links,
-- or a link and Google, race for one address.
--
-- Rows count the emails an address has been sent (both kinds), for its
-- hourly and daily caps, so the address is kept, for a day at most: the
-- background work deletes older rows.
CREATE TABLE IF NOT EXISTS registration_links (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email CITEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('link', 'notice')),
  -- Only a link has one; a notice to an existing account carries nothing to use.
  token_hash TEXT UNIQUE,
  locale TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  -- The account was made with it.
  used_at TEXT,
  -- A newer link for the address replaced it, or the address got an account another way.
  replaced_at TEXT,
  CHECK ((kind = 'link') = (token_hash IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_registration_links_open ON registration_links (email)
  WHERE kind = 'link' AND used_at IS NULL AND replaced_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_registration_links_email ON registration_links (email, created_at);
CREATE INDEX IF NOT EXISTS idx_registration_links_created ON registration_links (created_at);
