-- Signing in with Google (lib/oauth.ts), and a customer's phone number
-- checked by a code sent to it on WhatsApp (lib/phone-check.ts).

-- The number the account last proved it holds, as WhatsApp writes it
-- (601...). The phone on the account counts as checked while it is still
-- this number; changing it undoes the check.
ALTER TABLE users ADD COLUMN IF NOT EXISTS verified_phone TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS phone_verified_at TEXT;
CREATE INDEX IF NOT EXISTS idx_users_verified_phone ON users(verified_phone) WHERE verified_phone IS NOT NULL;

-- An account signed in to with Google: the provider's own id for the
-- person, which never changes, unlike their email. An account made this way
-- has no password ('' never matches one).
CREATE TABLE IF NOT EXISTS user_identities (
  provider TEXT NOT NULL CHECK (provider IN ('google', 'apple')),
  subject TEXT NOT NULL,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  email TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  PRIMARY KEY (provider, subject)
);
CREATE INDEX IF NOT EXISTS idx_user_identities_user ON user_identities(user_id);

-- Codes sent to check a number. Only a hash is kept, and only for minutes.
CREATE TABLE IF NOT EXISTS phone_codes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  phone TEXT NOT NULL,
  number TEXT NOT NULL,
  code_hash TEXT NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0,
  expires_at TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_phone_codes_user ON phone_codes(user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_phone_codes_number ON phone_codes(number, created_at);
