-- Who a membership covered when: every change to whom it covers, as a record
-- of its own, never an overwrite (docs/features/pricing.md#changing-whom-a-family-membership-covers;
-- lib/membership-purchases.ts).
--
-- `membership_participants` stays the list of whom it covers now, which every
-- member price and members-only check reads. This is its history:
--
-- * `named`: covered from the sale (or the renewal) on;
-- * `added`: added by the account that bought it, within the term's places;
-- * `removed`: taken off by that account (the place it used stays used);
-- * `corrected_out` / `corrected_in`: a manager correcting a wrongly entered
--   person, with the reason (also in the activity log): uses no place.
--
-- A term's places used are its `named` and `added` rows, less `corrected_out`,
-- plus `corrected_in`. Bookings already made keep the people they were made
-- for and the price they were given, so what anybody used stays theirs.
CREATE TABLE IF NOT EXISTS membership_cover_changes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  membership_id INTEGER NOT NULL REFERENCES memberships(id) ON DELETE CASCADE,
  -- An erased participant's rows stay, naming nobody, so the term's count stays right.
  participant_id INTEGER REFERENCES participants(id) ON DELETE SET NULL,
  change TEXT NOT NULL CHECK (change IN ('named', 'added', 'removed', 'corrected_out', 'corrected_in')),
  by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  reason TEXT,
  at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_membership_cover_changes_membership ON membership_cover_changes (membership_id, id);
CREATE INDEX IF NOT EXISTS idx_membership_cover_changes_participant ON membership_cover_changes (participant_id) WHERE participant_id IS NOT NULL;

-- Memberships already sold: whom each covers now, as named when it was added.
-- Changes made before this were not recorded, so a term already running
-- counts only whom it covers now (never fewer places than it had).
INSERT INTO membership_cover_changes (membership_id, participant_id, change, by_admin_id, at)
SELECT mp.membership_id, mp.participant_id, 'named', mp.added_by_admin_id, mp.added_at
  FROM membership_participants mp
 WHERE NOT EXISTS (SELECT 1 FROM membership_cover_changes c WHERE c.membership_id = mp.membership_id);
