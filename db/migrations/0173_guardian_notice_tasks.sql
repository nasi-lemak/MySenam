-- Telling a guardian a venue recorded by name and number only that who acts
-- for a child changed (ADR 0023; lib/contact-guardians.ts;
-- docs/integrations/messaging.md#guardian-notices).
--
-- Such a guardian has no email. Where a code sent to their number has come
-- back to staff (the number reaches them) and WhatsApp is set up, a minimal
-- notice goes to that number through the outbox: the venue's name and that
-- there was a change to a child's guardians, to ask at the counter or sign
-- in. Never the child's name, nor anything else about them. Otherwise
-- nothing is sent, and the venue that recorded them is given this task: tell
-- them, then mark it done, with who and how.

CREATE TABLE IF NOT EXISTS guardian_notice_tasks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  participant_id INTEGER NOT NULL REFERENCES participants(id) ON DELETE CASCADE,
  -- The guardian to tell: a relationship recorded by name and number.
  guardianship_id INTEGER NOT NULL REFERENCES participant_guardians(id) ON DELETE CASCADE,
  -- The venue whose staff are to tell them: the one that recorded them.
  venue_id INTEGER REFERENCES venues(id) ON DELETE SET NULL,
  change TEXT NOT NULL CHECK (change IN ('added', 'ended', 'request', 'claimed')),
  -- Why nothing could be sent: the number was never proved to reach them, or no WhatsApp here.
  why TEXT NOT NULL CHECK (why IN ('unverified_number', 'no_channel')),
  -- What it is about (a relationship or a request), so one change makes one task per guardian.
  about INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  done_at TIMESTAMPTZ,
  done_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  done_by_name TEXT,
  done_how TEXT CHECK (done_how IS NULL OR done_how IN ('told', 'not_needed')),
  CHECK ((done_at IS NULL) = (done_how IS NULL))
);
CREATE INDEX IF NOT EXISTS idx_guardian_notice_tasks_open ON guardian_notice_tasks (venue_id) WHERE done_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_guardian_notice_tasks_participant ON guardian_notice_tasks (participant_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_guardian_notice_tasks_once ON guardian_notice_tasks (guardianship_id, change, COALESCE(about, 0));
