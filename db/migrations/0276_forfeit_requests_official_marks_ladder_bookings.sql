-- Three owner decisions of 4 November 2026 (docs/features/tournaments.md).
--
-- 1. Team-league forfeits are a manager's (lib/team-forfeits.ts). A team's captain, or a member of staff, may REQUEST one;
--    a request records who asked, which side is asked to forfeit and why, and changes nothing else: no result, no table, no
--    advancement, no court time. A manager confirms it (the existing forfeit path, through `decideFixture`) or declines it
--    with a reason; the request keeps who decided, when, why, and the table before and after.
CREATE TABLE IF NOT EXISTS team_forfeit_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  league_id INTEGER NOT NULL REFERENCES team_leagues(id) ON DELETE CASCADE,
  fixture_id INTEGER NOT NULL REFERENCES team_fixtures(id) ON DELETE CASCADE,
  -- The team asked to forfeit.
  forfeit_team INTEGER NOT NULL REFERENCES team_league_teams(id),
  -- Who asked: 'u:<user id>' (a captain) or 'a:<admin id>' (staff), so one person has one open request on a fixture.
  requester_key TEXT NOT NULL,
  requester_kind TEXT NOT NULL CHECK (requester_kind IN ('captain', 'staff')),
  requested_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  requested_by_team INTEGER REFERENCES team_league_teams(id),
  requested_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  -- A captain's team name (not the person's name), or the member of staff's name.
  requested_by_name TEXT NOT NULL,
  reason TEXT NOT NULL CHECK (reason IN ('no_show', 'short_handed', 'told_us', 'other')),
  note TEXT,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'confirmed', 'declined', 'withdrawn', 'expired', 'closed')),
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  expires_at TEXT NOT NULL,
  decided_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  decided_by_name TEXT,
  decided_at TEXT,
  decision_note TEXT,
  -- Why it closed without a decision of its own: the fixture was decided otherwise ('decided').
  closed_reason TEXT,
  -- The table (JSON, one entry per team) as it stood when a manager confirmed, and as it stood after.
  standings_before TEXT,
  standings_after TEXT
);
CREATE INDEX IF NOT EXISTS idx_forfeit_requests_fixture ON team_forfeit_requests (fixture_id);
CREATE INDEX IF NOT EXISTS idx_forfeit_requests_league ON team_forfeit_requests (league_id, status);
CREATE UNIQUE INDEX IF NOT EXISTS uq_forfeit_request_open ON team_forfeit_requests (fixture_id, requester_key) WHERE status = 'open';

-- 2. An official assigned to a performance (climbing) event enters its counted results from their own page
--    (lib/match-reports.ts, lib/official-performances.ts). `tournament_official_marks` is each line they entered, with
--    what it replaced, for their page's recent entries and the audit.
CREATE TABLE IF NOT EXISTS tournament_official_marks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournament_id INTEGER NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
  official_id INTEGER NOT NULL REFERENCES tournament_officials(id) ON DELETE CASCADE,
  official_name TEXT NOT NULL,
  match_id INTEGER NOT NULL REFERENCES tournament_matches(id) ON DELETE CASCADE,
  entry_id INTEGER NOT NULL REFERENCES tournament_entries(id) ON DELETE CASCADE,
  -- What the line showed before and after ("2T 3Z 3 5", "dns", "-" for nothing), and the counts as entered (JSON).
  was_shown TEXT,
  now_shown TEXT,
  was_counts TEXT,
  now_counts TEXT,
  entered_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_official_marks_official ON tournament_official_marks (official_id, id);

--    A round already finalised (every line in) or one a competitor advanced from is corrected by the organiser, through the
--    correction flow with its preview and token. An official asks: a correction request holds the reason and the intended
--    lines, and a manager reviews it there.
CREATE TABLE IF NOT EXISTS tournament_correction_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournament_id INTEGER NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
  match_id INTEGER NOT NULL REFERENCES tournament_matches(id) ON DELETE CASCADE,
  official_id INTEGER NOT NULL REFERENCES tournament_officials(id) ON DELETE CASCADE,
  official_name TEXT NOT NULL,
  reason TEXT NOT NULL,
  -- The intended lines (JSON, as recordPerformances takes them).
  lines TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'applied', 'declined', 'withdrawn')),
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  decided_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  decided_by_name TEXT,
  decided_at TEXT,
  decision_note TEXT
);
CREATE INDEX IF NOT EXISTS idx_correction_requests_tournament ON tournament_correction_requests (tournament_id, status);
CREATE UNIQUE INDEX IF NOT EXISTS uq_correction_request_open ON tournament_correction_requests (match_id, official_id) WHERE status = 'open';

-- 3. A ladder challenge holds no court time. Once the two have agreed a time they book as anybody does, and either may
--    attach the booking code of that ordinary booking to the challenge (lib/ladders.ts `attachBooking`). Attaching changes
--    nothing about the booking; if the booking is cancelled the attachment is dropped (`dropped_at`, with the reason) and
--    the players told. At most one live attachment per challenge, and a booking is attached to at most one challenge.
CREATE TABLE IF NOT EXISTS ladder_challenge_bookings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  challenge_id INTEGER NOT NULL REFERENCES ladder_challenges(id) ON DELETE CASCADE,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  attached_by INTEGER REFERENCES ladder_players(id) ON DELETE SET NULL,
  attached_at TEXT NOT NULL DEFAULT datetime('now'),
  dropped_at TEXT,
  dropped_reason TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_ladder_challenge_booking_challenge ON ladder_challenge_bookings (challenge_id) WHERE dropped_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_ladder_challenge_booking_booking ON ladder_challenge_bookings (booking_id) WHERE dropped_at IS NULL;
