-- Money staff hand back at the counter when they cancel a booking paid there
-- (lib/counter-refunds.ts; docs/features/payments-and-credit.md#cancelling-a-booking-paid-at-the-counter).
--
-- A booking paid in cash, by DuitNow QR, by transfer or on the card terminal
-- and cancelled by staff is credited on a credit note (`receipts`, source
-- `booking:<id>`) as before. Where staff chose to give the money back the way
-- it was paid, what went out of the till is written here: how much, how, on
-- which credit note, by whom and when, so the till can be squared and the
-- payout traced to a person. Where staff gave it as stored credit instead,
-- the credit is a `wallet_entries` row with the booking and the member of
-- staff, and nothing is paid out here.
--
-- One payout per booking: a booking is cancelled once (its status is claimed
-- in the same transaction), and the constraint says so again.
CREATE TABLE IF NOT EXISTS counter_payouts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  booking_id INTEGER NOT NULL UNIQUE REFERENCES bookings(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  credit_note_id INTEGER REFERENCES receipts(id) ON DELETE SET NULL,
  amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  -- How it was paid and so how it goes back; null where the counter payment's method was never recorded.
  via TEXT CHECK (via IS NULL OR via IN ('cash', 'qr', 'transfer', 'card')),
  -- The venue's late-cancellation share kept, where staff applied it; null when all of it went back.
  kept_percent INTEGER CHECK (kept_percent IS NULL OR (kept_percent >= 0 AND kept_percent <= 100)),
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  -- As it was, so the record reads right after the account is removed (as the activity log keeps it).
  admin_name TEXT NOT NULL,
  paid_out_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_counter_payouts_venue_day ON counter_payouts (venue_id, paid_out_at);
