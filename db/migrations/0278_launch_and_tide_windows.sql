-- Launch and tide windows for water hire (docs/features/booking.md#launch-and-tide-windows-for-water-hire, ADR 0037).
--
-- A resource may have a daily window narrower than the venue's opening hours: a fixed launch window by weekday, a window
-- from a tide table the venue typed or imported, or both (the intersection). Nothing here is fetched from a service and
-- nothing is a forecast: the table is the venue's own data, and a date it says nothing about is closed ("no tide data").
-- The rule and the table only narrow the hours; whether to launch is the venue's judgement (lib/launch-day.ts).

-- One rule per resource, or per activity on a resource (a NULL activity is every activity the resource offers; a rule for
-- one activity wins over it). `weekly` is JSON: seven entries, Sunday first, each {"from": minute, "to": minute} or null
-- (no launch that day). `min_height_cm` and the event fields are the tide rule: usable where the interpolated height is
-- at least `min_height_cm`, or within `event_minutes` of a tide event of `event_kind`. Heights are whole centimetres.
CREATE TABLE IF NOT EXISTS launch_rules (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  court_id INTEGER NOT NULL REFERENCES courts(id) ON DELETE CASCADE,
  sport TEXT REFERENCES activities(key) ON UPDATE CASCADE ON DELETE CASCADE,
  source TEXT NOT NULL CHECK (source IN ('weekly', 'tide', 'both')),
  weekly TEXT,
  station TEXT,
  tide_rule TEXT CHECK (tide_rule IN ('height', 'event')),
  min_height_cm INTEGER CHECK (min_height_cm BETWEEN -500 AND 2500),
  event_kind TEXT CHECK (event_kind IN ('high', 'low')),
  event_minutes INTEGER CHECK (event_minutes BETWEEN 0 AND 720),
  -- A window shorter than this is not offered; bookings must be back this many minutes before a window closes.
  min_window_min INTEGER NOT NULL DEFAULT 0 CHECK (min_window_min BETWEEN 0 AND 1440),
  return_buffer_min INTEGER NOT NULL DEFAULT 0 CHECK (return_buffer_min BETWEEN 0 AND 240),
  updated_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  updated_at TEXT NOT NULL DEFAULT datetime('now'),
  CHECK (source = 'tide' OR weekly IS NOT NULL),
  CHECK (source = 'weekly' OR (station IS NOT NULL AND tide_rule IS NOT NULL)),
  CHECK (tide_rule IS DISTINCT FROM 'height' OR min_height_cm IS NOT NULL),
  CHECK (tide_rule IS DISTINCT FROM 'event' OR (event_kind IS NOT NULL AND event_minutes IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_launch_rules_venue ON launch_rules (venue_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_launch_rules_court ON launch_rules (court_id) WHERE sport IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_launch_rules_court_sport ON launch_rules (court_id, sport) WHERE sport IS NOT NULL;

-- The venue's own tide table: one entry per station and instant. `at` is the instant as an ISO UTC string to the minute
-- (so entries sort by time as text); `source` says whether it was typed or came in a CSV import.
CREATE TABLE IF NOT EXISTS tide_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  station TEXT NOT NULL CHECK (length(station) BETWEEN 1 AND 60),
  at TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('high', 'low')),
  height_cm INTEGER NOT NULL CHECK (height_cm BETWEEN -500 AND 2500),
  source TEXT NOT NULL DEFAULT 'typed' CHECK (source IN ('typed', 'csv')),
  entered_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  UNIQUE (venue_id, station, at)
);
CREATE INDEX IF NOT EXISTS idx_tide_events_station ON tide_events (venue_id, station, at);

-- A booking outside the window that staff looked at and chose to keep as it is. It names the day's window as it stood
-- (`signature`), so the booking is listed again if the table or the rule changes it afterwards.
CREATE TABLE IF NOT EXISTS launch_kept (
  booking_id INTEGER PRIMARY KEY REFERENCES bookings(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  signature TEXT NOT NULL,
  kept_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  kept_at TEXT NOT NULL DEFAULT datetime('now')
);
