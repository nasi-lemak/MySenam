-- Registering online for an activity that needs a sign-off or certification
-- (lib/approvals.ts; docs/features/activities.md#registering-online-for-approval;
-- ADR 0019).
--
-- An approval request is its own record, apart from bookings: a customer's
-- account asks a venue for one activity, answers what the venue asks, and
-- staff or an authorised coach decide. Approved, it writes the sign-off or
-- certification that the booking rules already check (sign_offs), so no
-- booking path changes. A slot asked for alongside is held by an expiring
-- claim of its own kind, never by a booking.

-- What a venue asks before it approves somebody for an activity, and how.
CREATE TABLE IF NOT EXISTS approval_requirements (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  sport TEXT NOT NULL REFERENCES activities(key) ON UPDATE CASCADE,
  -- What an approval writes: an operational sign-off, or a certification seen.
  kind TEXT NOT NULL DEFAULT 'operational' CHECK (kind IN ('operational', 'certification')),
  -- What the venue tells applicants first.
  intro TEXT,
  -- Verification methods, each on when its words are given:
  -- an online declaration the customer ticks,
  declaration TEXT,
  -- documents staff review (a certificate; never identity documents),
  document_label TEXT,
  -- a video briefing the customer confirms having watched,
  video_url TEXT,
  -- and a mandatory in-person briefing or assessment staff record.
  in_person TEXT,
  -- Questions, as JSON: [{ "id", "text", "required" }].
  questions TEXT NOT NULL DEFAULT '[]',
  -- The venue's waiver must be agreed (lib/waivers.ts).
  waiver INTEGER NOT NULL DEFAULT 0 CHECK (waiver IN (0, 1)),
  -- How long an approval lasts, in days; NULL: until taken back.
  valid_days INTEGER CHECK (valid_days IS NULL OR valid_days BETWEEN 1 AND 3660),
  -- A request nobody acts on lapses after this many days.
  pending_days INTEGER NOT NULL DEFAULT 14 CHECK (pending_days BETWEEN 1 AND 90),
  -- A slot asked for is held this many hours at most.
  hold_hours INTEGER NOT NULL DEFAULT 48 CHECK (hold_hours BETWEEN 1 AND 336),
  -- Taking applications.
  open INTEGER NOT NULL DEFAULT 1 CHECK (open IN (0, 1)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (venue_id, sport),
  CHECK (declaration IS NOT NULL OR document_label IS NOT NULL OR video_url IS NOT NULL OR in_person IS NOT NULL)
);

-- Coaches the venue lists who may review applications for an activity, at their own link.
CREATE TABLE IF NOT EXISTS approval_reviewers (
  requirement_id INTEGER NOT NULL REFERENCES approval_requirements(id) ON DELETE CASCADE,
  coach_id INTEGER NOT NULL REFERENCES coaches(id) ON DELETE CASCADE,
  PRIMARY KEY (requirement_id, coach_id)
);

CREATE TABLE IF NOT EXISTS approval_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requirement_id INTEGER NOT NULL REFERENCES approval_requirements(id) ON DELETE CASCADE,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  sport TEXT NOT NULL REFERENCES activities(key) ON UPDATE CASCADE,
  -- Approvals are personal: always an account's.
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  -- pending: waiting for review (PENDING_APPROVAL); info_requested: a reviewer
  -- asked the customer something; in_person_due: the online part is accepted
  -- and the in-person step is still to be recorded.
  status TEXT NOT NULL CHECK (status IN ('pending', 'info_requested', 'in_person_due', 'approved', 'rejected', 'withdrawn', 'expired')),
  renewal_of INTEGER REFERENCES approval_requests(id) ON DELETE SET NULL,
  -- Answers to the venue's questions, as JSON { questionId: text }.
  answers TEXT NOT NULL DEFAULT '{}',
  declared_at TIMESTAMPTZ,
  video_watched_at TIMESTAMPTZ,
  waiver_signed_at TIMESTAMPTZ,
  -- As the customer declared: 18 or over, or not; for a minor, a parent or
  -- guardian's name and their declaration. Recorded as declared, never verified.
  declared_adult INTEGER NOT NULL CHECK (declared_adult IN (0, 1)),
  guardian_name TEXT,
  guardian_declared_at TIMESTAMPTZ,
  -- For a certification: what the customer says it is, for staff to check against the document.
  cert_reference TEXT,
  cert_expires_on TEXT,
  online_ok_at TIMESTAMPTZ,
  online_ok_by TEXT,
  in_person_at TIMESTAMPTZ,
  in_person_by TEXT,
  -- A live request lapses then, if nobody acts.
  expires_at TIMESTAMPTZ NOT NULL,
  decided_at TIMESTAMPTZ,
  -- Approved until this day (inclusive); NULL: until taken back.
  valid_until TEXT,
  renew_notice_at TIMESTAMPTZ,
  sign_off_id INTEGER REFERENCES sign_offs(id) ON DELETE SET NULL,
  -- A slot asked for, held until hold_until; never a booking until approved.
  court_id INTEGER REFERENCES courts(id) ON DELETE SET NULL,
  slot_date TEXT,
  slot_start INTEGER,
  slot_end INTEGER,
  hold_until TIMESTAMPTZ,
  slot_status TEXT CHECK (slot_status IN ('held', 'lapsed', 'released', 'booked', 'taken')),
  booking_id INTEGER REFERENCES bookings(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (declared_adult = 1 OR (guardian_name IS NOT NULL AND guardian_declared_at IS NOT NULL)),
  CHECK (court_id IS NULL OR (slot_status IS NOT NULL AND slot_date IS NOT NULL AND slot_start IS NOT NULL AND slot_end IS NOT NULL)),
  CHECK (slot_end IS NULL OR slot_end > slot_start)
);
-- One live request per person, activity and venue.
CREATE UNIQUE INDEX IF NOT EXISTS uq_approval_requests_live ON approval_requests (user_id, venue_id, sport)
  WHERE status IN ('pending', 'info_requested', 'in_person_due');
CREATE INDEX IF NOT EXISTS idx_approval_requests_venue ON approval_requests (venue_id, status);
CREATE INDEX IF NOT EXISTS idx_approval_requests_user ON approval_requests (user_id);
CREATE INDEX IF NOT EXISTS idx_approval_requests_expiring ON approval_requests (expires_at)
  WHERE status IN ('pending', 'info_requested', 'in_person_due');

-- Everything that happened to a request: who, when, what and why. Kept, never rewritten.
CREATE TABLE IF NOT EXISTS approval_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id INTEGER NOT NULL REFERENCES approval_requests(id) ON DELETE CASCADE,
  at TIMESTAMPTZ NOT NULL DEFAULT now(),
  actor TEXT NOT NULL CHECK (actor IN ('customer', 'staff', 'coach', 'system')),
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  coach_id INTEGER REFERENCES coaches(id) ON DELETE SET NULL,
  actor_name TEXT NOT NULL,
  action TEXT NOT NULL,
  reason TEXT
);
CREATE INDEX IF NOT EXISTS idx_approval_events_request ON approval_events (request_id, id);

-- Supporting documents, redrawn as images (nothing of the upload survives
-- but its pixels). Private: served only to the customer and the venue's
-- reviewers, deleted on a clock after the decision (lib/privacy.ts).
CREATE TABLE IF NOT EXISTS approval_documents (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id INTEGER NOT NULL REFERENCES approval_requests(id) ON DELETE CASCADE,
  content_type TEXT NOT NULL,
  size INTEGER NOT NULL,
  content BYTEA NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_approval_documents_request ON approval_documents (request_id);

-- A requested slot is held as a claim of its own kind until it is booked,
-- let go, or its time runs out: the exclusion constraint and the capacity
-- trigger count it while it lasts, as they do a waiting-list offer.
ALTER TABLE claims ADD COLUMN IF NOT EXISTS approval_id INTEGER REFERENCES approval_requests(id) ON DELETE CASCADE;
ALTER TABLE claims DROP CONSTRAINT IF EXISTS claims_kind_check;
ALTER TABLE claims ADD CONSTRAINT claims_kind_check CHECK (kind IN ('booking', 'offer', 'class', 'block', 'outage', 'move', 'approval'));
ALTER TABLE claims ADD CONSTRAINT claims_approval_source CHECK ((kind = 'approval') = (approval_id IS NOT NULL));
-- A hold always ends.
ALTER TABLE claims ADD CONSTRAINT claims_approval_expires CHECK (kind <> 'approval' OR expires_at IS NOT NULL);
CREATE INDEX IF NOT EXISTS idx_claims_approval ON claims(approval_id) WHERE approval_id IS NOT NULL;
