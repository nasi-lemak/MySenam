-- A recorded review of the install's retention periods says who reviewed
-- them and on what authority, for which country and which periods, and
-- where the written advice is kept (lib/retention-policy.ts; ADR 0024;
-- docs/architecture/privacy.md#applications-to-be-approved-for-an-activity).
--
-- A name and a day alone do not make a review mean anything. Each review is
-- now a row per jurisdiction (Malaysia and Singapore separately): the
-- reviewer's name and role or qualification as stated, their firm, which
-- periods it covers, the day, a reference to the written advice kept outside
-- MySenam, and what it was based on; and who recorded it. It is the platform
-- owner's record of what a reviewer advised: MySenam does not verify it, and
-- the app never calls the periods legally approved. A period or a country a
-- review does not cover stays provisional. Any change of the periods lapses
-- every review in force (lapsed_at), and nothing is deleted.

CREATE TABLE IF NOT EXISTS retention_policy_reviews (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  jurisdiction TEXT NOT NULL CHECK (jurisdiction IN ('MY', 'SG')),
  reviewer_name TEXT NOT NULL CHECK (length(reviewer_name) BETWEEN 3 AND 200),
  reviewer_role TEXT NOT NULL CHECK (length(reviewer_role) BETWEEN 3 AND 200),
  firm TEXT NOT NULL CHECK (length(firm) BETWEEN 2 AND 200),
  -- The periods it covers: documentDays, reviewDays, recordDays, quarantineDays, comma-separated.
  scope TEXT NOT NULL CHECK (scope ~ '^(documentDays|reviewDays|recordDays|quarantineDays)(,(documentDays|reviewDays|recordDays|quarantineDays)){0,3}$'),
  reviewed_on TEXT NOT NULL,
  advice_reference TEXT NOT NULL CHECK (length(advice_reference) BETWEEN 3 AND 200),
  basis TEXT NOT NULL CHECK (length(basis) BETWEEN 10 AND 2000),
  -- The periods as they stood when it was recorded, e.g. 90/30/365/7.
  periods TEXT NOT NULL,
  recorded_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  recorded_by_name TEXT NOT NULL,
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  lapsed_at TIMESTAMPTZ,
  lapse_reason TEXT,
  CHECK ((lapsed_at IS NULL) = (lapse_reason IS NULL))
);
CREATE INDEX IF NOT EXISTS idx_retention_policy_reviews_live ON retention_policy_reviews (jurisdiction) WHERE lapsed_at IS NULL;

ALTER TABLE retention_policy_events DROP CONSTRAINT IF EXISTS retention_policy_events_kind_check;
ALTER TABLE retention_policy_events ADD CONSTRAINT retention_policy_events_kind_check CHECK (kind IN ('changed', 'reviewed', 'lapsed'));

-- A review recorded before this, with a name, a day and a basis alone, no
-- longer counts: the periods are provisional again until one is recorded
-- with its provenance. The record of it stays in the events.
INSERT INTO retention_policy_events (kind, admin_id, by_name, detail)
SELECT 'lapsed', NULL, 'Migration 0162',
       'The review recorded on ' || reviewed_on || ' (' || reviewed_by || ') lapsed: it did not say the reviewer''s role, the jurisdictions and periods it covers, or where the written advice is kept. Record it again with them.'
  FROM retention_policy WHERE id = 1 AND reviewed_on IS NOT NULL;
UPDATE retention_policy
   SET reviewed_on = NULL, reviewed_by = NULL, review_basis = NULL, review_recorded_by_name = NULL, review_recorded_at = NULL
