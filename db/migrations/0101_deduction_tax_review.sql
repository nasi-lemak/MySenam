-- Which reasons for keeping deposit money carry a venue's tax is provisional
-- until somebody qualified has reviewed it (docs/features/venue-operations.md):
-- the venue records that review and who made it; any change after it needs
-- reviewing again. Every change and approval is kept, never pruned.
ALTER TABLE venues ADD COLUMN IF NOT EXISTS deduction_tax_approved_at TEXT;
ALTER TABLE venues ADD COLUMN IF NOT EXISTS deduction_tax_approved_by INTEGER REFERENCES admins(id) ON DELETE SET NULL;
ALTER TABLE venues ADD COLUMN IF NOT EXISTS deduction_tax_reviewer TEXT;

CREATE TABLE IF NOT EXISTS deduction_tax_changes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('changed', 'approved')),
  -- The treatment of every reason after the change, and what was changed from.
  treatments TEXT NOT NULL,
  changed TEXT,
  reviewer TEXT,
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  admin_name TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_deduction_tax_changes_venue ON deduction_tax_changes (venue_id, id);

-- On what footing each amount kept from a deposit was taxed: the country's
-- provisional default, the venue's own unreviewed choice, or a reviewed one.
ALTER TABLE counter_sales ADD COLUMN IF NOT EXISTS tax_basis TEXT CHECK (tax_basis IN ('provisional', 'venue', 'reviewed'));
