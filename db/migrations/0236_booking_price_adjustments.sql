-- A manager's adjustment of one booking's price (lib/price-adjustments.ts;
-- docs/features/pricing.md#a-managers-price-adjustment), with the reason, as
-- ADR 0026 keeps a policy override: which booking, the price before and after,
-- the difference, whether it made the booking complimentary, and which
-- manager, by id and by name as it was then.
--
-- Before the booking is paid (`paid` false) the price itself changes and the
-- booking's receipt, drawn from the booking, shows the difference as a line of
-- its own. After it was paid at the counter (`paid` true) the receipt stays as
-- sold: the difference goes back on a credit note of its own, and what a later
-- cancellation gives back leaves it out.
--
-- Checked at commit, as every row pointing at a booking is (migration 0206).
CREATE TABLE IF NOT EXISTS booking_price_adjustments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  before_price NUMERIC(10,2) NOT NULL,
  after_price NUMERIC(10,2) NOT NULL CHECK (after_price >= 0),
  delta NUMERIC(10,2) NOT NULL,
  complimentary BOOLEAN NOT NULL DEFAULT false,
  paid BOOLEAN NOT NULL DEFAULT false,
  reason TEXT NOT NULL CHECK (length(trim(reason)) >= 5 AND length(reason) <= 300),
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  admin_name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_booking_price_adjustments_booking ON booking_price_adjustments (booking_id);
CREATE INDEX IF NOT EXISTS idx_booking_price_adjustments_venue ON booking_price_adjustments (venue_id, created_at);
