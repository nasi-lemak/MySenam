-- A waiting-list entry keeps who it is for (lib/participant-bookings.ts;
-- ADR 0023; docs/features/booking.md#waitlists).
--
-- Until now an entry was its customer's: one name and number, one place. A
-- guardian queuing for two children needs both kept, and two places: an
-- offer must never reserve too few, nor turn into the guardian's own place.
--
-- `places`: how many places the entry waits for (an offer of a class or of a
-- shared facility holds that many, all or none). `customer_takes_part`: the
-- entry's customer takes one of them; false where they only queue for the
-- people named. Every entry so far was its customer's alone, one place.

ALTER TABLE waitlist ADD COLUMN IF NOT EXISTS places INTEGER NOT NULL DEFAULT 1 CHECK (places >= 1);
ALTER TABLE waitlist ADD COLUMN IF NOT EXISTS customer_takes_part BOOLEAN NOT NULL DEFAULT true;

-- Each participant an entry is for, by id, as booking_participants is for a
-- booking. A participant whose record is erased leaves the row with no id:
-- the entry is then never offered (it would book the wrong person), and goes
-- with the queue's ordinary retention.
CREATE TABLE IF NOT EXISTS waitlist_participants (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  waitlist_id INTEGER NOT NULL REFERENCES waitlist(id) ON DELETE CASCADE,
  participant_id INTEGER REFERENCES participants(id) ON DELETE SET NULL,
  -- As named when queued; cleared with the participant.
  name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_waitlist_participants_person ON waitlist_participants (waitlist_id, participant_id) WHERE participant_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_waitlist_participants_entry ON waitlist_participants (waitlist_id);
CREATE INDEX IF NOT EXISTS idx_waitlist_participants_participant ON waitlist_participants (participant_id) WHERE participant_id IS NOT NULL;
