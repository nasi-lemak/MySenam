-- A court out of service from one day to another, or until further notice
-- (ends_on NULL): resurfacing, a broken net, a pool drained.
CREATE TABLE IF NOT EXISTS court_outages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  court_id INTEGER NOT NULL REFERENCES courts(id) ON DELETE CASCADE,
  starts_on TEXT NOT NULL,
  ends_on TEXT,
  reason TEXT,
  created_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  CHECK (ends_on IS NULL OR ends_on >= starts_on)
);
CREATE INDEX IF NOT EXISTS idx_court_outages_court ON court_outages(court_id);

-- Every hour taken out of service between two dates: the hours staff blocked
-- one by one, and every trading hour of a court that is out for the day. All
-- that asks what is blocked asks this, so an outage closes a court everywhere
-- a block would — availability, search, booking, moving, the waitlist, the
-- schedule and the reports — without any of them knowing outages exist.
-- Where an hour is both, the hand-made block wins, as it says more (a reason
-- of its own, or only some places).
CREATE OR REPLACE FUNCTION blocks_between(d_from text, d_to text)
RETURNS TABLE (court_id integer, date text, hour integer, reason text, places integer)
LANGUAGE sql STABLE AS $$
  SELECT s.court_id, s.date, s.hour, s.reason, s.places
    FROM slot_blocks s
   WHERE s.date >= d_from AND s.date <= d_to
  UNION ALL
  (SELECT DISTINCT ON (o.court_id, day.d, h.h)
         o.court_id, to_char(day.d, 'YYYY-MM-DD'), h.h, o.reason, NULL::integer
    FROM court_outages o
    JOIN courts c ON c.id = o.court_id
    JOIN venues v ON v.id = c.venue_id
    CROSS JOIN LATERAL generate_series(
      GREATEST(o.starts_on, d_from)::date,
      LEAST(COALESCE(o.ends_on, d_to), d_to)::date,
      interval '1 day') AS day(d)
    CROSS JOIN LATERAL generate_series(v.open_hour, v.close_hour - 1) AS h(h)
   WHERE o.starts_on <= d_to AND (o.ends_on IS NULL OR o.ends_on >= d_from)
     AND NOT EXISTS (
       SELECT 1 FROM slot_blocks s
        WHERE s.court_id = o.court_id AND s.date = to_char(day.d, 'YYYY-MM-DD') AND s.hour = h.h)
   -- Two outages over one hour: the earlier one's reason.
   ORDER BY o.court_id, day.d, h.h, o.id)
$$;

