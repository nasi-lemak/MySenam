-- Audit 9, F2 (ADR 0059): an automatic suspension of somebody's messaging can be reviewed.
--
-- The date it is to be reviewed by (operational, not a legal period; null on one made before this: its day of making plus the
-- default), and the suspended person's request for a review: one short text, answered in neutral words (lifted or stands) by
-- somebody who may lift it. Nothing of any report is shown or asked, as for a youth group's restriction (ADR 0052). No legal
-- right to a review or to notification is promised: rights to review and notification are pending legal review.
ALTER TABLE player_message_suspensions ADD COLUMN IF NOT EXISTS review_by TEXT;

CREATE TABLE IF NOT EXISTS player_message_suspension_appeals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  suspension_id INTEGER NOT NULL REFERENCES player_message_suspensions(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  message TEXT,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'decided')),
  outcome TEXT CHECK (outcome IS NULL OR outcome IN ('lifted', 'continues')),
  decided_by_name TEXT,
  decision_reason TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  decided_at TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_suspension_appeal_open ON player_message_suspension_appeals (suspension_id) WHERE status = 'open';
CREATE INDEX IF NOT EXISTS idx_suspension_appeals_user ON player_message_suspension_appeals (user_id, id DESC);
