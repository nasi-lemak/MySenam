-- Agreeing to hear from a venue, and what the venue then sends (lib/marketing.ts).
-- One row per venue and email address: agreed when, in what words, and
-- withdrawn when. Kept after withdrawal, as the record that it was asked.
CREATE TABLE IF NOT EXISTS marketing_consents (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  email_key TEXT NOT NULL,
  name TEXT,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  locale TEXT,
  source TEXT NOT NULL,
  -- The words of the box ticked, as they were.
  wording TEXT NOT NULL,
  -- For the one-click unsubscribe link: no account needed to stop.
  token TEXT NOT NULL UNIQUE,
  consented_at TEXT NOT NULL DEFAULT datetime('now'),
  withdrawn_at TEXT,
  UNIQUE (venue_id, email_key)
);

CREATE TABLE IF NOT EXISTS marketing_campaigns (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  subject TEXT NOT NULL,
  body TEXT NOT NULL,
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  recipients INTEGER NOT NULL DEFAULT 0,
  sent_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS marketing_campaigns_venue ON marketing_campaigns (venue_id, sent_at);
