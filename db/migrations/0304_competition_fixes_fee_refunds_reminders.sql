-- Audit 9, competitions (FX10; docs/features/tournaments.md, ladders.md, ADR 0059).
--
-- 1. Entry fees taken at the counter and owed back (F4, C11). A tournament the venue calls off, or an entrant taken out before the
--    draw where the rules refund before the draw, owes back what was paid at the counter, as a booking the venue cancels does
--    (`counter_refunds_owed`, which is for bookings): the row says how much, how it was paid and why; staff settle it from the
--    same list, by whom and when kept here, and the credit note on the entry's receipt is written then (so the till, the credit
--    note and the cash-up agree). Nothing is paid out automatically. One per entry: it is owed once and settled once.
CREATE TABLE IF NOT EXISTS counter_fee_refunds_owed (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  tournament_entry_id INTEGER NOT NULL UNIQUE REFERENCES tournament_entries(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  -- The receipt it was taken on (`entry:<id>@...`), which the credit note reverses when it is settled.
  receipt_source TEXT NOT NULL,
  amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  -- How it was paid and so how it goes back; null where the method was never recorded.
  via TEXT CHECK (via IS NULL OR via IN ('cash', 'qr', 'transfer', 'card')),
  cause TEXT NOT NULL CHECK (cause IN ('tournament_cancelled', 'before_draw')),
  owed_since TIMESTAMPTZ NOT NULL DEFAULT now(),
  settled_at TIMESTAMPTZ,
  outcome TEXT CHECK (outcome IS NULL OR outcome IN ('back')),
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  admin_name TEXT,
  credit_note_id INTEGER REFERENCES receipts(id) ON DELETE SET NULL,
  CHECK ((settled_at IS NULL) = (outcome IS NULL) AND (settled_at IS NULL) = (admin_name IS NULL))
);
CREATE INDEX IF NOT EXISTS idx_counter_fee_refunds_owed_open ON counter_fee_refunds_owed (venue_id) WHERE settled_at IS NULL;

-- 2. A ladder challenge nobody has answered is reminded once before it forfeits (F9): the ladder's own lead in days before the
--    last day to answer (null: half the response window), and the last day it was reminded for (so a new last day is reminded
--    again, and a repeat run does nothing).
ALTER TABLE ladders ADD COLUMN IF NOT EXISTS remind_days INTEGER CHECK (remind_days IS NULL OR remind_days BETWEEN 1 AND 14);
ALTER TABLE ladder_challenges ADD COLUMN IF NOT EXISTS reminded_for TEXT;

-- 3. A walkover a player reported in a tournament, standing after the silence (F10): when the silent side was reminded before it
--    stands, and whether it stands because they said nothing (the evidence for staff: who reported it and when are already here).
ALTER TABLE tournament_reports ADD COLUMN IF NOT EXISTS reminded_at TEXT;
ALTER TABLE tournament_reports ADD COLUMN IF NOT EXISTS stood_by_silence BOOLEAN NOT NULL DEFAULT false;
