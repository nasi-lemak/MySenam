-- Gift vouchers: an amount bought for somebody else, at the counter or
-- online, that whoever holds it turns into stored credit at the venue.
--
-- 'pending' is one being paid for online, not yet anybody's; 'active' can be
-- used; 'redeemed' has become credit; 'void' was cancelled by staff.
CREATE TABLE IF NOT EXISTS gift_vouchers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  amount NUMERIC(12,2) NOT NULL,
  buyer_name TEXT NOT NULL,
  buyer_email TEXT,
  buyer_phone TEXT,
  recipient_name TEXT,
  message TEXT,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('pending', 'active', 'redeemed', 'void')),
  expires_on TEXT NOT NULL,
  sold_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  paid_via TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  redeemed_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  redeemed_at TEXT
);
CREATE INDEX IF NOT EXISTS gift_vouchers_venue ON gift_vouchers (venue_id, created_at);

ALTER TABLE online_payments DROP CONSTRAINT IF EXISTS online_payments_purpose_check;
ALTER TABLE online_payments ADD CONSTRAINT online_payments_purpose_check
  CHECK (purpose IN ('booking', 'invoice', 'share', 'entry', 'league', 'pack', 'topup', 'membership', 'voucher'));
-- The voucher a payment buys.
ALTER TABLE online_payments ADD COLUMN IF NOT EXISTS voucher_id INTEGER REFERENCES gift_vouchers(id) ON DELETE SET NULL;
