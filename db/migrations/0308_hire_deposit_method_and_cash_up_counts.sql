-- Hire deposits and the cash-up, audit 9 (C10, E13, H10; docs/features/payments-and-credit.md#cash-up, ADR 0061).
--
-- A hire deposit is money held for the customer, in the drawer, on the card terminal or in the QR account, until the kit comes
-- back. How it was held when the kit went out, and who took it and who gave it back, are kept with the record, so the cash-up can
-- list deposits held, given back and kept by method. Rows taken before this keep NULLs: shown as "not recorded", never as cash.
ALTER TABLE hire_records ADD COLUMN IF NOT EXISTS deposit_via TEXT CHECK (deposit_via IS NULL OR deposit_via IN ('cash', 'qr', 'transfer', 'card'));
ALTER TABLE hire_records ADD COLUMN IF NOT EXISTS taken_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL;
ALTER TABLE hire_records ADD COLUMN IF NOT EXISTS taken_by_name TEXT;
-- How what was given back (and what was kept) went: the method it was held by, or, for a deposit taken before that was recorded,
-- the one staff said on return; NULL where nobody said.
ALTER TABLE hire_records ADD COLUMN IF NOT EXISTS returned_via TEXT CHECK (returned_via IS NULL OR returned_via IN ('cash', 'qr', 'transfer', 'card'));
ALTER TABLE hire_records ADD COLUMN IF NOT EXISTS returned_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL;
ALTER TABLE hire_records ADD COLUMN IF NOT EXISTS returned_by_name TEXT;

-- What a cashier counted at the end of a shift, against what the cash-up expected. Rows are only added: a recount is another
-- row, and the latest counts. `scope_staff_id` is the member of staff whose takings were counted, NULL for everybody's; `expected`
-- is what the cash-up said at that moment, kept so the variance never changes afterwards.
CREATE TABLE IF NOT EXISTS cash_up_counts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  day TEXT NOT NULL,
  scope_staff_id INTEGER,
  method TEXT NOT NULL CHECK (method IN ('cash', 'qr', 'transfer', 'card')),
  counted NUMERIC(12,2) NOT NULL CHECK (counted >= 0),
  expected NUMERIC(12,2) NOT NULL,
  -- counted less expected: negative when short.
  variance NUMERIC(12,2) NOT NULL,
  note TEXT CHECK (note IS NULL OR length(note) <= 300),
  counted_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  counted_by_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_cash_up_counts_day ON cash_up_counts (venue_id, day, method, id);
