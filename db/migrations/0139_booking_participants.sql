-- Who takes a place on a booking (lib/participants.ts; ADR 0023).
--
-- One row per person taking part: a participant (a child a parent booked
-- for, somebody staff booked for at the counter), or the booking's own
-- customer when they take a place alongside others. A booking with no rows
-- here is taken by its customer alone, as every booking always was: an
-- adult booking for themself is unchanged. A parent booking two children
-- has two rows and takes two places; a parent who only pays and watches has
-- none of their own.
--
-- This table is the one record of who takes part. `bookings.participant_id`
-- and `participant_name` (0135) stay as a summary the database keeps from it
-- (the first participant, and everybody's names), for the screens and
-- queries that show one line per booking; no code writes them.

CREATE TABLE IF NOT EXISTS booking_participants (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  -- 'customer': the booking's own customer takes a place; 'participant': somebody else does.
  takes_part_as TEXT NOT NULL CHECK (takes_part_as IN ('customer', 'participant')),
  -- NULL for the customer; for a participant, NULL only once their record was erased
  -- (the row stays as the venue's record that a place was taken, counting for nobody).
  participant_id INTEGER REFERENCES participants(id) ON DELETE SET NULL,
  -- As named when booked; cleared with the booking's names (lib/privacy.ts).
  name TEXT,
  -- Who put them on it: the account booking, or staff at the counter.
  added_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  added_by_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (takes_part_as = 'participant' OR participant_id IS NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_booking_participants_person ON booking_participants (booking_id, participant_id) WHERE participant_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_booking_participants_customer ON booking_participants (booking_id) WHERE takes_part_as = 'customer';
CREATE INDEX IF NOT EXISTS idx_booking_participants_booking ON booking_participants (booking_id);
CREATE INDEX IF NOT EXISTS idx_booking_participants_participant ON booking_participants (participant_id) WHERE participant_id IS NOT NULL;

-- Every booking made so far for somebody an adult manages (0135): that person,
-- added by the adult who booked. A name left where the person's record has
-- since gone is kept as it was, counting for nobody. The booking itself,
-- its money and its customer are not touched.
INSERT INTO booking_participants (booking_id, takes_part_as, participant_id, name, added_by_user_id)
SELECT id, 'participant', participant_id, participant_name, user_id FROM bookings
 WHERE participant_id IS NOT NULL OR participant_name IS NOT NULL;

-- The summary on the booking, kept by the database from the rows above.
CREATE OR REPLACE FUNCTION booking_participants_summary(target INTEGER) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  UPDATE bookings b SET
    participant_id = (SELECT bp.participant_id FROM booking_participants bp
                       WHERE bp.booking_id = target AND bp.takes_part_as = 'participant' AND bp.participant_id IS NOT NULL
                       ORDER BY bp.id LIMIT 1),
    participant_name = CASE WHEN EXISTS (SELECT 1 FROM booking_participants bp WHERE bp.booking_id = target AND bp.takes_part_as = 'participant')
      THEN (SELECT string_agg(bp.name, ', ' ORDER BY bp.id) FROM booking_participants bp WHERE bp.booking_id = target AND bp.name IS NOT NULL) END
  WHERE b.id = target
    AND (b.participant_id IS DISTINCT FROM (SELECT bp.participant_id FROM booking_participants bp
                       WHERE bp.booking_id = target AND bp.takes_part_as = 'participant' AND bp.participant_id IS NOT NULL
                       ORDER BY bp.id LIMIT 1)
      OR b.participant_name IS DISTINCT FROM CASE WHEN EXISTS (SELECT 1 FROM booking_participants bp WHERE bp.booking_id = target AND bp.takes_part_as = 'participant')
      THEN (SELECT string_agg(bp.name, ', ' ORDER BY bp.id) FROM booking_participants bp WHERE bp.booking_id = target AND bp.name IS NOT NULL) END);
END
$$;
CREATE OR REPLACE FUNCTION booking_participants_changed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP <> 'INSERT' THEN PERFORM booking_participants_summary(OLD.booking_id); END IF;
  IF TG_OP <> 'DELETE' AND (TG_OP = 'INSERT' OR NEW.booking_id <> OLD.booking_id) THEN PERFORM booking_participants_summary(NEW.booking_id); END IF;
  RETURN NULL;
END
$$;
DROP TRIGGER IF EXISTS booking_participants_summary ON booking_participants;
CREATE TRIGGER booking_participants_summary AFTER INSERT OR UPDATE OR DELETE ON booking_participants
  FOR EACH ROW EXECUTE FUNCTION booking_participants_changed();
