-- Two owner requests of 5 November 2026 (docs/architecture/decisions/0040-ladder-court-time-and-team-ladders.md;
-- docs/features/tournaments.md#club-ladders, #team-ladders; lib/ladder-holds.ts, lib/team-ladders.ts).
--
-- 1. A ladder may be set to hold court time for its accepted challenges. Off by default: the owner's decision of 4 November
--    (a challenge holds no court time; the players book as anybody does) stands for every ladder that does not turn it on.
--    A hold is a block the hold owns, like a team league's fixture, under the claims constraints; no money moves.
-- 2. Persistent teams (lib/teams.ts) may enter a ladder of teams. A team match is made of games from the sport's template and
--    scored by the team league's own checks (`lib/team-leagues.ts`); nothing here scores a match.

-- ---------------------------------------------------------------- ladder settings

ALTER TABLE ladders ADD COLUMN IF NOT EXISTS court_time_on BOOLEAN NOT NULL DEFAULT false;
-- Minutes held for a match; NULL: the template's match length (a team ladder: its games' minutes added up).
ALTER TABLE ladders ADD COLUMN IF NOT EXISTS match_minutes INTEGER CHECK (match_minutes IS NULL OR match_minutes BETWEEN 10 AND 480);
-- 'players' (singles or pairs, as before) or 'teams' (persistent teams, entered by their captain).
ALTER TABLE ladders ADD COLUMN IF NOT EXISTS kind TEXT NOT NULL DEFAULT 'players' CHECK (kind IN ('players', 'teams'));
-- A ladder of teams: what a team match is made of (JSON list of singles / doubles / team, as a team league's), minutes held for a
-- game, the fewest and most a team has to have to enter, and the most games one person plays in one match.
ALTER TABLE ladders ADD COLUMN IF NOT EXISTS rubbers TEXT;
ALTER TABLE ladders ADD COLUMN IF NOT EXISTS rubber_minutes INTEGER CHECK (rubber_minutes IS NULL OR rubber_minutes BETWEEN 5 AND 300);
ALTER TABLE ladders ADD COLUMN IF NOT EXISTS roster_min INTEGER CHECK (roster_min IS NULL OR roster_min BETWEEN 1 AND 40);
ALTER TABLE ladders ADD COLUMN IF NOT EXISTS roster_max INTEGER CHECK (roster_max IS NULL OR roster_max BETWEEN 1 AND 40);
ALTER TABLE ladders ADD COLUMN IF NOT EXISTS max_rubbers_per_player INTEGER CHECK (max_rubbers_per_player IS NULL OR max_rubbers_per_player BETWEEN 1 AND 10);

-- The courts a ladder holds time on; none named: any of the venue's courts for the sport.
CREATE TABLE IF NOT EXISTS ladder_courts (
  ladder_id INTEGER NOT NULL REFERENCES ladders(id) ON DELETE CASCADE,
  court_id INTEGER NOT NULL REFERENCES courts(id) ON DELETE CASCADE,
  PRIMARY KEY (ladder_id, court_id)
);

-- Caps on held court time, install data (one row): holds a ladder may have live at once, and holds made for one player's (or
-- team's) challenges in any 7 days, moves included. A manager's own release or move is not counted against the second.
CREATE TABLE IF NOT EXISTS ladder_hold_limits (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  max_live_per_ladder INTEGER NOT NULL CHECK (max_live_per_ladder BETWEEN 1 AND 200),
  max_per_player_week INTEGER NOT NULL CHECK (max_per_player_week BETWEEN 1 AND 50)
);
INSERT INTO ladder_hold_limits (id, max_live_per_ladder, max_per_player_week) VALUES (1, 8, 4) ON CONFLICT (id) DO NOTHING;

-- ---------------------------------------------------------------- the hold of a challenge

-- One row per hold ever made for a challenge, so a hold's life (made, moved, released and why) is kept and the caps can count it.
-- The court time itself is `blocks.ladder_hold_id`: the hold owns its blocks, so a staff block or unblock never carves them.
-- `date`, `start_min`, `end_min` are the match; `held_from`/`held_to` the match with the court's operational time either side.
CREATE TABLE IF NOT EXISTS ladder_court_holds (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ladder_id INTEGER NOT NULL REFERENCES ladders(id) ON DELETE CASCADE,
  challenge_id INTEGER NOT NULL REFERENCES ladder_challenges(id) ON DELETE CASCADE,
  court_id INTEGER REFERENCES courts(id) ON DELETE SET NULL,
  date TEXT NOT NULL,
  start_min INTEGER NOT NULL,
  end_min INTEGER NOT NULL,
  held_from INTEGER NOT NULL,
  held_to INTEGER NOT NULL,
  -- Who made it: the players' agreement ('players'), or a manager ('staff').
  made_by TEXT NOT NULL DEFAULT 'players' CHECK (made_by IN ('players', 'staff')),
  made_by_name TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  released_at TEXT,
  -- withdrawn, declined, forfeited, lapsed, ignored, played, season, left, frozen, moved, booking, staff, lost
  released_reason TEXT,
  released_by TEXT,
  release_note TEXT
);
CREATE INDEX IF NOT EXISTS idx_ladder_holds_ladder ON ladder_court_holds (ladder_id) WHERE released_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_ladder_holds_challenge ON ladder_court_holds (challenge_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_ladder_hold_live ON ladder_court_holds (challenge_id) WHERE released_at IS NULL;

ALTER TABLE blocks ADD COLUMN IF NOT EXISTS ladder_hold_id INTEGER REFERENCES ladder_court_holds(id) ON DELETE CASCADE;
CREATE INDEX IF NOT EXISTS idx_blocks_ladder_hold ON blocks (ladder_hold_id) WHERE ladder_hold_id IS NOT NULL;

-- A time the other player is asked to agree for a challenge that is already accepted (a move, or the first specific time).
ALTER TABLE ladder_challenges ADD COLUMN IF NOT EXISTS move_on TEXT;
ALTER TABLE ladder_challenges ADD COLUMN IF NOT EXISTS move_min INTEGER;
ALTER TABLE ladder_challenges ADD COLUMN IF NOT EXISTS move_by INTEGER REFERENCES ladder_players(id);

-- ---------------------------------------------------------------- ladders of teams

-- A team's place: the persistent team (its name as it was entered is `name`). The captain of the team acts for it, whoever that is now.
ALTER TABLE ladder_players ADD COLUMN IF NOT EXISTS team_id INTEGER REFERENCES teams(id) ON DELETE SET NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_ladder_player_team ON ladder_players (ladder_id, team_id) WHERE team_id IS NOT NULL AND status = 'active';

-- The games of a team challenge, in order, the challenger's side as 'home': the same shape as a team league fixture's games.
CREATE TABLE IF NOT EXISTS ladder_challenge_rubbers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  challenge_id INTEGER NOT NULL REFERENCES ladder_challenges(id) ON DELETE CASCADE,
  rubber_no INTEGER NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('singles', 'doubles', 'team')),
  score TEXT,
  winner TEXT CHECK (winner IN ('home', 'away')),
  played BOOLEAN NOT NULL DEFAULT false,
  walkover BOOLEAN NOT NULL DEFAULT false,
  UNIQUE (challenge_id, rubber_no)
);

-- Who plays each game, as each captain picked them from the team's members (names as they were). Never public.
CREATE TABLE IF NOT EXISTS ladder_challenge_lineups (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  challenge_id INTEGER NOT NULL REFERENCES ladder_challenges(id) ON DELETE CASCADE,
  rubber_no INTEGER NOT NULL,
  side TEXT NOT NULL CHECK (side IN ('home', 'away')),
  team_member_id INTEGER REFERENCES team_members(id) ON DELETE SET NULL,
  name TEXT NOT NULL,
  is_junior BOOLEAN NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS idx_ladder_lineups_challenge ON ladder_challenge_lineups (challenge_id, side);
CREATE INDEX IF NOT EXISTS idx_ladder_lineups_member ON ladder_challenge_lineups (team_member_id) WHERE team_member_id IS NOT NULL;

-- A forfeit on a team ladder is a manager's, as in a team league (migration 0276): a captain or a member of staff asks, a manager decides.
-- The request table is the team league's, extended to name a ladder challenge and the ladder places concerned instead of a fixture.
ALTER TABLE team_forfeit_requests ALTER COLUMN league_id DROP NOT NULL;
ALTER TABLE team_forfeit_requests ALTER COLUMN fixture_id DROP NOT NULL;
ALTER TABLE team_forfeit_requests ALTER COLUMN forfeit_team DROP NOT NULL;
ALTER TABLE team_forfeit_requests ADD COLUMN IF NOT EXISTS ladder_challenge_id INTEGER REFERENCES ladder_challenges(id) ON DELETE CASCADE;
ALTER TABLE team_forfeit_requests ADD COLUMN IF NOT EXISTS forfeit_player INTEGER REFERENCES ladder_players(id) ON DELETE CASCADE;
ALTER TABLE team_forfeit_requests ADD COLUMN IF NOT EXISTS requested_by_player INTEGER REFERENCES ladder_players(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_forfeit_requests_ladder ON team_forfeit_requests (ladder_challenge_id) WHERE ladder_challenge_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_forfeit_request_open_ladder ON team_forfeit_requests (ladder_challenge_id, requester_key)
  WHERE status = 'open' AND ladder_challenge_id IS NOT NULL;
