-- Signing a member of staff in to the MCP server from an AI provider's
-- connector (claude.ai, ChatGPT, any OAuth-capable MCP client): an OAuth 2.1
-- authorization server inside the app (docs/integrations/mcp.md#signing-in-from-an-ai-assistant,
-- ADR 0030).
--
-- oauth_clients   what a connector registered about itself (RFC 7591): its
--                 own name, shown as an unverified name, and the exact
--                 addresses a sign-in may go back to. Public clients only:
--                 no secret is issued or kept.
-- oauth_codes     a sign-in a member of staff allowed, waiting to be
--                 exchanged once (PKCE S256): only its SHA-256 is kept, with
--                 everything the grant will be bound to.
-- oauth_grants    what a member of staff allowed one client to do: one
--                 venue, the role they had there when they allowed it, and the
--                 scopes they ticked. Re-checked on every call against their
--                 staff record as it is then; it ends when they revoke it, a
--                 manager of the venue does, the account is removed, loses
--                 the venue or its role there drops, or a refresh token is
--                 used twice.
-- oauth_tokens    access tokens (an hour) and refresh tokens (30 days,
--                 replaced on every use), each by its SHA-256 only, as API
--                 keys are: a copy of the database gives nobody a token. A
--                 used refresh token is kept until it would have expired, so
--                 a second use is recognised.
-- The only personal data is the link from a grant to the staff account (and
-- the venue's staff activity log entries, as for any staff action); a grant
-- goes with the account.
CREATE TABLE IF NOT EXISTS oauth_clients (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  redirect_uris JSONB NOT NULL,
  client_uri TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  last_used_at TEXT
);

CREATE TABLE IF NOT EXISTS oauth_grants (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id INTEGER NOT NULL REFERENCES oauth_clients(id) ON DELETE CASCADE,
  admin_id INTEGER NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('manager', 'desk')),
  scopes TEXT NOT NULL,
  resource TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  last_used_at TEXT,
  revoked_at TEXT,
  revoked_reason TEXT
);
CREATE INDEX IF NOT EXISTS oauth_grants_admin ON oauth_grants (admin_id);
CREATE INDEX IF NOT EXISTS oauth_grants_venue ON oauth_grants (venue_id);

CREATE TABLE IF NOT EXISTS oauth_codes (
  code_hash TEXT PRIMARY KEY,
  client_id INTEGER NOT NULL REFERENCES oauth_clients(id) ON DELETE CASCADE,
  admin_id INTEGER NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('manager', 'desk')),
  scopes TEXT NOT NULL,
  resource TEXT NOT NULL,
  redirect_uri TEXT NOT NULL,
  code_challenge TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  -- The grant the code was exchanged for: a second exchange ends it.
  grant_id INTEGER REFERENCES oauth_grants(id) ON DELETE CASCADE,
  used_at TEXT
);

CREATE TABLE IF NOT EXISTS oauth_tokens (
  token_hash TEXT PRIMARY KEY,
  grant_id INTEGER NOT NULL REFERENCES oauth_grants(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('access', 'refresh')),
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  expires_at TEXT NOT NULL,
  used_at TEXT
);
CREATE INDEX IF NOT EXISTS oauth_tokens_grant ON oauth_tokens (grant_id);
