-- A membership bought online for somebody: what the customer chose and saw
-- before paying, kept with the payment until the gateway settles it
-- (docs/features/pricing.md#joining-online; lib/membership-purchases.ts).
--
-- Nothing here is a membership. A membership is made only once the money is
-- in (lib/payments.ts settleBill), from this record, its dates worked out
-- then. Until then the purchase is `pending`, and holds the people it names
-- for a short while (`hold_until`): a second purchase naming any of them is
-- refused, or sent back to the same page when it is the same purchase, so
-- nobody pays twice for one person by accident. A payment that fails, or a
-- hold that lapses, `released`: it holds nobody, and money that still comes
-- in later makes the membership where it can, or is owed back. Settled, it
-- is `made` (the membership it made) or `owed_back` (paid for something it
-- could not give, and why).

CREATE TABLE IF NOT EXISTS membership_purchases (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- The page it is paid on; NULL only while that page is being opened.
  payment_id INTEGER UNIQUE REFERENCES online_payments(id) ON DELETE CASCADE,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  plan_id INTEGER REFERENCES membership_plans(id) ON DELETE SET NULL,
  -- Who bought it: the guardian's account.
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  -- Whose it is: the account holder themself, or a participant they act for.
  holder_kind TEXT NOT NULL CHECK (holder_kind IN ('customer', 'participant')),
  holder_participant_id INTEGER REFERENCES participants(id) ON DELETE SET NULL,
  -- Shown before paying; the membership's own dates are worked out when it is paid.
  quoted_starts_on TEXT NOT NULL,
  quoted_expires_on TEXT NOT NULL,
  price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
  auto_renew BOOLEAN NOT NULL DEFAULT false,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'made', 'released', 'owed_back')),
  why TEXT,
  membership_id INTEGER REFERENCES memberships(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  hold_until TIMESTAMPTZ NOT NULL,
  settled_at TIMESTAMPTZ,
  CHECK (holder_kind = 'participant' OR holder_participant_id IS NULL)
);
CREATE INDEX IF NOT EXISTS idx_membership_purchases_pending ON membership_purchases (hold_until) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS idx_membership_purchases_user ON membership_purchases (user_id);
CREATE INDEX IF NOT EXISTS idx_membership_purchases_holder ON membership_purchases (holder_participant_id) WHERE holder_participant_id IS NOT NULL;

-- The dependants a family purchase names, as chosen.
CREATE TABLE IF NOT EXISTS membership_purchase_participants (
  purchase_id INTEGER NOT NULL REFERENCES membership_purchases(id) ON DELETE CASCADE,
  participant_id INTEGER NOT NULL REFERENCES participants(id) ON DELETE CASCADE,
  PRIMARY KEY (purchase_id, participant_id)
);
CREATE INDEX IF NOT EXISTS idx_membership_purchase_participants_participant ON membership_purchase_participants (participant_id);
