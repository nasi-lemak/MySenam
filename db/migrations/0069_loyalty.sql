-- A free hour for regulars: every `loyalty_every` paid hours played at a
-- venue earns its player one hour free, as a one-entry pass. NULL: off.
ALTER TABLE venues ADD COLUMN IF NOT EXISTS loyalty_every INTEGER;

-- Each free hour given, so none is given twice and the hours it paid for do
-- not count towards the next.
CREATE TABLE IF NOT EXISTS loyalty_rewards (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  phone_key TEXT NOT NULL,
  pass_id INTEGER REFERENCES passes(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS loyalty_rewards_venue_phone ON loyalty_rewards (venue_id, phone_key);
