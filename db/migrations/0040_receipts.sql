-- Receipts for what is sold besides court time — memberships, passes,
-- credit, tournament entries, league fees, shares of a game — and credit
-- notes when a sale is reversed. A booking's own receipt is drawn from the
-- booking (migration 0036); its credit note is stored here.
--
-- Each is a document written once, at the moment of sale, with its own
-- serial number per venue (tax invoices need one) and the tax as it was
-- then. `source` says what it is for ('membership:12', 'payment:40',
-- 'credit:7', 'booking:93'), unique so a sale is receipted once.
CREATE TABLE IF NOT EXISTS receipts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- NULL: the install's own, for credit spendable at any of its venues.
  venue_id INTEGER REFERENCES venues(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('receipt', 'credit_note')),
  seq INTEGER NOT NULL,
  number TEXT NOT NULL,
  source TEXT NOT NULL UNIQUE,
  -- A credit note: the receipt it reverses, and how that is printed.
  credits_id INTEGER REFERENCES receipts(id),
  credits_ref TEXT,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  customer_name TEXT NOT NULL,
  customer_phone TEXT,
  -- [{ "description": "...", "amount": 12.5 }]
  lines TEXT NOT NULL,
  total NUMERIC(12,2) NOT NULL,
  tax_name TEXT,
  tax_rate NUMERIC(5,2),
  tax_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  tax_reg_no TEXT,
  paid_via TEXT,
  note TEXT,
  issued_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE UNIQUE INDEX IF NOT EXISTS receipts_serial ON receipts ((COALESCE(venue_id, 0)), kind, seq);
CREATE INDEX IF NOT EXISTS receipts_user ON receipts (user_id);
CREATE INDEX IF NOT EXISTS receipts_venue_issued ON receipts (venue_id, issued_at);
