-- Box leagues run by venues (lib/leagues.ts): seasons of small boxes of
-- players at about the same level, who arrange and book their own matches,
-- report the results, and move up or down a box for the next season.

CREATE TABLE IF NOT EXISTS leagues (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  sport TEXT NOT NULL,
  -- 1 for singles, 2 for doubles pairs.
  team_size INTEGER NOT NULL DEFAULT 1 CHECK (team_size IN (1, 2)),
  level TEXT CHECK (level IN ('beginner', 'intermediate', 'advanced', 'competitive')),
  -- Players a box holds, about.
  box_size INTEGER NOT NULL DEFAULT 4 CHECK (box_size BETWEEN 3 AND 6),
  -- How many go up, and how many down, from each box at the end of a season.
  moves INTEGER NOT NULL DEFAULT 1 CHECK (moves BETWEEN 1 AND 2),
  season_days INTEGER NOT NULL DEFAULT 28 CHECK (season_days BETWEEN 14 AND 62),
  -- Per player (or pair), per season, paid to the venue.
  fee NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (fee >= 0),
  description TEXT,
  status TEXT NOT NULL DEFAULT 'running' CHECK (status IN ('running', 'closed')),
  created_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_leagues_venue ON leagues(venue_id);

CREATE TABLE IF NOT EXISTS league_seasons (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  league_id INTEGER NOT NULL REFERENCES leagues(id) ON DELETE CASCADE,
  number INTEGER NOT NULL,
  -- Planned while it forms; fixed once it starts.
  starts_on TEXT NOT NULL,
  ends_on TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'forming' CHECK (status IN ('forming', 'running', 'finished')),
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  UNIQUE (league_id, number),
  CHECK (ends_on >= starts_on)
);
-- One season at a time that is not over.
CREATE UNIQUE INDEX IF NOT EXISTS uq_league_season_current ON league_seasons(league_id) WHERE status <> 'finished';

-- Who plays in a league, from season to season.
CREATE TABLE IF NOT EXISTS league_players (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  league_id INTEGER NOT NULL REFERENCES leagues(id) ON DELETE CASCADE,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  -- As shown in the boxes: a player's name, or "Lim / Tan" for a pair.
  name TEXT NOT NULL,
  partner_name TEXT,
  -- For a newcomer: the box staff want them to start in. NULL: by level.
  start_box INTEGER CHECK (start_box BETWEEN 1 AND 99),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'left')),
  joined_at TEXT NOT NULL DEFAULT datetime('now'),
  left_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_league_players_league ON league_players(league_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_league_player_user ON league_players(league_id, user_id)
  WHERE user_id IS NOT NULL AND status = 'active';

-- A player's box in one season, and how they finished it.
CREATE TABLE IF NOT EXISTS league_places (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id INTEGER NOT NULL REFERENCES league_seasons(id) ON DELETE CASCADE,
  player_id INTEGER NOT NULL REFERENCES league_players(id) ON DELETE CASCADE,
  -- 1 is the top box.
  box_no INTEGER NOT NULL,
  -- Place in the box when the season ended, and what that meant.
  finish INTEGER,
  move TEXT CHECK (move IN ('up', 'down', 'stay')),
  paid_at TEXT,
  withdrawn_at TEXT,
  UNIQUE (season_id, player_id)
);
CREATE INDEX IF NOT EXISTS idx_league_places_player ON league_places(player_id);

CREATE TABLE IF NOT EXISTS league_matches (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id INTEGER NOT NULL REFERENCES league_seasons(id) ON DELETE CASCADE,
  box_no INTEGER NOT NULL,
  player_a INTEGER NOT NULL REFERENCES league_players(id) ON DELETE CASCADE,
  player_b INTEGER NOT NULL REFERENCES league_players(id) ON DELETE CASCADE,
  score TEXT,
  winner INTEGER REFERENCES league_players(id) ON DELETE SET NULL,
  -- 'reported': one side has said how it went; 'confirmed' once the other
  -- agrees, staff decide, or nobody objects in time. 'disputed': the other
  -- side says otherwise, and staff decide. 'void': not counted.
  status TEXT NOT NULL DEFAULT 'unplayed'
    CHECK (status IN ('unplayed', 'reported', 'confirmed', 'disputed', 'walkover', 'void')),
  reported_by INTEGER REFERENCES league_players(id) ON DELETE SET NULL,
  reported_at TEXT,
  dispute_note TEXT,
  decided_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  updated_at TEXT,
  UNIQUE (season_id, player_a, player_b)
);
CREATE INDEX IF NOT EXISTS idx_league_matches_season ON league_matches(season_id);
CREATE INDEX IF NOT EXISTS idx_league_matches_reported ON league_matches(status, reported_at);

-- A season's fee paid online, to the venue.
ALTER TABLE online_payments DROP CONSTRAINT IF EXISTS online_payments_purpose_check;
ALTER TABLE online_payments ADD CONSTRAINT online_payments_purpose_check
  CHECK (purpose IN ('booking', 'invoice', 'share', 'entry', 'league'));
ALTER TABLE online_payments ADD COLUMN IF NOT EXISTS league_place_id INTEGER
  REFERENCES league_places(id) ON DELETE SET NULL;
