-- Tournament day (docs/features/tournaments.md#tournament-day; lib/tournament-day.ts): the next match announced to
-- the entrants it is for, a court called when it is free, a no-show timer, and a public live page.
--
-- Settings of a tournament (a division is a tournament, so each division has its own), changeable by a manager at any
-- time before it finishes:
-- * min_rest_minutes: how long somebody rests after a match they played before they are called to another (0: none).
-- * call_wait_minutes: how long a called fixture waits for its players before the organiser decides (wait, forfeit,
--   or swap in the next ready fixture).
-- * announce_next: whether entrants are told when their match is next and when it is called.
-- * live_names: what the public live page shows of a name: 'full', or 'short' (first name and the initial of the
--   rest). A declared minor is shown short whatever this says.
ALTER TABLE tournaments ADD COLUMN IF NOT EXISTS min_rest_minutes INTEGER NOT NULL DEFAULT 0 CHECK (min_rest_minutes BETWEEN 0 AND 240);
ALTER TABLE tournaments ADD COLUMN IF NOT EXISTS call_wait_minutes INTEGER NOT NULL DEFAULT 10 CHECK (call_wait_minutes BETWEEN 1 AND 60);
ALTER TABLE tournaments ADD COLUMN IF NOT EXISTS announce_next BOOLEAN NOT NULL DEFAULT true;
ALTER TABLE tournaments ADD COLUMN IF NOT EXISTS live_names TEXT NOT NULL DEFAULT 'full' CHECK (live_names IN ('full', 'short'));

-- A fixture's day-of state. Called: the players are told to come to the court (the court is held for it through the
-- tournament's blocks, which are claims); started: the players are on court, which stops the no-show timer; the timer
-- is call_due_at, moved on by "wait". call_count counts calls, so a fixture called again after a swap announces
-- again. decided_at: when its result went in, for the rest time between a player's matches. Called and started are
-- cleared when a result goes in.
ALTER TABLE tournament_matches ADD COLUMN IF NOT EXISTS called_at TIMESTAMPTZ;
ALTER TABLE tournament_matches ADD COLUMN IF NOT EXISTS call_due_at TIMESTAMPTZ;
ALTER TABLE tournament_matches ADD COLUMN IF NOT EXISTS called_by TEXT;
ALTER TABLE tournament_matches ADD COLUMN IF NOT EXISTS started_at TIMESTAMPTZ;
ALTER TABLE tournament_matches ADD COLUMN IF NOT EXISTS call_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE tournament_matches ADD COLUMN IF NOT EXISTS decided_at TIMESTAMPTZ;
CREATE INDEX IF NOT EXISTS idx_tournament_matches_called ON tournament_matches (tournament_id) WHERE called_at IS NOT NULL;

-- Who was told what, once: 'next' (your match is next on its court), 'called' (go to the court), per fixture, per
-- side, and per call (seq is the fixture's call_count for 'called', 0 for 'next'). A result entered twice, a retry or
-- the scheduler running on two servers announces once; the outbox's own dedupe key is a second guard.
CREATE TABLE IF NOT EXISTS tournament_notices (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournament_id INTEGER NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
  match_id INTEGER NOT NULL REFERENCES tournament_matches(id) ON DELETE CASCADE,
  entry_id INTEGER NOT NULL REFERENCES tournament_entries(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('next', 'called')),
  seq INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (match_id, entry_id, kind, seq)
);
CREATE INDEX IF NOT EXISTS idx_tournament_notices_t ON tournament_notices (tournament_id);
