-- Branch staff are a manager or front desk. Existing accounts stay managers,
-- so nobody loses anything they could do; new ones are chosen when added.
-- Business managers and platform owners are managers by what they are.
ALTER TABLE admins ADD COLUMN IF NOT EXISTS role TEXT NOT NULL DEFAULT 'manager'
  CHECK (role IN ('manager', 'desk'));

-- Who did what, at which venue, to which booking: payments, cancellations,
-- moves, prices, refunds, voids, credit, settings, staff. The name is kept
-- with the entry, so it reads right after the account is removed.
CREATE TABLE IF NOT EXISTS staff_actions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  admin_name TEXT NOT NULL,
  venue_id INTEGER REFERENCES venues(id) ON DELETE CASCADE,
  booking_code TEXT,
  action TEXT NOT NULL,
  detail TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_staff_actions_venue ON staff_actions (venue_id, created_at);
CREATE INDEX IF NOT EXISTS idx_staff_actions_booking ON staff_actions (booking_code) WHERE booking_code IS NOT NULL;
