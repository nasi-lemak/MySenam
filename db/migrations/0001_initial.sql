-- The whole schema, as it stood when MySenam moved from SQLite to Postgres.
--
-- Migrations are applied in filename order, once each, and recorded in
-- schema_migrations. Never edit one that has been applied anywhere: add the
-- next number instead.
--
-- Conventions carried over from SQLite, on purpose:
--   * Timestamps are TEXT, 'YYYY-MM-DD HH:MM:SS' in UTC, written by datetime()
--     below. Every comparison in the code is between strings of that shape,
--     so keeping it means no query and no screen changes what it reads.
--   * Flags are INTEGER 0/1.
--   * Money is NUMERIC(12,2): ringgit, exact to the sen. SQLite let a
--     fraction into an INTEGER column without a word; Postgres would refuse it.

CREATE EXTENSION IF NOT EXISTS citext;

-- SQLite's datetime('now'[, '+5 minutes']), so the queries keep their shape.
CREATE OR REPLACE FUNCTION datetime(base text, modifier text DEFAULT NULL)
RETURNS text LANGUAGE sql STABLE AS $$
  SELECT to_char(
    (CASE WHEN lower(base) = 'now' THEN now() AT TIME ZONE 'utc' ELSE base::timestamp END)
      + COALESCE(modifier::interval, interval '0'),
    'YYYY-MM-DD HH24:MI:SS')
$$;

CREATE TABLE venues (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  area TEXT NOT NULL,
  address TEXT NOT NULL,
  phone TEXT NOT NULL,
  -- Customers may cancel until this many hours before start.
  cancel_cutoff_hours INTEGER NOT NULL DEFAULT 2,
  -- Trading hours: the first bookable hour starts at open_hour, the last ends
  -- at close_hour.
  open_hour INTEGER NOT NULL DEFAULT 8,
  close_hour INTEGER NOT NULL DEFAULT 23,
  -- When somebody is behind the counter. NULL for both: always staffed.
  -- Equal values: never staffed.
  staffed_from INTEGER,
  staffed_to INTEGER,
  -- Shown to anyone letting themselves in.
  emergency_phone TEXT,
  emergency_info TEXT,
  -- On a marketplace: what the venue pays a month (NULL: the default), and
  -- from when (NULL: not billed).
  monthly_fee NUMERIC(12,2),
  billing_starts_on TEXT
);

CREATE TABLE courts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id),
  name TEXT NOT NULL,
  -- Validated in lib/types.ts, so the vocabulary can grow without a migration.
  sport TEXT NOT NULL,
  off_peak_rate NUMERIC(12,2) NOT NULL,
  peak_rate NUMERIC(12,2) NOT NULL,
  -- What a member pays instead. NULL: members pay the public rate here.
  member_off_peak_rate NUMERIC(12,2),
  member_peak_rate NUMERIC(12,2),
  capacity INTEGER NOT NULL DEFAULT 1,
  -- Held while the kit is out. 0: nothing is handed over.
  deposit NUMERIC(12,2) NOT NULL DEFAULT 0,
  -- Nobody at the door: customers let themselves in with a code.
  unmanned INTEGER NOT NULL DEFAULT 0,
  -- What is set on that door. The lock is the source of truth.
  access_code TEXT,
  access_code_changed_at TEXT
);

CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email CITEXT NOT NULL UNIQUE,
  phone TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);

CREATE TABLE sessions (
  token TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TEXT NOT NULL
);

-- Venue operators. venue_id NULL: a platform owner who sees every venue.
CREATE TABLE admins (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email CITEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  venue_id INTEGER REFERENCES venues(id),
  created_at TEXT NOT NULL DEFAULT datetime('now')
);

CREATE TABLE admin_sessions (
  token TEXT PRIMARY KEY,
  admin_id INTEGER NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
  expires_at TEXT NOT NULL
);

-- An instructor-led session held on a resource.
CREATE TABLE classes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  court_id INTEGER NOT NULL REFERENCES courts(id),
  name TEXT NOT NULL,
  instructor TEXT NOT NULL,
  date TEXT NOT NULL,
  start_hour INTEGER NOT NULL,
  end_hour INTEGER NOT NULL,
  capacity INTEGER NOT NULL,
  price NUMERIC(12,2) NOT NULL,
  status TEXT NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled','cancelled')),
  series_code TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);

CREATE TABLE bookings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  court_id INTEGER NOT NULL REFERENCES courts(id),
  date TEXT NOT NULL,
  start_hour INTEGER NOT NULL,
  end_hour INTEGER NOT NULL,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  email TEXT,
  total_price NUMERIC(12,2) NOT NULL,
  status TEXT NOT NULL DEFAULT 'confirmed' CHECK (status IN ('confirmed','cancelled')),
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  check_in_token TEXT,
  -- 1 if the demo seeder invented it, which is what lets the demo be reloaded
  -- and stops that ever happening once a real customer has booked.
  demo INTEGER NOT NULL DEFAULT 0,
  user_id INTEGER REFERENCES users(id),
  series_code TEXT,
  class_id INTEGER REFERENCES classes(id),
  no_show INTEGER NOT NULL DEFAULT 0,
  payment_status TEXT NOT NULL DEFAULT 'unpaid' CHECK (payment_status IN ('unpaid','paid')),
  paid_at TEXT,
  -- 'online' for the venue's gateway; NULL for the counter, credit or a pass.
  paid_via TEXT
);

-- One row per booked hour per place taken. The UNIQUE constraint is what
-- makes a double booking impossible, whatever the code above it does.
CREATE TABLE booking_slots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  court_id INTEGER NOT NULL REFERENCES courts(id),
  date TEXT NOT NULL,
  hour INTEGER NOT NULL,
  seat INTEGER NOT NULL DEFAULT 0,
  UNIQUE (court_id, date, hour, seat)
);

CREATE TABLE check_ins (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL UNIQUE REFERENCES bookings(id) ON DELETE CASCADE,
  checked_in_at TEXT NOT NULL DEFAULT datetime('now'),
  checked_out_at TEXT
);

CREATE TABLE access_reveals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  revealed_at TEXT NOT NULL DEFAULT datetime('now')
);

CREATE TABLE hire_records (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL UNIQUE REFERENCES bookings(id) ON DELETE CASCADE,
  deposit NUMERIC(12,2) NOT NULL CHECK (deposit >= 0),
  taken_at TEXT NOT NULL DEFAULT datetime('now'),
  returned_at TEXT,
  -- Kept back out of the deposit. NULL until the kit comes back.
  withheld NUMERIC(12,2) CHECK (withheld IS NULL OR withheld >= 0),
  condition TEXT CHECK (condition IS NULL OR condition IN ('ok','damaged','lost')),
  note TEXT
);

CREATE TABLE inductions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  -- Normalised, so the country code cannot split one person in two.
  phone TEXT NOT NULL,
  name TEXT NOT NULL,
  admin_id INTEGER REFERENCES admins(id),
  note TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  revoked_at TEXT,
  UNIQUE (venue_id, phone)
);

CREATE TABLE memberships (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  holder_name TEXT NOT NULL,
  holder_phone TEXT NOT NULL,
  user_id INTEGER REFERENCES users(id),
  -- Inclusive: live on both of these dates.
  starts_on TEXT NOT NULL,
  expires_on TEXT NOT NULL,
  price NUMERIC(12,2) NOT NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','void')),
  admin_id INTEGER REFERENCES admins(id),
  created_at TEXT NOT NULL DEFAULT datetime('now')
);

CREATE TABLE passes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  -- NULL: good for any sport at that venue.
  sport TEXT,
  name TEXT NOT NULL,
  entries INTEGER NOT NULL,
  price NUMERIC(12,2) NOT NULL,
  holder_name TEXT NOT NULL,
  holder_phone TEXT NOT NULL,
  user_id INTEGER REFERENCES users(id),
  -- Inclusive: still good on this date.
  expires_on TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','void')),
  admin_id INTEGER REFERENCES admins(id),
  created_at TEXT NOT NULL DEFAULT datetime('now')
);

-- Append-only, like wallet_entries: remaining = entries + SUM(delta).
CREATE TABLE pass_entries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pass_id INTEGER NOT NULL REFERENCES passes(id) ON DELETE CASCADE,
  delta INTEGER NOT NULL,
  reason TEXT NOT NULL,
  booking_id INTEGER REFERENCES bookings(id),
  created_at TEXT NOT NULL DEFAULT datetime('now')
);

CREATE TABLE promo_codes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  -- NULL: any sport at that venue.
  sport TEXT,
  description TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('percent','amount')),
  -- Percent 1-100, or whole ringgit off.
  value INTEGER NOT NULL,
  min_hours INTEGER NOT NULL DEFAULT 1,
  -- Inclusive dates the booking itself must fall within.
  valid_from TEXT NOT NULL,
  valid_to TEXT NOT NULL,
  -- NULL: unlimited.
  max_uses INTEGER,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','void')),
  admin_id INTEGER REFERENCES admins(id),
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  UNIQUE (venue_id, code)
);

CREATE TABLE promo_uses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  promo_id INTEGER NOT NULL REFERENCES promo_codes(id) ON DELETE CASCADE,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  discount NUMERIC(12,2) NOT NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  UNIQUE (booking_id)
);

-- Stored credit: an append-only ledger whose sum is the balance.
CREATE TABLE wallet_entries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  amount NUMERIC(12,2) NOT NULL,
  reason TEXT NOT NULL,
  booking_id INTEGER REFERENCES bookings(id),
  admin_id INTEGER REFERENCES admins(id),
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  -- Whose credit, where credit is per venue. NULL: spendable anywhere.
  venue_id INTEGER REFERENCES venues(id)
);

CREATE TABLE slot_blocks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  court_id INTEGER NOT NULL REFERENCES courts(id),
  date TEXT NOT NULL,
  hour INTEGER NOT NULL,
  reason TEXT,
  -- Places out of service. NULL: the whole resource.
  places INTEGER,
  UNIQUE (court_id, date, hour)
);

CREATE TABLE venue_closures (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  date TEXT NOT NULL,
  reason TEXT,
  UNIQUE (venue_id, date)
);

CREATE TABLE waitlist (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id INTEGER REFERENCES classes(id) ON DELETE CASCADE,
  court_id INTEGER REFERENCES courts(id),
  date TEXT,
  start_hour INTEGER,
  end_hour INTEGER,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  email TEXT,
  user_id INTEGER REFERENCES users(id),
  status TEXT NOT NULL DEFAULT 'waiting'
    CHECK (status IN ('waiting','offered','claimed','expired','cancelled')),
  offered_at TEXT,
  offer_token TEXT UNIQUE,
  -- The language they joined in, so the offer reaches them in it.
  locale TEXT NOT NULL DEFAULT 'en',
  created_at TEXT NOT NULL DEFAULT datetime('now')
);

-- Messages to customers, written down before they are sent.
CREATE TABLE messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER REFERENCES bookings(id) ON DELETE SET NULL,
  venue_id INTEGER NOT NULL REFERENCES venues(id),
  kind TEXT NOT NULL,
  channel TEXT NOT NULL CHECK (channel IN ('whatsapp','email')),
  recipient TEXT NOT NULL,
  locale TEXT NOT NULL DEFAULT 'en',
  subject TEXT,
  body TEXT NOT NULL,
  -- What filled the body, as JSON: WhatsApp sends these as parameters.
  params TEXT,
  status TEXT NOT NULL DEFAULT 'queued'
    CHECK (status IN ('queued','sent','failed','abandoned')),
  attempts INTEGER NOT NULL DEFAULT 0,
  last_error TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  next_attempt_at TEXT NOT NULL DEFAULT datetime('now'),
  sent_at TEXT,
  -- What it is about, when saying it twice would be wrong.
  dedupe_key TEXT UNIQUE
);

CREATE TABLE settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- A venue's own payment gateway account. The keys are sealed (lib/secrets.ts).
CREATE TABLE venue_payment_accounts (
  venue_id INTEGER PRIMARY KEY REFERENCES venues(id),
  provider TEXT NOT NULL DEFAULT 'billplz' CHECK (provider IN ('billplz')),
  api_key TEXT NOT NULL,
  collection_id TEXT NOT NULL,
  x_signature_key TEXT NOT NULL,
  sandbox INTEGER NOT NULL DEFAULT 0,
  enabled INTEGER NOT NULL DEFAULT 1,
  updated_at TEXT NOT NULL DEFAULT datetime('now')
);

-- A marketplace venue's monthly fee, one row per venue per month.
CREATE TABLE venue_invoices (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id),
  period TEXT NOT NULL,
  amount NUMERIC(12,2) NOT NULL,
  status TEXT NOT NULL DEFAULT 'due' CHECK (status IN ('due','paid','void')),
  issued_on TEXT NOT NULL,
  due_on TEXT NOT NULL,
  paid_at TEXT,
  paid_via TEXT CHECK (paid_via IN ('online','manual')),
  UNIQUE (venue_id, period)
);

-- One bill somebody was sent to pay: a customer for bookings (into the
-- venue's account) or a venue for its invoice (into the platform's).
CREATE TABLE online_payments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider TEXT NOT NULL,
  bill_id TEXT NOT NULL UNIQUE,
  url TEXT NOT NULL,
  venue_id INTEGER REFERENCES venues(id),
  amount NUMERIC(12,2) NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','paid')),
  payer_name TEXT,
  payer_phone TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  paid_at TEXT,
  -- Owed back for bookings cancelled after paying, and refunded since.
  refund_due NUMERIC(12,2) NOT NULL DEFAULT 0,
  refunded NUMERIC(12,2) NOT NULL DEFAULT 0,
  purpose TEXT NOT NULL DEFAULT 'booking' CHECK (purpose IN ('booking','invoice')),
  invoice_id INTEGER REFERENCES venue_invoices(id)
);

CREATE TABLE online_payment_bookings (
  payment_id INTEGER NOT NULL REFERENCES online_payments(id) ON DELETE CASCADE,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  PRIMARY KEY (payment_id, booking_id)
);

-- Venues asking to join a marketplace. The password their operator chose is
-- held hashed until decided, and dropped if turned down.
CREATE TABLE venue_applications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_name TEXT NOT NULL,
  area TEXT NOT NULL,
  address TEXT NOT NULL,
  venue_phone TEXT NOT NULL,
  contact_name TEXT NOT NULL,
  email CITEXT NOT NULL,
  password_hash TEXT NOT NULL,
  message TEXT,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  reason TEXT,
  venue_id INTEGER REFERENCES venues(id),
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  decided_at TEXT,
  decided_by INTEGER REFERENCES admins(id)
);

-- A venue's own website on the marketplace (lib/storefront.ts).
CREATE TABLE storefronts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hostname TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  tagline TEXT,
  accent_color TEXT,
  logo_url TEXT,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);

CREATE TABLE storefront_venues (
  storefront_id INTEGER NOT NULL REFERENCES storefronts(id) ON DELETE CASCADE,
  venue_id INTEGER NOT NULL REFERENCES venues(id),
  PRIMARY KEY (storefront_id, venue_id)
);

