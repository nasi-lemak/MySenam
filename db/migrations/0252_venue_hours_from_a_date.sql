-- Opening hours from a date (audit R8 X1-13; ADR 0027;
-- docs/features/booking.md#hours-from-a-date). A venue's own columns
-- (open_min, close_min, week_hours) stay the hours in force today; hours set
-- to apply from a later date wait here, each a whole set (the usual hours and
-- the week), and the date asked about decides which applies. When a change's
-- date comes it is in force by that rule alone; the app makes it the current
-- settings the next time staff look at or change the hours
-- (lib/dated-changes.ts), and nothing stored about bookings changes.
CREATE TABLE IF NOT EXISTS venue_hours_changes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  from_date TEXT NOT NULL CHECK (from_date ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'),
  open_min INTEGER NOT NULL CHECK (open_min >= 0 AND open_min < 1440),
  close_min INTEGER NOT NULL CHECK (close_min <= 1680 AND close_min - open_min >= 60),
  week_hours TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (venue_id, from_date)
);

-- The list on the venue row too, kept by the database, so everything that
-- reads a venue's hours has it: JSON [{id, from, openMin, closeMin, weekHours}], soonest first.
ALTER TABLE venues ADD COLUMN IF NOT EXISTS hours_changes TEXT NOT NULL DEFAULT '[]';
CREATE OR REPLACE FUNCTION venue_hours_changes_list(venue INTEGER) RETURNS TEXT LANGUAGE sql STABLE AS $$
  SELECT COALESCE(json_agg(json_build_object('id', h.id, 'from', h.from_date, 'openMin', h.open_min, 'closeMin', h.close_min,
                                             'weekHours', CASE WHEN h.week_hours IS NULL THEN NULL ELSE h.week_hours::json END)
                           ORDER BY h.from_date)::text, '[]')
    FROM venue_hours_changes h
   WHERE h.venue_id = venue
$$;
CREATE OR REPLACE FUNCTION venue_hours_changes_changed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP <> 'INSERT' THEN
    UPDATE venues SET hours_changes = venue_hours_changes_list(OLD.venue_id) WHERE id = OLD.venue_id;
  END IF;
  IF TG_OP <> 'DELETE' THEN
    UPDATE venues SET hours_changes = venue_hours_changes_list(NEW.venue_id) WHERE id = NEW.venue_id;
  END IF;
  RETURN NULL;
END
$$;
DROP TRIGGER IF EXISTS venue_hours_changes_list ON venue_hours_changes;
CREATE TRIGGER venue_hours_changes_list AFTER INSERT OR UPDATE OR DELETE ON venue_hours_changes
  FOR EACH ROW EXECUTE FUNCTION venue_hours_changes_changed();
