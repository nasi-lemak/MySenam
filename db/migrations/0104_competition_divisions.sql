-- Competitions with divisions (lib/competitions.ts, ADR 0013): one event at a
-- venue holds the courts and hours; each division is a tournament of its own
-- (format, rules, entries, draw) scheduled into that shared time.
CREATE TABLE IF NOT EXISTS competitions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venue_id INTEGER NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  sport TEXT NOT NULL,
  starts_on TEXT NOT NULL,
  ends_on TEXT NOT NULL,
  start_min INTEGER NOT NULL,
  end_min INTEGER NOT NULL,
  -- Every division's matches are this long, so they share the same slots.
  match_minutes INTEGER NOT NULL,
  -- How many of its divisions one player may enter; null for no limit.
  max_divisions_per_player INTEGER CHECK (max_divisions_per_player BETWEEN 1 AND 20),
  description TEXT,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'cancelled')),
  created_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  CHECK (ends_on >= starts_on),
  CHECK (end_min > start_min)
);
CREATE INDEX IF NOT EXISTS idx_competitions_venue ON competitions(venue_id);

CREATE TABLE IF NOT EXISTS competition_courts (
  competition_id INTEGER NOT NULL REFERENCES competitions(id) ON DELETE CASCADE,
  court_id INTEGER NOT NULL REFERENCES courts(id) ON DELETE CASCADE,
  PRIMARY KEY (competition_id, court_id)
);

ALTER TABLE tournaments ADD COLUMN IF NOT EXISTS competition_id INTEGER REFERENCES competitions(id) ON DELETE CASCADE;
CREATE INDEX IF NOT EXISTS idx_tournaments_competition ON tournaments(competition_id) WHERE competition_id IS NOT NULL;
-- A competition's hold belongs to it, not to one division.
ALTER TABLE blocks ADD COLUMN IF NOT EXISTS competition_id INTEGER REFERENCES competitions(id) ON DELETE CASCADE;
CREATE INDEX IF NOT EXISTS idx_blocks_competition ON blocks(competition_id) WHERE competition_id IS NOT NULL;

