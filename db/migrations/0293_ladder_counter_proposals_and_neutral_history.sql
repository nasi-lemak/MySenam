-- The owner's decisions of 5 November 2026, third round on ladder court time
-- (docs/architecture/decisions/0051-a-counter-proposal-is-an-agreement-and-expired-holds-are-no-ones-fault.md, which amends ADR 0050;
-- docs/features/tournaments.md#court-time-held-by-the-venue-an-optional-setting-per-ladder; lib/ladder-holds.ts, lib/ladders.ts):
--   1. a counter-proposal is the counter-proposer's recorded agreement to that exact specification and reserves nothing; the other player's explicit acceptance of
--      exactly it makes the hold; every proposal has a revision, an act answers the revision it saw, and a superseded proposal can never be accepted;
--   2. nobody is blamed for an expired or unanswered hold: a neutral record of who proposed, countered, accepted, withdrew, cancelled or did not answer, and the only
--      anti-abuse signal is a player's own cancellations of holds that really reserved court capacity.
-- Everything is additive. Nothing is deleted or rewritten: the abandonment columns of migration 0292 stay as history and nothing reads them for a limit.

-- ---------------------------------------------------------------- revisions of a proposal

-- The revision of the challenge's proposal (the day and time asked, or the move asked): 1 for every challenge already in flow, so each keeps the proposal it has;
-- it goes up whenever the proposal changes or ends. An act answers the revision it saw (`rev`), and one for a revision that is no longer current is refused.
ALTER TABLE ladder_challenges ADD COLUMN IF NOT EXISTS proposal_rev INTEGER NOT NULL DEFAULT 1;
-- A request to move an accepted challenge's time lapses like a challenge's own response window: the last day it can be answered.
ALTER TABLE ladder_challenges ADD COLUMN IF NOT EXISTS move_respond_by TEXT;

-- ---------------------------------------------------------------- what each player agreed, before any hold exists

-- A counter-proposal is its maker's agreement to that exact specification, recorded when it is made, with no hold behind it (`held_id` empty until the other player
-- accepts it and the hold is made). `rev` is the revision of the proposal it agreed; `superseded_at` says a later revision replaced the specification, so the agreement
-- is kept as history and never counts toward a hold.
ALTER TABLE ladder_agreed_times ALTER COLUMN held_id DROP NOT NULL;
ALTER TABLE ladder_agreed_times ADD COLUMN IF NOT EXISTS rev INTEGER;
ALTER TABLE ladder_agreed_times ADD COLUMN IF NOT EXISTS superseded_at TIMESTAMPTZ;
ALTER TABLE ladder_agreed_times ADD COLUMN IF NOT EXISTS superseded_reason TEXT;
ALTER TABLE ladder_agreed_times DROP CONSTRAINT IF EXISTS ladder_agreed_times_role_check;
ALTER TABLE ladder_agreed_times ADD CONSTRAINT ladder_agreed_times_role_check CHECK (role IN ('proposed', 'accepted', 'countered'));
CREATE INDEX IF NOT EXISTS idx_ladder_agreed_times_open ON ladder_agreed_times (challenge_id, rev) WHERE held_id IS NULL AND superseded_at IS NULL;

-- ---------------------------------------------------------------- the neutral record

-- One row per thing that happened to a proposal or a hold, said as it happened and attributing nothing: `kind` is proposed, countered, accepted, held, moved,
-- withdrawn (a proposal or request taken back by the one who made it), cancelled (a hold its player cancelled), released (by the venue or the system),
-- declined, superseded, no_response (nobody answered in time: no fault, no counter, no label), or pause_lifted (a manager lifted a pause on creating holds).
-- `place_id` is the player who acted (empty for the venue or the system); `reserved_capacity` says whether court capacity was ever reserved by it: a proposal or a
-- counter-proposal never reserves a court, only a hold does. Staff see it; players and the public never do.
CREATE TABLE IF NOT EXISTS ladder_hold_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ladder_id INTEGER NOT NULL REFERENCES ladders(id) ON DELETE CASCADE,
  challenge_id INTEGER REFERENCES ladder_challenges(id) ON DELETE CASCADE,
  place_id INTEGER,
  by_name TEXT,
  kind TEXT NOT NULL,
  rev INTEGER,
  date TEXT,
  start_min INTEGER,
  minutes INTEGER,
  court_id INTEGER,
  reserved_capacity BOOLEAN NOT NULL DEFAULT false,
  note TEXT,
  at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_ladder_hold_events_challenge ON ladder_hold_events (challenge_id, id);
CREATE INDEX IF NOT EXISTS idx_ladder_hold_events_place ON ladder_hold_events (place_id, kind, at) WHERE place_id IS NOT NULL;

-- ---------------------------------------------------------------- the one anti-abuse signal

-- A player's own cancellation of a hold that really reserved court capacity (a hold row exists only when its claims did): who, and when. It is the only thing the
-- anti-abuse count reads. An expiry, a non-response, a decline, a release by the venue or the system, and a proposal that never reserved capacity are never in it.
ALTER TABLE ladder_court_holds ADD COLUMN IF NOT EXISTS cancelled_place INTEGER;
ALTER TABLE ladder_court_holds ADD COLUMN IF NOT EXISTS cancelled_at TIMESTAMPTZ;
CREATE INDEX IF NOT EXISTS idx_ladder_holds_cancelled ON ladder_court_holds (cancelled_place, cancelled_at) WHERE cancelled_at IS NOT NULL;
-- What migration 0292 recorded as abandoned by withdrawing is exactly a player's own cancellation of a hold that reserved capacity: carried over as history (once; a
-- second run changes nothing). What it recorded for an expiry is not, and is left where it was, unread.
UPDATE ladder_court_holds SET cancelled_place = abandoned_place, cancelled_at = abandoned_at
 WHERE cancelled_place IS NULL AND released_reason = 'withdrawn' AND abandoned_place IS NOT NULL AND abandoned_at IS NOT NULL;
